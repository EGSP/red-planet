/// <summary>
/// Занимает в мире прямоугольную площадь.
///
/// ПОЧЕМУ ОТДЕЛЬНО ОТ <see cref="IObstacle"/>. Форма и непроходимость — разные свойства,
/// и совпадают они не у всех: план стройки площадь за собой держит, но пройти сквозь него
/// можно, и в карту препятствий он не попадает. Пока форма объявлялась вместе
/// с непроходимостью, всё, что читает форму, вынуждено было спрашивать её у препятствия,
/// а плану оставалось только собственное свойство того же имени, никому не видное.
///
/// Форму читают расчёт досягаемости (<see cref="Reach"/>), постановка
/// (<see cref="Placement"/>) и наведение курсора; непроходимость — карта препятствий
/// и растр навигации.
///
/// Прямоугольник ориентированный и считается от позиции, размера определения и угла
/// ПОСТАНОВКИ, а НЕ от поворота ноды. У турели в Rotation живёт ось башни, корпус при этом
/// не шевелится, и занимаемая площадь от вращения башни зависеть не должна.
/// </summary>
public interface IFootprint
{
    /// <summary>Занимаемый прямоугольник в мировых координатах.</summary>
    Obb Footprint { get; }
}
