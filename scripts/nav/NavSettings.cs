using Godot;

/// <summary>
/// Настройка навигации: порог клиренса и связанные величины, которые подбираются по ходу
/// игры, а не выводятся из правил растра.
///
/// ПОЧЕМУ РЕСУРС. <see cref="NavGrid"/> считает поле расстояний из геометрии зданий;
/// требование к проходимости — отдельный рычаг: насколько строго радиус юнита сравнивается
/// с этим полем. Его правят в инспекторе рядом с остальным тюнингом
/// (<c>resources/tuning/nav.tres</c>), а не в коде чемфера.
/// </summary>
[Tool]
[GlobalClass]
public partial class NavSettings : Resource
{
    [ExportGroup("Клиренс")]

    /// <summary>
    /// Множитель радиуса в формуле <see cref="NavGrid.Required"/>.
    /// Единица — прежнее поведение; меньше единицы — юниты проходят более узкие щели;
    /// больше единицы — требование к коридору жёстче.
    ///
    /// На само поле <c>_distance</c> не влияет: меняется только порог сравнения.
    /// </summary>
    [Export(PropertyHint.Range, "0.1,2,0.01")]
    public float ClearanceFactor = 1f;

    /// <summary>
    /// Верхняя граница сохраняемого chamfer-расстояния, в третях ячейки.
    ///
    /// Благодаря насыщению изменение препятствия влияет только на конечную окрестность,
    /// а не на весь растр. Значение должно быть не меньше <see cref="NavGrid.Required"/>
    /// для самого крупного юнита при текущем <see cref="ClearanceFactor"/>; для радиуса
    /// 0.48 клетки и фактора 1 достаточно 8, запас 12 закрывает более жёсткий тюнинг.
    /// </summary>
    [Export(PropertyHint.Range, "4,64,1")]
    public int MaxClearance = 12;
}
