/// <summary>
/// Занимает место в мире и не пропускает сквозь себя.
///
/// Признак заменил занятость клеток сетки. Разница не в форме записи, а в том, где живёт
/// истина: раньше место принадлежало клеткам, а положение постройки выводилось из них;
/// теперь место принадлежит самой постройке, а растр навигации выводится из него.
///
/// Прямоугольник ориентированный и считается от позиции, размера определения и угла
/// ПОСТАНОВКИ, а НЕ от поворота ноды. У турели в Rotation живёт ось башни, корпус при этом
/// не шевелится, и занимаемая площадь от вращения башни зависеть не должна.
/// </summary>
public interface IObstacle
{
    /// <summary>Занимаемый прямоугольник в мировых координатах.</summary>
    Obb Footprint { get; }
}
