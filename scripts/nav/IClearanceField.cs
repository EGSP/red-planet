/// <summary>
/// Поле chamfer-расстояний, пригодное для чтения отрисовкой.
///
/// ЗАЧЕМ ОТДЕЛЬНЫЙ ИНТЕРФЕЙС. Тень препятствий выводится из расстояний, а расстояния берутся
/// из двух разных мест: в партии — из <see cref="NavGrid"/>, который ведёт фоновый пересчёт
/// и временную маску, а в предпросмотре редактора — из одиночного <see cref="NavSnapshot"/>,
/// собранного тут же и без всякой сессии. Отрисовщику различие безразлично: ему нужны сторона
/// растра, расстояние по номеру ячейки и признак того, что поле изменилось.
/// </summary>
public interface IClearanceField
{
    /// <summary>Ячеек по стороне растра.</summary>
    int Width { get; }

    /// <summary>
    /// Метка состояния. Отрисовка сравнивает её с показанной и пересобирает текстуру,
    /// только когда значения разошлись.
    /// </summary>
    int Revision { get; }

    /// <summary>Chamfer-расстояние до ближайшего препятствия в третях ячейки.</summary>
    int DistanceAt(int index);
}
