using Godot;

/// <summary>
/// Всё, что ходит по миру. Один признак на юнита игрока и на врага: классы у них разные
/// и общего предка нет, а движутся они одинаково.
///
/// Сам по себе признак ничего не двигает — он лишь позволяет <see cref="MovementSystem"/>
/// найти подвижных в индексе и прочитать у них то немногое, что движению нужно.
/// </summary>
public interface IMobile
{
    Vector2 GlobalPosition { get; set; }

    float Rotation { get; set; }

    Movement Movement { get; }

    UnitDefinition Definition { get; }

    Faction Faction { get; }

    /// <summary>Физический радиус: по нему считаются проходимость и расталкивание.</summary>
    float HitRadius { get; }
}

/// <summary>
/// Намерение двигаться и состояние движения.
///
/// ЗАЧЕМ ОТДЕЛЬНО ОТ ПРИКАЗОВ. Раньше сущность двигала себя сама прямо в обработчике
/// приказа вызовом MoveToward. Пока движение размазано по обработчикам, локальный обход
/// подключить некуда: у отдельного обработчика нет ни соседей, ни сил, ни пути. Теперь
/// обработчик приказа объявляет намерение — «дойти вот сюда и остановиться вот на таком
/// расстоянии», — а как именно туда идти, решает одна система на всех.
///
/// Поля с силами нужны только отрисовке отладки. Считать их дешевле, чем заводить
/// отдельный канал для наблюдения, и они же служат единственным окном в то,
/// почему юнит поехал не туда.
/// </summary>
public sealed class Movement
{
    /// <summary>Куда идти. Осмысленно, только пока Active.</summary>
    public Vector2 Goal;

    /// <summary>На каком расстоянии до цели считать, что дошли.</summary>
    public float StopDistance;

    /// <summary>
    /// Приказ требует движения прямо сейчас. Ставится обработчиком приказа каждый кадр,
    /// снимается системой движения в конце её шага: не подтверждённое намерение гаснет само,
    /// и снимать его отдельно никому не нужно.
    /// </summary>
    public bool Active;

    /// <summary>
    /// Стоять и не поддаваться толчкам. Пока приказ не подтверждён, сущность считается
    /// удерживающей позицию: работающий строитель и стреляющая турель не должны
    /// разъезжаться от того, что мимо прошёл отряд.
    /// </summary>
    public bool HoldGround => !Active;

    public Vector2 Velocity;

    /// <summary>Цель в другой связной области: дойти нельзя никаким путём.</summary>
    public bool Blocked;

    /// <summary>
    /// Ближе к цели не подойти. Три причины, и все означают одно и то же для приказа:
    /// дальше идти некуда, ход закончен.
    ///
    /// ПЕРВАЯ — толпа: место у цели занято своими, которые уже встали. Без этого признака
    /// отряд, посланный в одну точку, толчётся бесконечно, потому что попасть в неё всем
    /// сразу нельзя, а каждый по отдельности считает, что ещё не дошёл.
    ///
    /// ВТОРАЯ — цель занята постройкой. Путь ведёт к её краю, а заданная точка лежит
    /// внутри, и без признака юнит упирался бы в стену, считая, что не дошёл.
    ///
    /// ТРЕТЬЯ — цель в другой связной области. Дойти нельзя вовсе.
    ///
    /// Признак вычисляет система движения, читает обработчик приказа: именно ему решать,
    /// что приказ исполнен.
    /// </summary>
    public bool Settled;

    /// <summary>Сколько секунд сущность не продвигается. Ноль означает «идёт нормально».</summary>
    public float StuckFor;

    // ── выезд из корпуса завода ───────────────────────────────────────────────────

    /// <summary>
    /// Завод, из корпуса которого сущность сейчас выезжает. Пока ссылка не null,
    /// сущность игнорирует выталкивание из этого препятствия и движется к ExitPoint
    /// принудительно — без поиска пути и без расталкивания в свою сторону.
    /// </summary>
    public IObstacle Exit;

    /// <summary>Внешняя точка выезда: центр завода плюс направление rolloff.</summary>
    public Vector2 ExitPoint;

    /// <summary>Сколько секунд уже длится выезд.</summary>
    public float ExitFor;

    /// <summary>Юнит ещё внутри корпуса или на отрезке выезда.</summary>
    public bool Leaving => Exit != null;

    /// <summary>Начать выезд. Зовёт завод в момент SpawnUnit.</summary>
    public void BeginExit(IObstacle obstacle, Vector2 point)
    {
        Exit = obstacle;
        ExitPoint = point;
        ExitFor = 0f;
        Settled = false;
    }

    /// <summary>Снять состояние выезда. После этого юнит подчиняется обычным правилам.</summary>
    public void EndExit()
    {
        Exit = null;
        ExitPoint = Vector2.Zero;
        ExitFor = 0f;
    }

    // ── только для отрисовки отладки ──────────────────────────────────────────────

    public Vector2 SeekForce;
    public Vector2 AvoidForce;
    public Vector2 AlignForce;

    /// <summary>Зафиксированная сторона обхода: −1 влево, +1 вправо, 0 — обхода нет.</summary>
    public int AvoidSide;

    /// <summary>Во сколько раз ослаблено стремление к цели правилами «кто кого толкает».</summary>
    public float SeekScale = 1f;

    public int Neighbours;

    /// <summary>Объявить намерение. Зовётся обработчиком приказа каждый кадр движения.</summary>
    public void Seek(Vector2 goal, float stopDistance)
    {
        Goal = goal;
        StopDistance = stopDistance;
        Active = true;
    }
}
