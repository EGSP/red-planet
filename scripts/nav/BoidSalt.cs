using Godot;

/// <summary>
/// Соль локального слоя движения: небольшое постоянное отличие одной сущности от другой
/// той же породы.
///
/// ЗАЧЕМ. Затор, в котором двое не пропускают друг друга, есть следствие симметрии: у обоих
/// одинаковые веса, одинаковые пороги и потому одинаковые решения, а решения эти взаимно
/// противоположны по смыслу. Усиление сил симметрию не нарушает — оно лишь делает упор
/// сильнее. Нарушает её различие между участниками, и различие достаточно ничтожного:
/// доли процента хватает, чтобы один уступил раньше другого.
///
/// ПОЧЕМУ ТАБЛИЦА, А НЕ ГЕНЕРАТОР. Соль обязана быть ПОСТОЯННОЙ у сущности. Значение,
/// вытянутое заново каждый кадр, есть шум: пара, застрявшая лоб в лоб, совпадёт снова
/// с прежней вероятностью, и затор растянется вместо того, чтобы разойтись. Поэтому номер
/// в таблице сущность получает один раз при появлении, а сама таблица считается один раз
/// на партию.
///
/// ПОЧЕМУ ЗЕРНО ПОСТОЯННО. Воспроизводимость партии в проекте держится на журнале событий,
/// и случайность, зависящая от запуска, её нарушила бы: два проигрывания одного журнала
/// разошлись бы в движении.
///
/// ЗНАЧЕНИЯ РАССТАВЛЕНЫ РАВНОМЕРНО И ЛИШЬ ПОТОМ ПЕРЕМЕШАНЫ. Выборка независимых случайных
/// чисел даёт сгущения, и в маленьком отряде соседи получали бы близкую соль — то есть
/// как раз ту симметрию, ради устранения которой соль и заведена. Равномерная сетка такого
/// сгущения не даёт вовсе, а перемешивание убирает связь между номером появления
/// и величиной соли.
///
/// ИМЯ ГОВОРИТ ОБ ОБЛАСТИ ПРИМЕНЕНИЯ. Это соль именно локального слоя движения; если
/// подобное различие понадобится в другом месте — в разбросе стрельбы, во времени
/// переназначения цели, — оно заводится своей таблицей, а не расширением этой.
/// </summary>
public sealed class BoidSalt
{
    /// <summary>
    /// Сколько различных значений. Затор есть событие парное, поэтому существенна не длина
    /// таблицы сама по себе, а доля пар с совпавшей солью: она равна единице на длину.
    /// Десяток оставлял бы неразрешённой каждую десятую пару, тридцать два — каждую
    /// тридцать вторую, а стоят они одинаково.
    /// </summary>
    public const int Slots = 32;

    /// <summary>Зерно перемешивания. Постоянно ради воспроизводимости партии.</summary>
    private const ulong Seed = 20260817UL;

    private readonly float[] _values = new float[Slots];

    public BoidSalt()
    {
        for (int i = 0; i < Slots; i++)
            _values[i] = (2f * i + 1f) / Slots - 1f;

        var rng = new RandomNumberGenerator { Seed = Seed };

        for (int i = Slots - 1; i > 0; i--)
        {
            int j = rng.RandiRange(0, i);
            (_values[i], _values[j]) = (_values[j], _values[i]);
        }
    }

    /// <summary>
    /// Соль слота: число от −1 до 1. Отрицательный номер означает, что слот сущности ещё
    /// не назначен, и соли у неё нет.
    /// </summary>
    public float Of(int slot) => slot < 0 ? 0f : _values[slot % Slots];
}
