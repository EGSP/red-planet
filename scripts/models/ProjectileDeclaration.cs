using Godot;

/// <summary>
/// Объявление снаряда: «этот ствол бросает вот такую сцену вот такого размера».
///
/// УЗЕЛ КЛАДЁТСЯ ВНУТРЬ <see cref="ModelTool"/> того ствола, которому принадлежит, — туда же,
/// где уже лежат вспышка выстрела и <see cref="ImpactEffect"/>. Подписывать его не нужно:
/// часть связана с определением оружия по <see cref="ModelTool.ToolId"/>, и объявление
/// внутри неё наследует эту связь целиком.
///
/// ПОЛОЖЕНИЕ УЗЛА НИ НА ЧТО НЕ ВЛИЯЕТ — как и у <see cref="ImpactEffect"/>. Снаряд рождается
/// на срезе ствола, в точке <see cref="ModelTool.Muzzle"/>, а узел ставится туда, где его
/// удобно видеть в редакторе; обыкновенно это и есть срез.
///
/// ПОЛЕ <c>Effect</c> ДЕРЖИТ СЦЕНУ СНАРЯДА с корнем <see cref="ProjectileModel"/>, а <c>Size</c>
/// — множитель её размера. Имена унаследованы от <see cref="EffectDeclaration"/>, поскольку
/// объявление устроено одинаково у эффекта и у снаряда: ссылка, размер и предпросмотр.
///
/// ЕСЛИ УЗЛА НЕТ, выстрел всё равно виден: <see cref="ProjectileSystem"/> берёт общую сцену
/// из своего поля, а нет и её — снаряд рисуется кругом цвета <c>projectile_color</c>, как
/// было до появления моделей.
/// </summary>
[Tool, GlobalClass]
public partial class ProjectileDeclaration : EffectDeclaration
{
    /// <summary>Отметка места в редакторе жёлтая: снаряд отличается от вспышек.</summary>
    protected override Color Mark => new(1f, 0.85f, 0.35f, 0.7f);
}
