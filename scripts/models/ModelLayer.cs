using System;
using Godot;

/// <summary>
/// Узел, рисующий то, что должно лечь выше или ниже изображения модели.
///
/// ЗАЧЕМ ОН НУЖЕН. Godot выполняет собственные команды узла ДО его потомков. Пока корпус
/// рисовался внутри <c>_Draw</c> самой сущности, полосу прочности, прогресс завода и
/// стрелки выездов достаточно было выписать после него. С появлением модели корпус стал
/// дочерним узлом, и всё, что сущность рисует сама, ушло под него. Порядком вызовов это
/// не лечится: свои команды родителя всегда идут первыми.
///
/// ПОЧЕМУ ПОРЯДКОМ В ДЕРЕВЕ, А НЕ ZIndex. Слои мира <see cref="WorldLayer"/> стоят на нуле
/// и различаются только положением в дереве; собственный ZIndex вывел бы узел из этого
/// порядка и спрятал бы его под саму местность. Поэтому слой пометок добавляется потомком
/// ПОСЛЕ модели и остаётся на нуле. Тот же приём и по той же причине применён
/// в <see cref="BlueprintLayer"/>.
///
/// ZIndex задаётся лишь подсказкам редактора: там мир не рисуется, и вывести подсказку
/// поверх всего — единственное требование.
/// </summary>
[Tool]
public partial class ModelLayer : Node2D
{
    /// <summary>Наибольший ZIndex: подсказка редактора обязана лежать поверх изображения.</summary>
    public static readonly int TopZ = (int)RenderingServer.CanvasItemZMax;

    /// <summary>Что рисовать. Владелец передаёт собственный метод отрисовки.</summary>
    public Action<Node2D> Painter;

    /// <summary>
    /// Создать слой над узлом. Слой стоит в начале координат владельца и его поворот
    /// наследует, поэтому рисование ведётся в тех же координатах, что и у самого владельца.
    ///
    /// Владельцем может быть и <see cref="Control"/>: поле редактора контента рисует свои
    /// подсказки поверх добавленных на него экземпляров моделей той же надобности ради.
    ///
    /// <paramref name="internalNode"/> убирает слой из сохраняемого дерева сцены — так
    /// подсказки редактора не попадают в .tscn и не мешают в панели узлов. Пометки игровых
    /// сущностей создаются в мире, где сохранять нечего, и признак им безразличен.
    /// </summary>
    public static ModelLayer Attach(Node owner, Action<Node2D> painter, string name = "Layer",
        int zIndex = 0, bool internalNode = false)
    {
        var layer = new ModelLayer
        {
            Name = name,
            Painter = painter,
            ZIndex = zIndex,
        };

        owner.AddChild(layer, false,
            internalNode ? Node.InternalMode.Back : Node.InternalMode.Disabled);

        return layer;
    }

    public override void _Draw() => Painter?.Invoke(this);
}
