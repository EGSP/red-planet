using Godot;

/// <summary>
/// Цвет стороны, которым шейдер <c>unit_body.gdshader</c> окрашивает спрайты модели.
///
/// ПОЧЕМУ НЕ ЦВЕТ ИЗ СПРАВОЧНИКА. Ключ <c>color</c> в .toml различает виды между собой:
/// у завода ботов он один, у завода машин другой, и служит он процедурному силуэту.
/// Окраска же отвечает на другой вопрос — чья это машина, — и обязана быть одинаковой
/// у всех машин стороны, иначе принадлежность по цвету не читается. Отсюда следует, что
/// величины две и выводить одну из другой нельзя.
///
/// Различать виды внутри стороны остаётся задачей самого рисунка: спрайты для того
/// и заведены, чтобы силуэт нёс больше, чем оттенок заливки.
/// </summary>
public static class TeamPalette
{
    /// <summary>Сторона игрока: холодный синий.</summary>
    public static readonly Color Player = new(0.42f, 0.68f, 0.98f);

    /// <summary>Противник: тёплый красный.</summary>
    public static readonly Color Hostile = new(0.93f, 0.36f, 0.31f);

    public static Color Of(Faction faction) =>
        faction == Faction.Hostile ? Hostile : Player;
}
