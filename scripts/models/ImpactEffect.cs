using Godot;

/// <summary>
/// Объявление вспышки попадания: «снаряд ЭТОГО ствола, во что бы он ни угодил, разрывается
/// такой сценой такого размера».
///
/// УЗЕЛ КЛАДЁТСЯ ВНУТРЬ <see cref="ModelTool"/> того ствола, которому принадлежит, — так же,
/// как туда кладётся вспышка выстрела. Подписывать его не нужно: часть уже связана
/// с определением оружия по <see cref="ModelTool.ToolId"/>, и объявление внутри неё
/// наследует эту связь целиком.
///
/// ПОЧЕМУ ВИД ПОПАДАНИЯ ПРИНАДЛЕЖИТ ОРУЖИЮ, А НЕ ЦЕЛИ. Разрыв показывает, чем ударили,
/// а не во что: болванка малого калибра и снаряд титана оставляют разное на одной и той же
/// машине. Обратный порядок — объявление у цели — означал бы, что вид попадания меняется
/// от того, кого задело, и одно оружие выглядело бы по-разному в каждом бою.
///
/// ПОЛОЖЕНИЕ УЗЛА НИ НА ЧТО НЕ ВЛИЯЕТ, в отличие от <see cref="DeathEffect"/>: разрыв
/// случается там, куда прилетел снаряд, и место берётся из документа попадания. Узел
/// ставится куда удобно смотреть — обычно при точке вылета.
///
/// ЕСЛИ УЗЛА НЕТ, попадание всё равно видно: <see cref="EffectSystem"/> играет общую
/// вспышку из своего поля <c>Impact</c>. То же происходит и тогда, когда стрелявший погиб
/// раньше, чем его снаряд долетел: спросить объявление становится не у кого.
/// </summary>
[Tool, GlobalClass]
public partial class ImpactEffect : EffectDeclaration
{
    /// <summary>Отметка места в редакторе синяя: попадание отличается от гибели.</summary>
    protected override Color Mark => new(0.45f, 0.75f, 1f, 0.7f);
}
