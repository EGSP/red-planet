using Godot;

/// <summary>
/// Настройка тумана войны: что показывать, каким цветом и как часто пересчитывать растр.
///
/// ПОЧЕМУ РЕСУРС, А НЕ НАБОР ПРИЗНАКОВ ОТЛАДКИ. Туман есть часть вида игры, а не выкладка
/// для разбора поведения систем, поэтому его настройки должны переживать перезапуск партии
/// и правиться в инспекторе — там же, где размер мира и раскладка точек метала. Признаки
/// <see cref="DebugFlags"/> живут по другим правилам: они статические и намеренно не
/// сохраняются никуда.
///
/// Панель отладки правит поля этого ресурса напрямую — так переключение работает по ходу
/// партии. Правки из панели в файл не сохраняются: постоянное значение задаётся в инспекторе.
/// </summary>
[Tool]
[GlobalClass]
public partial class FogSettings : Resource
{
    // ── что показывать ────────────────────────────────────────────────────────────

    [ExportGroup("Отображение")]

    /// <summary>Закрашивать ли непросматриваемую часть карты.</summary>
    [Export] public bool Fog = true;

    /// <summary>Проводить ли обводку по общей границе поля зрения.</summary>
    [Export] public bool Outline = true;

    /// <summary>
    /// Скрывать ли сущности противника вне поля зрения.
    ///
    /// Скрытие касается только отрисовки: выбор целей, приказы и выделение видят карту
    /// целиком, поэтому башня по-прежнему стреляет по невидимому юниту.
    /// </summary>
    [Export] public bool HideEnemies = true;

    // ── цвета ─────────────────────────────────────────────────────────────────────

    [ExportGroup("Цвета")]

    /// <summary>Цвет закрытой части карты. Альфа задаёт плотность.</summary>
    [Export] public Color FogColor = new(0.02f, 0.02f, 0.06f, 0.72f);

    /// <summary>Цвет обводки.</summary>
    [Export] public Color OutlineColor = new(0.95f, 0.95f, 0.35f, 0.9f);

    // ── геометрия границы ─────────────────────────────────────────────────────────

    [ExportGroup("Граница")]

    /// <summary>
    /// Толщина обводки в пикселях ЭКРАНА: линия остаётся одинаковой при любом масштабе
    /// камеры — так же, как обводка фигур в <see cref="WidthMode.Screen"/>.
    /// </summary>
    [Export(PropertyHint.Range, "0.5,8,0.1")] public float OutlineWidthPx = 2f;

    /// <summary>
    /// Ширина перехода от видимого к закрытому, пикселей экрана. Полтора пикселя дают
    /// сглаженный, но не размытый край; большие значения превращают границу в ореол.
    /// </summary>
    [Export(PropertyHint.Range, "0.5,32,0.5")] public float SoftnessPx = 1.5f;

    // ── пересчёт ──────────────────────────────────────────────────────────────────

    [ExportGroup("Пересчёт")]

    /// <summary>
    /// Ячейка растра, пикселей. Задаёт чёткость ФОРМЫ границы — того, насколько точно
    /// передаются стыки перекрывающихся полей зрения и узкие перемычки между ними.
    /// Положение самой линии от размера ячейки почти не зависит: растр хранит расстояние,
    /// и промежуточные значения интерполируются.
    ///
    /// Стоимость пересборки растёт как квадрат: вдвое мельче ячейка — вчетверо больше
    /// работы. На больших картах это заметно, поэтому уменьшать имеет смысл, только если
    /// огрубление формы видно глазом.
    /// </summary>
    [Export(PropertyHint.Enum, "8:8,16:16,32:32")] public int CellPx = 16;

    /// <summary>
    /// Пересобирать растр каждый кадр. Иначе граница тумана отстаёт от юнитов и движется
    /// рывками: за время между пересборками юнит успевает пройти заметное расстояние,
    /// и вся видимая область догоняет его скачком.
    /// </summary>
    [Export] public bool EveryFrame = true;

    /// <summary>Сколько раз в секунду пересобирается растр, когда пересчёт не покадровый.</summary>
    [Export(PropertyHint.Range, "1,60,1")] public float UpdateHz = 20f;
}
