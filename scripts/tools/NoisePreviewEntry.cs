using Godot;

/// <summary>
/// Одна панель стенда шумов: поле и то, что на нём показывается в паре.
///
/// ПОЧЕМУ ОТДЕЛЬНЫЙ РЕСУРС, А НЕ МАССИВ <see cref="NoiseSettings"/>. Панель показывает не
/// только поле, но и покрытие с декалью, отобранные этим полем; массив полей такой пары
/// выразить не может. Ресурс же сохраняется вместе со сценой стенда, поэтому подобранный
/// набор панелей не приходится собирать заново при каждом открытии.
///
/// ПОЧЕМУ ПОКРЫТИЕ И ДЕКАЛЬ БЕРУТСЯ ГОТОВЫМИ РЕСУРСАМИ. Это те же <see cref="SurfaceTile"/>
/// и <see cref="SurfaceDecal"/>, что назначены местности. Стенд их не копирует и не правит,
/// поэтому увиденное на панели совпадает с тем, что даст <see cref="SurfaceRenderer"/> на
/// том же поле.
/// </summary>
[Tool]
[GlobalClass]
public partial class NoisePreviewEntry : Resource
{
    /// <summary>Имя панели. Попадает в подпись; пусто — подставляется имя файла поля.</summary>
    [Export] public string Id = "";

    /// <summary>Показывать ли панель. Снятая галка убирает её из раскладки целиком.</summary>
    [Export] public bool Enabled = true;

    /// <summary>Поле шума. Не назначено — панель показывает только подпись.</summary>
    [Export] public NoiseSettings Noise;

    /// <summary>
    /// Покрытие, накладываемое поверх серого поля по своему отрезку значений. Не назначено —
    /// панель остаётся чёрно-белой.
    /// </summary>
    [Export] public SurfaceTile Tile;

    /// <summary>
    /// Декаль, раскладываемая по этому же полю. Отрезки температуры и высоты при показе на
    /// стенде не проверяются: отбор идёт только по <see cref="SurfaceDecal.NoiseRange"/>,
    /// иначе панель показывала бы не поле, а положение биома.
    /// </summary>
    [Export] public SurfaceDecal Decal;
}
