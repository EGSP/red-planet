using Godot;

/// <summary>
/// Набор отметин копоти: чем помечается земля там, где что-то взорвалось.
///
/// ЗАЧЕМ ОТДЕЛЬНЫЙ РЕСУРС, А НЕ ПОЛЯ В УЗЛЕ ЭФФЕКТА. Отметина переживает эффект, который
/// её поставил: сама она лежит на общем слое земли и рисуется вместе со всеми прочими,
/// поэтому вид её принадлежит не одному взрыву, а всем сразу. Ресурс лежит одним файлом
/// (<c>resources/particles/scorch.tres</c>), а узлы <see cref="ScorchStamp"/> в сценах
/// эффектов на него лишь ссылаются: правка расходится по всем взрывам сама.
///
/// РАЗМЕР ЗДЕСЬ НЕ ЗАДАЁТСЯ. Он принадлежит событию, а не набору: след от гибели бота
/// и след от гибели завода рисуются одними и теми же изображениями разной величины.
/// Поэтому размер объявлен в <see cref="ScorchStamp"/>, то есть в той сцене, где эффект
/// собран целиком и величину видно относительно корпуса.
/// </summary>
[Tool, GlobalClass]
public partial class ScorchDecal : Resource
{
    /// <summary>
    /// Изображения отметин. Выбирается случайное на каждый отпечаток, поэтому одинаковые
    /// взрывы не оставляют одинакового следа. Берётся диффузная карта: освещения
    /// в двумерии нет.
    /// </summary>
    [Export] public Texture2D[] Textures { get; set; } = System.Array.Empty<Texture2D>();

    /// <summary>
    /// Оттенок и прозрачность отпечатка. Земля под ним остаётся видна, поэтому копоть
    /// задаётся тёмным цветом с неполной прозрачностью, а не сплошным пятном.
    /// </summary>
    [Export] public Color Tint { get; set; } = new(1f, 1f, 1f, 0.75f);

    /// <summary>Поворачивать ли отпечаток на случайный угол. Снимает повторяемость рисунка.</summary>
    [Export] public bool RandomRotation { get; set; } = true;

    /// <summary>
    /// Сколько секунд отпечаток держится. Ноль означает, что он не гаснет вовсе и живёт
    /// до тех пор, пока его не вытеснит новый: мест в наборе отпечатков ограниченное
    /// число, и самый старый уступает место очередному.
    /// </summary>
    [Export(PropertyHint.Range, "0,600,1,or_greater")] public float Lifetime { get; set; }

    /// <summary>
    /// Сколько секунд занимает угасание в конце срока. Отсчитывается внутрь срока, а не
    /// сверх него: отпечаток со сроком 60 и угасанием 10 держится полными 50 секунд
    /// и последние 10 бледнеет.
    /// </summary>
    [Export(PropertyHint.Range, "0,120,0.5,or_greater")] public float Fade { get; set; } = 10f;
}
