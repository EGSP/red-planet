using Godot;

/// <summary>
/// Вид луча: три части, каждая со своим сводом настроек, и общее для них время разгорания.
/// Один ресурс на все лучи одного рода — строительный луч у коммандера, фабрикатора
/// и башни-сборщика есть одно и то же изображение, и правиться оно должно в одном месте.
///
/// ПОЧЕМУ РЕСУРС, А НЕ ПОЛЯ УЗЛА. Поля пришлось бы повторять в каждой сцене модели, и три
/// строителя разошлись бы видом при первой же правке. Узел <see cref="BeamVisual"/> говорит,
/// ЧТО показать и откуда, ресурс — КАК.
///
/// ПОЧЕМУ ЧАСТЕЙ ТРИ. Тело луча, вспышка у среза инструмента и вспышка в точке попадания
/// рисуются разными приёмами и потому разными шейдерами. Материал в множественной сетке
/// один на все её экземпляры, поэтому каждая часть получает свою сетку, а вместе с ней
/// и свой свод настроек — см. <see cref="BeamPainter"/>.
///
/// ЧИСЛА ЗАДАНЫ В ПИКСЕЛЯХ МИРА и растут вместе с приближением камеры: луч принадлежит миру,
/// а не тому, кто на мир смотрит. Прежней поправки на экранный размер здесь больше нет.
/// </summary>
[Tool]
[GlobalClass]
public partial class BeamStyle : Resource
{
    /// <summary>Тело луча — полоса от инструмента к цели.</summary>
    [Export] public BeamBodyStyle Body { get; set; } = new();

    /// <summary>Вспышка у среза инструмента.</summary>
    [Export] public BeamCapStyle Muzzle { get; set; } = new();

    /// <summary>Вспышка в точке попадания.</summary>
    [Export] public BeamCapStyle Impact { get; set; } = new();

    /// <summary>
    /// За сколько секунд луч разгорается и гаснет.
    ///
    /// ЗАЧЕМ ЭТО ВООБЩЕ ЕСТЬ. Работа прерывается на кадр всякий раз, когда исполнитель
    /// переподключается к соседнему каркасу либо когда постройка достроена, а следующая
    /// ещё не назначена. Луч, показываемый строго по признаку «работа идёт», на таких
    /// разрывах мигал бы.
    /// </summary>
    [Export(PropertyHint.Range, "0,1,0.01")] public float RiseTime { get; set; } = 0.05f;

    /// <inheritdoc cref="RiseTime"/>
    [Export(PropertyHint.Range, "0,1,0.01")] public float FadeTime { get; set; } = 0.12f;

    /// <summary>Загрузить ресурс по пути, если он есть. Общая подстановка умолчаний частей.</summary>
    internal static T Fallback<T>(string path) where T : Resource =>
        ResourceLoader.Exists(path) ? GD.Load<T>(path) : null;
}
