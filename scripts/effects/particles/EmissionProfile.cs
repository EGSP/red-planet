using Godot;

/// <summary>
/// Настройки рождения одной части эффекта, снятые с узла <see cref="GpuParticles2D"/>
/// при запекании.
///
/// ГРАНИЦА ОТВЕТСТВЕННОСТИ ЗДЕСЬ ГЛАВНОЕ. Профиль описывает лишь тот миг, когда частица
/// появляется: где она родится, куда полетит, сколько их выйдет за один вброс. Всё, что
/// происходит с частицей дальше — затухание, тяготение, вращение, кривая размера, градиент
/// цвета, — по-прежнему считает материал обработки общего поля. Отсюда следует, что
/// настройки материала здесь не повторяются: повторено ровно то, что вбрасывающий
/// перехватывает у материала, и ничего сверх.
///
/// ПОЧЕМУ РАЗБРОС МЕСТА И СКОРОСТИ ПЕРЕХВАТЫВАЕТСЯ. Общее поле стоит в начале координат
/// мира и о событии не знает, поэтому место рождения задаётся вбросом обязательно,
/// а вместе с ним отпадает и разброс места, который материал разыграл бы сам. Направление
/// разлёта задаётся по той же причине: попадание разбрасывает искры навстречу выстрелу,
/// а материал общего поля знает лишь собственные оси и повернуть их под каждое событие
/// не может.
///
/// ЧТО ОСТАЁТСЯ У МАТЕРИАЛА: начальный угол спрайта, угловая скорость, затухание,
/// тяготение, кривые размера и цвета, разброс срока жизни.
/// </summary>
public sealed class EmissionProfile
{
    /// <summary>Поле, в которое идёт вброс.</summary>
    public ParticleKey Key;

    /// <summary>Место части в осях эффекта — то, где узел лежал в сцене.</summary>
    public Vector2 Offset;

    /// <summary>Поворот части в осях эффекта.</summary>
    public float Angle;

    /// <summary>
    /// Сколько частиц выходит за один вброс. Снимается с <see cref="GpuParticles2D.Amount"/>:
    /// одноразовая часть эффекта объявлена взрывной выдачей, то есть выпускает весь свой
    /// запас разом.
    /// </summary>
    public int Count = 1;

    /// <summary>
    /// Сколько частиц в секунду даёт непрерывный поток. Считается как запас, делённый
    /// на срок жизни, — именно с такой частотой узел выпускал бы частицы, чтобы держать
    /// в воздухе ровно свой запас.
    /// </summary>
    public float Rate = 1f;

    /// <summary>Разброс места рождения в пикселях — снят с формы выдачи материала.</summary>
    public float Radius;

    /// <summary>Наименьшая начальная скорость, пикселей в секунду.</summary>
    public float SpeedMin;

    /// <summary>Наибольшая начальная скорость, пикселей в секунду.</summary>
    public float SpeedMax;

    /// <summary>Половина раствора конуса разлёта, радианы.</summary>
    public float Spread;

    /// <summary>Направление разлёта в осях части, радианы.</summary>
    public float Course;

    /// <summary>
    /// Задаёт ли вброс скорость сам. Ложь означает часть, у которой начальной скорости нет
    /// вовсе: разыгрывать нечего, и поле оставляет скорость материалу.
    /// </summary>
    public bool Driven => SpeedMax > 0.01f;
}
