using Godot;

/// <summary>
/// Частицы, выдаваемые ходом сущности: пыль из-под корпуса, песок, копоть.
///
/// СОБСТВЕННОГО КОДА ЗДЕСЬ НЕТ, И ЭТО НАМЕРЕННО. Узел объявляет лишь то, при каких
/// скоростях эффект уместен; ни владельца, ни его скорость он не ищет. Связывает узел
/// с сущностью и ведёт его <see cref="EffectSystem"/> — по тому же правилу, по которому
/// <see cref="ModelTool"/> не разыскивает своё определение оружия, а лишь объявляет роль.
/// Иначе узел изображения знал бы про симуляцию, и всякое новое событие для эффекта
/// требовал бы правки самого узла.
///
/// ЗАЧЕМ НАСЛЕДОВАНИЕ, А НЕ ДОЧЕРНИЙ УЗЕЛ ПРИ ОТДЕЛЬНОМ ПРИЗНАКЕ. Наследник
/// <see cref="GpuParticles2D"/> сохраняет весь штатный разбор частиц в инспекторе вместе
/// с предпросмотром в редакторе, а поля порога оказываются на том же узле, что и вид
/// частиц. Разнеси их по двум узлам — и настройка вида перестала бы совпадать с правилом
/// выдачи, согласовывать их пришлось бы вручную.
///
/// ЭФФЕКТ ПЕРЕИСПОЛЬЗУЕТСЯ ЭКЗЕМПЛЯРОМ СЦЕНЫ. Сцена вида эффекта лежит одна
/// (<c>resources/particles/*.tscn</c>), а в сцену модели вставляется её экземпляр:
/// правка общего расходится по всем видам сама, а положение и пороги остаются
/// переопределениями экземпляра.
/// </summary>
[Tool, GlobalClass]
public partial class MovementParticles : GpuParticles2D
{
    /// <summary>
    /// Скорость, ниже которой выдачи нет вовсе, пикселей в секунду. Порог нужен затем,
    /// что стоящая машина всё равно мелко смещается расталкиванием соседей и без него
    /// пылила бы на месте.
    /// </summary>
    [Export] public float MinSpeed { get; set; } = 25f;

    /// <summary>
    /// Скорость, при которой выдача идёт в полную силу. Между порогом и этой величиной
    /// плотность нарастает пропорционально, поэтому разгон и торможение видны сами собой.
    /// </summary>
    [Export] public float FullSpeed { get; set; } = 120f;

    /// <summary>
    /// Сколько секунд после остановки поток ещё считался работающим.
    ///
    /// НА ИГРУ БОЛЬШЕ НЕ ВЛИЯЕТ. Задержка требовалась, пока пыль выпускал собственный узел
    /// машины: повторное включение <see cref="GpuParticles2D.Emitting"/> начинает выдачу
    /// заново, и переступающая в толпе машина мигала бы пылью на каждом шаге. Общее поле
    /// частиц ничего не включает и не выключает — частота вброса просто следует
    /// за скоростью, — поэтому мигать нечему. Поле сохранено ради сцен, где оно задано.
    /// </summary>
    [Export] public float StopDelay { get; set; } = 0.5f;

    /// <summary>
    /// В игре выдача выключается принудительно.
    ///
    /// ЗАЧЕМ. Предпросмотра у частиц в редакторе нет иного, кроме включённой выдачи,
    /// и художник её включает, а признак сохраняется в файл. Без сброса пыль пошла бы
    /// при всяком поднятии сцены — в том числе в иконке панели строительства и в поле
    /// редактора контента, где никто никуда не едет.
    ///
    /// В САМОЙ ПАРТИИ ЭТОТ УЗЕЛ НЕ ЖИВЁТ ВОВСЕ: запекание модели снимает его со сцены
    /// и оставляет от него настройки рождения, а частицы выпускает общее поле —
    /// см. <see cref="ParticleBake"/>. Сброс поэтому остаётся значим лишь там, где сцена
    /// поднимается целиком: в редакторе и в поле предпросмотра.
    /// </summary>
    public override void _Ready()
    {
        if (!Engine.IsEditorHint())
            Emitting = false;
    }
}
