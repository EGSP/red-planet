using Godot;

/// <summary>
/// Сущность, которая видит вокруг себя. Поле зрения есть у всего, что принадлежит игроку
/// или воюет против него: у зданий, каркасов, ботов, коммандера и врагов.
///
/// СЕЙЧАС на видимость мира это не влияет — тумана войны в игре нет. Но радиус уже работает
/// как рабочая зона: фабрикатор чинит то, что видит, а башня-сборщик обслуживает свой круг.
/// Заведено единым свойством заранее, чтобы потом не пришлось разносить два разных радиуса
/// («что вижу» и «докуда дотягиваюсь») по всем справочникам задним числом.
/// </summary>
public interface IVision
{
    /// <summary>Радиус обзора в пикселях. Ноль — сущность слепа.</summary>
    float VisionRadius { get; }

    Vector2 GlobalPosition { get; }
}

/// <summary>Отрисовка поля зрения — одинаковая у всех, кто его имеет.</summary>
public static class VisionGizmo
{
    /// <summary>
    /// Круг обзора. Намеренно почти прозрачный: полей зрения на экране десятки,
    /// и заметными их делать нельзя — они превратят карту в паутину.
    /// </summary>
    public static void Draw(CanvasItem canvas, float radius, Color tint)
    {
        if (radius <= 0f)
            return;

        // Слабая заливка + экранный контур: при zoom 0.25 дуга остаётся читаемой,
        // а десятки дисков не перекрывают карту
        ShapeDraw.Circle(canvas, Vector2.Zero, radius,
            ShapeStyle.Filled(
                new Color(tint, 0.025f),
                new Color(tint, 0.12f),
                1f,
                WidthMode.Screen),
            48);
    }
}
