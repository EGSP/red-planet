using Godot;

/// <summary>
/// Сущность, которая видит вокруг себя. Поле зрения есть у всего, что принадлежит игроку
/// или воюет против него: у зданий, каркасов, ботов, коммандера и врагов.
///
/// Радиус работает и как рабочая зона: фабрикатор чинит то, что видит, а башня-сборщик
/// обслуживает свой круг. Заведено единым свойством намеренно, чтобы не разносить два
/// разных радиуса («что вижу» и «докуда дотягиваюсь») по всем справочникам задним числом.
///
/// РАСТР ВИДИМОСТИ собирает <see cref="VisionSystem"/> из полей стороны игрока: по нему
/// рисуется туман войны и скрываются сущности противника. Ответный огонь и автовыбор
/// цели режет тот же радиус в <see cref="WeaponSystem"/>: ствол длиннее обзора не стреляет
/// в то, чего носитель не видит. Выделение и приказы игрока по-прежнему видят карту целиком.
/// </summary>
public interface IVision
{
    /// <summary>Радиус обзора в пикселях. Ноль — сущность слепа.</summary>
    float VisionRadius { get; }

    /// <summary>
    /// Чья сторона смотрит. Растр видимости собирается по одной стороне, поэтому спрашивать
    /// её приходится у самого источника: тип узла о стороне ничего не говорит — и юнит
    /// игрока, и юнит противника суть один и тот же класс.
    /// </summary>
    Faction Faction { get; }

    Vector2 GlobalPosition { get; }
}

/// <summary>
/// Разведка стороны: видит ли хоть кто-нибудь из своих указанное место.
///
/// ЗАЧЕМ ОТДЕЛЬНОЕ ПОНЯТИЕ. Прежде огонь ограничивался ЛИЧНЫМ обзором стрелка, отчего
/// два числа справочника — дальность ствола и радиус обзора — делали одну и ту же работу,
/// и меньшее из них молча отменяло большее. Виды с разным соотношением этих чисел выразить
/// было нельзя: дальнозоркий с коротким стволом стрелял ровно так же, как близорукий
/// с длинным.
///
/// Разделение ролей таково. Дальность ствола отвечает на вопрос «докуда достаёт выстрел»
/// и остаётся личным свойством стрелка. Обзор отвечает на вопрос «что сторона знает
/// о положении противника» и складывается по стороне целиком: цель, которую видит союзник,
/// разведана для всех. Отсюда следует и то, ради чего разделение затевалось, — слепой
/// стрелок бьёт по цели, разведанной соседом, а зоркий не стреляет дальше своего ствола.
///
/// СТОРОНА, А НЕ РАСТР. <see cref="VisionSystem"/> собирает растр видимости, но собирает
/// его только для игрока, в графическом цикле и по таймеру, поэтому основанием боевого
/// решения он служить не может. Здесь спрашиваются сами источники обзора, и ответ
/// одинаково верен для обеих сторон.
/// </summary>
public static class Sight
{
    /// <summary>
    /// Разведана ли точка стороной. <paramref name="self"/> — сам спрашивающий, если он
    /// зряч: его обзор проверяется первым, потому что в подавляющем большинстве случаев
    /// стрелок видит свою цель сам, и обход прочих источников тогда не нужен вовсе.
    /// </summary>
    public static bool Spots(Faction side, Vector2 point, IVision self = null)
    {
        if (Sees(self, side, point))
            return true;

        foreach (var eye in GameManager.I.Index.All<IVision>())
            if (!ReferenceEquals(eye, self) && Sees(eye, side, point))
                return true;

        return false;
    }

    private static bool Sees(IVision eye, Faction side, Vector2 point)
    {
        if (eye == null || eye.Faction != side)
            return false;

        float radius = eye.VisionRadius;

        return radius > 0f && eye.GlobalPosition.DistanceSquaredTo(point) <= radius * radius;
    }
}

/// <summary>
/// Примитив круга обзора. Когда его показывать, решает <see cref="GizmoGate"/> /
/// <see cref="UnitGizmos"/> — сам круг про видимость ничего не знает.
/// </summary>
public static class VisionGizmo
{
    /// <summary>
    /// Круг обзора. Намеренно почти прозрачный: полей зрения на экране десятки,
    /// и заметными их делать нельзя — они превратят карту в паутину.
    /// </summary>
    public static void Draw(CanvasItem canvas, float radius)
    {
        if (radius <= 0f)
            return;

        // Слабая заливка + экранный контур: при zoom 0.25 дуга остаётся читаемой,
        // а десятки дисков не перекрывают карту
        ShapeDraw.Circle(canvas, Vector2.Zero, radius, DrawTheme.Radius(VizKind.Vision), 48);
    }
}
