using Godot;
using System.Text.Json.Nodes;

/// <summary>
/// Система — нода: её добавляют в сцену и настраивают в инспекторе.
/// Сама регистрируется в планировщике, порядок исполнения задаётся полем Order.
///
/// Менеджера система берёт не из статической ссылки, а из собственных предков: она
/// принадлежит тому корню, под которым висит. Разница видна на сносе сессии — выход
/// из дерева идёт сверху вниз, и к тому мигу, когда очередь доходит до системы,
/// статической ссылки уже нет, а своя — есть.
///
/// ИНИЦИАЛИЗАЦИЯ В ДВЕ ФАЗЫ. В <see cref="OnRegister"/> система настраивает саму себя
/// и не вправе рассчитывать, что соседи уже существуют: порядок _Ready определяется
/// расстановкой узлов в сцене. В <see cref="OnLink"/> состав систем полон, поэтому
/// здесь можно связываться с соседями. Взаимные ссылки при этом работают без всякого
/// разбора графа зависимостей: к началу второй фазы существуют все участники разом.
/// </summary>
public partial class GameSystem : Node
{
    [Export] public Phase Phase = Phase.Simulate;

    /// <summary>Порядок внутри фазы — чем меньше, тем раньше.</summary>
    [Export] public int StepOrder;

    /// <summary>
    /// В каком цикле обновления Godot планировщик вызывает эту систему.
    /// По умолчанию — физический: симуляция остаётся на фиксированном шаге.
    /// Графический цикл нужен представлению, которое должно совпадать с отрисовкой.
    /// </summary>
    [Export] public UpdateCycle UpdateCycle = UpdateCycle.PhysicsProcess;

    protected GameManager GM { get; private set; }

    private bool _linked;

    public override void _EnterTree()
    {
        GM = this.Ancestor<GameManager>() ?? GameManager.I;

        if (GM == null)
            GD.PushError($"[{Name}] система вне сессии: композиционный корень не найден");
    }

    public override void _Ready()
    {
        GM?.Scheduler.Add(this);
        OnRegister();

        // Систему, добавленную после сборки сессии, связываем сразу: общей точки
        // «все зарегистрированы» для неё уже не будет, она её опоздала застать
        if (GM is { SystemsLinked: true })
            Link();
    }

    public override void _ExitTree() => GM?.Scheduler.Remove(this);

    /// <summary>
    /// Вторая фаза. Зовёт композиционный корень, повторный вызов ничего не делает —
    /// иначе поздно добавленная система связалась бы дважды.
    /// </summary>
    internal void Link()
    {
        if (_linked)
            return;

        _linked = true;
        OnLink();
    }

    /// <summary>Первая фаза: настройка самой системы. Соседей здесь ещё может не быть.</summary>
    protected virtual void OnRegister() { }

    /// <summary>
    /// Вторая фаза: связывание с другими системами через <c>GM.System&lt;T&gt;()</c>.
    ///
    /// Что здесь ЕЩЁ НЕ готово: мир пуст. Стартовая выдача сессии — коммандер и начальный
    /// запас — создаётся в <see cref="Session"/>, а его _Ready приходит позже нашего.
    /// Поэтому работа, которой нужен населённый мир, по-прежнему откладывается до первого
    /// кадра, как это делает MetalSpotSystem: точки метала нельзя расставлять раньше того,
    /// что выдано на старте, иначе они встанут на занятые клетки.
    /// </summary>
    protected virtual void OnLink() { }

    /// <summary>Шаг системы в своей фазе кадра.</summary>
    public virtual void Step(double dt) { }

    /// <summary>
    /// Проход показа у системы физического цикла: то, что готовит картинку, а не меняет
    /// состояние мира.
    ///
    /// ЗАЧЕМ ВТОРАЯ ТОЧКА ВХОДА. Часть работы системы симуляции влияет на одну лишь картинку:
    /// положение узлов с частицами, сроки догорания, освобождение отслуживших узлов.
    /// Промежуточные физические шаги не рисуются вовсе — при восьми шагах на кадр видимый
    /// след оставляет один из них, — поэтому вести такую работу на частоте шага значит
    /// повторять её вхолостую. Разделение проходит по назначению: <see cref="Step"/> меняет
    /// мир, <see cref="Present"/> готовит его показ.
    ///
    /// ПОЧЕМУ НЕ НАЗВАН ПО ЦИКЛУ. Цикл уже назван — <see cref="UpdateCycle.Process"/>, —
    /// и второе имя для той же частоты только запутало бы. Здесь важна не частота, а то,
    /// что проход не вправе менять состояние мира: исход партии от него зависеть не должен.
    ///
    /// КОГДА ЗОВЁТСЯ. В графическом цикле, после <see cref="Step"/> того же кадра, и только
    /// у систем физического цикла: системе, объявившей <see cref="UpdateCycle.Process"/>,
    /// второй проход не нужен — её <see cref="Step"/> и так идёт раз в кадр.
    /// </summary>
    public virtual void Present(double dt) { }

    /// <summary>
    /// Система объявила проход показа. Выясняется однажды, при создании: обходить состав
    /// систем с проверкой на каждом кадре незачем, а требовать от автора системы отдельного
    /// признака — значит завести признак, который забудут выставить.
    /// </summary>
    internal bool Presents { get; }

    protected GameSystem()
    {
        Presents = GetType().GetMethod(nameof(Present), new[] { typeof(double) })?.DeclaringType
                   != typeof(GameSystem);
    }

    /// <summary>
    /// Записать краткое состояние системы в игровой снимок. Сборщик вызывает метод
    /// только во время явно начатого perf-среза и не чаще выбранного интервала.
    ///
    /// Раздел уже отделён от данных других систем. В него следует помещать агрегаты
    /// и короткие значения, подготовленные обычным шагом системы; повторный обход мира,
    /// ссылки на Godot-объекты и коллекции неограниченного размера здесь недопустимы.
    /// </summary>
    public virtual void CaptureSnapshot(JsonObject data) { }
}
