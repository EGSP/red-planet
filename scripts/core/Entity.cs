using Godot;

/// <summary>
/// Объект, который сам объявляет, в игре он ещё или уже нет.
///
/// ЗАЧЕМ. Прежде живость выясняли у движка: <see cref="GodotObject.IsInstanceValid"/> плюс
/// <see cref="Node.IsQueuedForDeletion"/> на каждой проверке. Оба вызова переходят границу
/// между C# и Godot, а спрашивают их не по разу за кадр, а по разу на элемент каждого обхода
/// индекса — при двух сотнях сущностей это миллионы переходов в секунду. Замер показал
/// четверть времени главного потока на одном этом вопросе.
///
/// Ответ на него у сущности есть и без движка: она знает, что её вывели из игры. Признак
/// читается полем, поэтому обход индекса перестал обращаться к движку вовсе.
///
/// ГАРАНТИЯ СОХРАНЕНА. Замысел индекса состоял в том, что списывать сущность руками не нужно
/// (см. <see cref="Index"/>), и терять его нельзя. Поэтому признак снимается тремя путями:
/// прямым выводом из игры (<see cref="Entity.Retire"/>), снятием через <see cref="Index.Remove"/>
/// и выходом узла из дерева. Последнее и есть страховка: как бы узел ни ушёл — QueueFree,
/// RemoveChild или снос всей сессии, — <see cref="Node._ExitTree"/> случится, и сущность
/// объявит себя выбывшей сама.
/// </summary>
public interface ILive
{
    /// <summary>Сущность ещё в игре.</summary>
    bool Live { get; }

    /// <summary>
    /// Вывести из игры. Узла не касается: снятие с индекса и удаление узла — разные события,
    /// и второе бывает без первого (сущность сняли, а узел ещё догорает кадр).
    /// </summary>
    void Drop();
}

/// <summary>
/// Сущность мира: узел, чьё положение живёт в управляемой памяти, а не спрашивается у движка.
///
/// ПОЧЕМУ ПОЛОЖЕНИЕ КЭШИРУЕТСЯ. <c>Node2D.GlobalPosition</c> есть вызов через границу
/// C#↔Godot. Системы читают положение не единожды: выбор цели, обход соседей, расталкивание
/// и разведка спрашивают его по нескольку раз на сущность за шаг, а внутри перебора кандидатов
/// — по разу на кандидата. Замер отдал на одно это чтение 37 % времени главного потока.
/// Здесь оно становится чтением поля.
///
/// ЗАПИСЬ ОТКЛАДЫВАЕТСЯ ДО КОНЦА ШАГА. Поле правится сразу, а узел получает значение один
/// раз за шаг, проходом по тем сущностям, которые за этот шаг сдвинулись
/// (<see cref="Flush"/>). Причина в том, что за один шаг положение пишется по нескольку раз:
/// интегрирование, затем два прохода расталкивания, причём расталкивание правит и соседей.
/// Каждая такая запись есть переход границы C#↔Godot, и по замеру на записи положения и угла
/// уходила четверть собственного времени главного потока.
///
/// ЧТО ИЗ ЭТОГО СЛЕДУЕТ. Внутри шага узел показывает положение, каким оно было на конец
/// прошлого шага. Всё, что читает положение через поле — а это все системы, — видит верное
/// значение; всё, что спрашивает узел, обязано быть переведено на поле. Оставшиеся такие
/// места собраны в <c>docs/performance-plan.md</c>. К мигу отрисовки узел уже согласован:
/// проход выполняется в конце обоих циклов обновления.
///
/// ОТКУДА БЕРЁТСЯ НАЧАЛЬНОЕ ЗНАЧЕНИЕ. Из узла, при входе в дерево: сущность появляется
/// либо из сцены, где положение задано редактором, либо через Spawner, который выставляет
/// его до <c>AddChild</c>. Оба случая закрываются одной сверкой в <see cref="_EnterTree"/>.
///
/// ЧЕГО ДЕЛАТЬ НЕЛЬЗЯ. Писать положение через ссылку типа <see cref="Node2D"/> в обход этого
/// класса и двигать родительский слой: ни то, ни другое сюда не дойдёт, и поле разойдётся
/// с узлом. Расхождение ловит сверка <see cref="EntityAudit"/> под признаком отладки.
/// </summary>
public abstract partial class Entity : Node2D, ILive
{
    /// <summary>
    /// Сущности, сдвинувшиеся с прошлого прохода. Список один на всех и живёт не дольше кадра:
    /// его опустошает <see cref="Flush"/>. Хранить его у сессии было бы вернее по духу, но
    /// запись положения зовётся из глубины расчёта, и путь до сессии там стоил бы дороже
    /// самой записи.
    /// </summary>
    private static readonly System.Collections.Generic.List<Entity> Moved = new();

    private Vector2 _spot;
    private float _facing;
    private bool _dropped;

    /// <summary>Показ узла, каким его знает управляемый код, — см. <see cref="Visible"/>.</summary>
    private bool _shown = true;

    /// <summary>Сущность уже стоит в очереди на запись — второй раз добавлять её не нужно.</summary>
    private bool _queued;

    private bool _spotDirty;
    private bool _facingDirty;

    /// <summary>
    /// Родительский слой стоит в начале координат и не повёрнут, а значит мировое положение
    /// сущности совпадает с местным.
    ///
    /// ЗАЧЕМ РАЗЛИЧАТЬ. <c>Node2D.GlobalPosition</c> при записи не просто кладёт число:
    /// движок выводит местное положение из мирового, а для этого обращает преобразование
    /// родителя и перемножает матрицы. Запись местного положения такой работы не требует.
    /// По замеру при пятистах юнитах на записи мирового положения уходила пятая часть
    /// времени главного потока, тогда как сами сущности лежат в слоях площадки, которые
    /// стоят в начале координат и никогда не двигаются.
    ///
    /// Признак снимается при входе в дерево — один вопрос движку на сущность за всю её жизнь.
    /// Слой, который всё же окажется сдвинутым, вернёт запись на прежний путь.
    /// </summary>
    private bool _plainParent;

    /// <summary>
    /// Положение в мире. Скрывает одноимённое свойство узла намеренно: имя менять нельзя —
    /// им пользуются все интерфейсы сущностей (<see cref="IDamageable"/>, <see cref="IMobile"/>,
    /// <see cref="IVision"/>), и они же через это скрытие получают быстрое чтение.
    /// </summary>
    public new Vector2 GlobalPosition
    {
        get => _spot;
        set
        {
            // Запись без изменения значения — самый частый случай, а не редкий: система
            // движения выставляет положение каждому подвижному каждый шаг, включая тех,
            // кто стоит на месте, и делает это дважды за проход расталкивания. Сравнение
            // двух чисел здесь отменяет переход границы C#↔Godot, который по замеру
            // при трёх сотнях стоящих юнитов занимал пятую часть времени главного потока
            if (_spot == value)
                return;

            _spot = value;
            _spotDirty = true;
            Queue();
        }
    }

    /// <summary>
    /// Показ сущности. Скрывает одноимённое свойство узла по той же причине, что положение:
    /// <see cref="VisionSystem"/> назначает показ каждому противнику и каждому его снаряду
    /// раз в кадр, и почти всегда назначает то же самое значение, какое уже стоит. Проверку
    /// на совпадение Godot делает у себя, то есть уже после того, как переход границы
    /// C#↔Godot оплачен, а по замеру на эти записи уходило 7 % времени главного потока.
    ///
    /// ЗАПИСЬ НЕ ОТКЛАДЫВАЕТСЯ, в отличие от положения: показ меняется редко и по одному
    /// разу за шаг, откладывать здесь нечего. Поэтому узел всегда согласован с полем,
    /// и начальное значение просто перечитывается при входе в дерево.
    ///
    /// ЧЕГО ДЕЛАТЬ НЕЛЬЗЯ. Гасить сущность через ссылку типа <see cref="CanvasItem"/>
    /// в обход этого класса: поле разойдётся с узлом, и следующая запись того же значения
    /// будет отброшена как излишняя. Расхождение ловит <see cref="EntityAudit"/>.
    /// </summary>
    public new bool Visible
    {
        get => _shown;
        set
        {
            if (_shown == value)
                return;

            _shown = value;
            base.Visible = value;
        }
    }

    /// <summary>Угол корпуса. Кэшируется по той же причине и тем же способом, что и положение.</summary>
    public new float Rotation
    {
        get => _facing;
        set
        {
            if (_facing == value)
                return;

            _facing = value;
            _facingDirty = true;
            Queue();
        }
    }

    /// <summary>
    /// Точка в мировых координатах, заданная смещением от корпуса сущности. То же, что
    /// <see cref="Node2D.ToGlobal"/>, но по кэшированным полям: внутри шага узел ещё
    /// не согласован, и спрашивать преобразование у движка нельзя.
    /// </summary>
    public Vector2 ToWorld(Vector2 local) => _spot + local.Rotated(_facing);

    public bool Live => !_dropped;

    /// <summary>
    /// Записать в узлы всё, что сдвинулось за шаг. Зовёт композиционный корень в конце
    /// каждого цикла обновления — после систем и до того, как движок станет рисовать.
    /// </summary>
    public static void Flush()
    {
        for (int i = 0; i < Moved.Count; i++)
            Moved[i].WriteBack();

        Moved.Clear();
    }

    private void Queue()
    {
        if (_queued)
            return;

        _queued = true;
        Moved.Add(this);
    }

    private void WriteBack()
    {
        _queued = false;

        // Выбывшую сущность записывать некуда и незачем: её узел либо уже освобождён,
        // либо помечен на удаление и в этом кадре не рисуется
        if (_dropped)
        {
            _spotDirty = false;
            _facingDirty = false;
            return;
        }

        if (_spotDirty)
        {
            _spotDirty = false;

            if (_plainParent)
                Position = _spot;
            else
                base.GlobalPosition = _spot;
        }

        if (!_facingDirty)
            return;

        _facingDirty = false;
        base.Rotation = _facing;
    }

    public void Drop() => _dropped = true;

    /// <summary>
    /// Вернуть выбывшую сущность в игру.
    ///
    /// НУЖНО ТОЛЬКО ТОМУ, КТО ЖИВЁТ НАБОРОМ ГОТОВЫХ ЭКЗЕМПЛЯРОВ. Снаряд после попадания
    /// объявляется выбывшим, но узел его не освобождается и достаётся следующему выстрелу
    /// (<see cref="ProjectileSystem"/>). Всем прочим сущностям возврат запрещён: выбытие
    /// у них означает гибель, о которой уже разосланы документы и снята подписка.
    ///
    /// Признак снимается ДО записи положения: <see cref="WriteBack"/> выбывшую сущность
    /// в узел не пишет, и порядок наоборот оставил бы снаряд там, где он лежал в наборе.
    /// </summary>
    protected void Revive() => _dropped = false;

    /// <summary>
    /// Вход в дерево. Значение берётся у узла лишь тогда, когда своего ещё нет: сущность
    /// из сцены получает положение от редактора, а созданная Spawner'ом — до <c>AddChild</c>,
    /// и во втором случае у узла стоит ноль, которым затирать своё значение нельзя.
    /// </summary>
    public override void _EnterTree()
    {
        _plainParent = GetParent() is not Node2D parent
                       || parent.GlobalTransform == Transform2D.Identity;

        // Показ пишется сразу, поэтому узел здесь верней поля: сущность из сцены могла быть
        // погашена редактором, а набор готовых экземпляров возвращает узел в том виде,
        // в каком его оставил прошлый выстрел
        _shown = base.Visible;

        if (_spotDirty || _facingDirty)
            WriteBack();
        else
            Sync();
    }

    /// <summary>Выход из дерева означает уход из игры — см. страховку в <see cref="ILive"/>.</summary>
    public override void _ExitTree() => Drop();

    /// <summary>
    /// Вывести сущность из игры: объявить выбывшей и убрать узел.
    ///
    /// ЕДИНЫЙ ПОРЯДОК ДЛЯ ВСЕХ. Прежде это место повторялось у юнита, постройки, каркаса,
    /// плана и снаряда: три строки, гасящие обработку, показ и сам узел. Повторялось оно
    /// с расхождениями, и добавить к порядку четвёртое действие — объявление о выбытии —
    /// значило бы вписать его в пять файлов.
    ///
    /// Показ гасится до удаления, потому что удаление отложенное: без этого по узлу прошёл бы
    /// ещё один кадр отрисовки.
    /// </summary>
    public void Retire()
    {
        Drop();
        SetProcess(false);
        Visible = false;
        QueueFree();
    }

    /// <summary>
    /// Перечитать положение и угол у узла. Нужно там, где узел двигали мимо этого класса:
    /// при входе в дерево и в сверке отладки.
    /// </summary>
    public void Sync()
    {
        _spot = base.GlobalPosition;
        _facing = base.Rotation;
        _spotDirty = false;
        _facingDirty = false;
    }

    /// <summary>Положение узла — то, что видит движок. Нужно одной лишь сверке.</summary>
    internal Vector2 NodeSpot => base.GlobalPosition;

    /// <summary>Показ узла — то, что видит движок. Нужно одной лишь сверке.</summary>
    internal bool NodeShown => base.Visible;

    /// <summary>Перечитать показ у узла. Нужно сверке отладки при найденном расхождении.</summary>
    internal void SyncShown() => _shown = base.Visible;
}
