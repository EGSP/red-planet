using Godot;

/// <summary>
/// Единицы измерения и мировые константы.
/// 1 unit = 64 px. Все размеры сущностей кратны юниту.
/// </summary>
public static class Const
{
    public const int Unit = 64;

    /// <summary>Мир — квадрат 41x41 клетка с центром в (0,0).</summary>
    public const int WorldRadiusCells = 20;

    // ── Навигация и постановка ────────────────────────────────────────────────────
    //
    // Клетка застройки правилом постановки быть перестала: здания ставятся в произвольной
    // точке и лишь не пересекаются друг с другом. Сетка осталась двум потребителям —
    // растру навигации, где она вчетверо мельче, и раскладке визуальных ориентиров.

    /// <summary>Ячейка навигационного растра. Четыре на клетку застройки.</summary>
    public const int NavCell = 16;

    /// <summary>Клеток застройки по стороне мира.</summary>
    public const int WorldCells = WorldRadiusCells * 2 + 1;

    /// <summary>Сторона мира в пикселях.</summary>
    public const int WorldSizePx = WorldCells * Unit;

    /// <summary>Ячеек навигации по стороне мира.</summary>
    public const int NavWidth = WorldSizePx / NavCell;

    /// <summary>
    /// Обязательный зазор между строениями, пикселей. Един для всех.
    ///
    /// Назначение — гигиена растра, а не гарантия прохода. При нулевом зазоре два
    /// соприкасающихся здания дают щели в одну ячейку и диагональные протечки: путь по ним
    /// находится, а пройти по ним нельзя. Зазор в ячейку этот класс ситуаций убирает.
    ///
    /// Проход зазор НЕ гарантирует: он меньше диаметра юнита, поэтому плотный ряд зданий
    /// образует стену. Так и задумано — проходимость решает поле клиренса, а возможность
    /// огородиться остаётся за игроком.
    /// </summary>
    public const float BuildMarginPx = NavCell;

    /// <summary>
    /// Насколько далеко место готово отъехать от курсора, прилипая к соседу, пикселей.
    ///
    /// Половина клетки застройки выбрана из смысла порога: сдвиг такой величины означает,
    /// что курсор стоял у самого края чужого места, и намерение игрока прочитывается
    /// однозначно. Глубже начинается область, откуда ближайший свободный край далеко,
    /// и подменять там выбор игрока нельзя.
    /// </summary>
    public const float ClingLimitPx = Unit * 0.5f;

    /// <summary>
    /// Добавок к промежутку между местами раскладки, пикселей.
    ///
    /// ЗАЧЕМ. Промежуток равен размеру строения с обязательным зазором, то есть ровно тому
    /// расстоянию, на котором раздутые прямоугольники соседей касаются краями. Касание
    /// пересечением не считается, но после округлений равенство читается то так, то иначе,
    /// и соседи в плотном ряду через раз отказывались вставать.
    ///
    /// Полпикселя снимают вопрос целиком и на глаз неразличимы: клетка застройки — 64 px.
    /// </summary>
    public const float PatternSlackPx = 0.5f;

    /// <summary>
    /// Сколько мест паттерн раскладывает за одно перетаскивание, не больше.
    ///
    /// Предел нужен не отрисовке, а миру: каждое принятое место становится каркасом, то есть
    /// нодой, препятствием и пересборкой растра навигации. Сотня — заведомо больше, чем
    /// осмысленно поставить одним движением, и заведомо меньше, чем заметно по кадрам.
    /// </summary>
    public const int PatternLimit = 100;

    /// <summary>Левый верхний угол мира в пикселях.</summary>
    public static Vector2 WorldMin => new(-WorldRadiusCells * Unit, -WorldRadiusCells * Unit);

    public static Rect2 WorldBounds => new(WorldMin, new Vector2(WorldSizePx, WorldSizePx));

    // ── Точки метала ──────────────────────────────────────────────────────────────
    //
    // Расставляются один раз при создании мира и больше не меняются: точка вечна,
    // и восстанавливать в ней нечего. Все точки одинаковы — богатство числом не задаётся.
    // Разницу между ними создаёт только положение: до дальней дольше идти и труднее
    // её прикрыть, и этого достаточно, чтобы выбор «куда расширяться» имел цену.

    /// <summary>Сколько точек метала на карте.</summary>
    public const int MetalSpotCount = 14;

    /// <summary>Дальше этого радиуса точек нет: у самой границы мира их не разместить.</summary>
    public const int MetalSpotFieldRadius = 15;

    /// <summary>Ближе этого радиуса точек нет — иначе они встанут прямо в базу.</summary>
    public const int MetalSpotBaseClearance = 4;

    /// <summary>Минимальное расстояние между точками, клеток: иначе они собираются в кучу.</summary>
    public const int MetalSpotSpacing = 3;

    // Сколько точек гарантированно лежит рядом со стартом. Без гарантии случайная раскладка
    // иногда оставляет начало вовсе без метала, и партия проиграна ещё до первого решения
    public const int MetalSpotStartCount = 3;
    public const int MetalSpotStartRadius = 8;

    /// <summary>На каком расстоянии бот держится от коммандера, когда идёт следом.</summary>
    public static float FollowDistancePx => Unit * 3f;

    // Врождённый запас коммандера, как storage у base_commander в celestial / PA Titans.
    // Энергия на сжатой шкале (÷100): 45000 → 450. Дальше потолок поднимают склады
    // (metal_storage / energy_storage) — без демпфера любой всплеск спроса мгновенно
    // роняет производительность базы
    public const float BaseMetalCapacity = 1500f;
    public const float BaseEnergyCapacity = 450f;

    // Враги приходят из-за поля точек: дальние точки лежат на линии их подхода,
    // и экстрактор на краю карты обороняется тяжелее, чем экстрактор у базы
    public const float EnemyRingFactor = 1.3f;

    // Темп восполнения потерь противника. Объём давления числом здесь больше не задаётся:
    // он выводится из террора бюджетом мощи — см. PressureSettings
    public const float EnemySpawnDelay = 10f;
    public const float EnemyFirstDelay = 30f;

    /// <summary>Как часто юнит переигрывает выбор цели, секунд. Одинаково для обеих сторон.</summary>
    public const float RetargetDelay = 1.5f;

    /// <summary>
    /// Доля прочности готовой постройки, которая есть у её каркаса.
    /// Недостроенное ломается заметно легче — стройка под обстрелом должна быть рискованной.
    /// </summary>
    public const float BlueprintHealthFactor = 0.4f;

    /// <summary>Радиус окружности появления врагов в пикселях.</summary>
    public static float EnemySpawnRadiusPx => MetalSpotFieldRadius * EnemyRingFactor * Unit;

    /// <summary>
    /// Точка высадки — центр стартовой клетки, вокруг которой встаёт база.
    ///
    /// От неё, а не от текущего центра базы, отсчитывается удалённость построек для террора.
    /// Центр базы смещается по мере роста, и тогда дальняя постройка со временем сама собой
    /// становилась бы ближней — то есть расширение удешевляло бы уже сделанное расширение.
    /// Точка высадки неподвижна, поэтому удалённость означает ровно то, что должна.
    /// </summary>
    public static Vector2 LandingPoint => CellCenter(Vector2I.Zero);

    /// <summary>
    /// Центр клетки застройки. Правилом постановки клетка быть перестала, но осталась
    /// удобной единицей раскладки: по ней выравниваются точки метала и стартовые позиции,
    /// и мир от этого читается как упорядоченный, а не как рассыпанная горсть.
    /// </summary>
    public static Vector2 CellCenter(Vector2I cell) =>
        new(cell.X * Unit + Unit * 0.5f, cell.Y * Unit + Unit * 0.5f);
}
