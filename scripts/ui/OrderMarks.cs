using Godot;

/// <summary>
/// Значки видов приказа в точках очереди.
///
/// ЧЕМ ЭТО БЫЛО РАНЬШЕ. Значок собирался из фигур: крест из двух отрезков у атаки,
/// прямоугольник у стройки, кольцо у патруля. Различить их удавалось плохо, а стоили они
/// от двух до четырёх фигур на каждую точку очереди. Здесь значок есть картинка из общего
/// массива изображений, то есть один экземпляр сетки, и вид приказа читается рисунком,
/// а не сочетанием отрезков.
///
/// ПОДПИСЕЙ БОЛЬШЕ НЕТ. Название приказа выводилось текстом рядом с точкой, и каждый символ
/// стоил своей команды отрисовки, разрывая объединение соседних фигур. Картинка говорит
/// то же самое и не требует шрифта.
///
/// ЧТО ОСТАЛОСЬ ЗА ПРЕДЕЛАМИ ЗНАЧКА. Круг области рисуется отдельно — см.
/// <see cref="OrderOverlay"/>: важен не центр области, а её граница, и заменять её значком
/// нельзя.
/// </summary>
public static class OrderMarks
{
    /// <summary>
    /// Поставить значок приказа. Задаётся только плотность: текущий шаг очереди показывается
    /// ярче предстоящих, а пройденная часть кольца патруля — бледнее всех.
    ///
    /// ОТТЕНОК ВИДА ПРИКАЗА НА КАРТИНКУ НЕ НАКЛАДЫВАЕТСЯ. Картинки набора цветные сами
    /// по себе, и умножение на оттенок сбивало бы их собственный рисунок, а вид приказа
    /// картинка называет и без окраски. Цвет вида остаётся у линии очереди и у круга области.
    /// </summary>
    public static void Draw(Vector2 at, OrderKind kind, float alpha,
        WorldLayer layer = WorldLayer.Overlay)
    {
        if (alpha <= 0f)
            return;

        ShapeMesh.Icon(at, kind, new Color(1f, 1f, 1f, alpha), layer);
    }
}
