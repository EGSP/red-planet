using Godot;

/// <summary>
/// Общая раскладка постоянных блоков, стоящих стопкой у верхнего края по центру:
/// <see cref="EventBar"/>, <see cref="ResourceBar"/> и <see cref="PortalCountdownBar"/>.
///
/// ПОЧЕМУ ЭТО ВЫНЕСЕНО ИЗ САМИХ БЛОКОВ. Каждый из них есть отдельный слой и знает только
/// себя, а стопка есть свойство их совокупности. Пока отступ каждого яруса задавался
/// числом в его собственном коде, эти числа приходилось согласовывать вручную при любой
/// правке высоты, и расхождение выражалось щелью на экране.
///
/// ВЫСОТА ЯРУСА ИЗМЕРЯЕТСЯ, А НЕ ВЫЧИСЛЯЕТСЯ. Она складывается из шрифтов, отступов темы
/// и полей панели, то есть из величин, которых код блока не знает. Поэтому ярус берёт
/// нижний край соседа сверху готовым числом и прижимается к нему.
///
/// ШИРИНА ЖЕ ЗАДАЁТСЯ ОДНА НА ВСЕХ. Блоки стоят один под другим, и разная ширина читается
/// как небрежность, а не как различие смысла. Каждый блок ставит эту ширину наименьшей
/// для своего содержимого, а внутренности растягивает по ней.
/// </summary>
public static class HudLayout
{
    /// <summary>Ширина всех блоков верхней стопки, пикселей.</summary>
    public const int CenterWidth = 620;

    /// <summary>Отступ верхнего яруса от края окна, пикселей.</summary>
    public const int TopMargin = 8;

    /// <summary>
    /// Нижний край панели в координатах слоя. Ноль означает, что раскладка ещё не посчитана:
    /// в первом кадре размеры контейнеров не известны.
    /// </summary>
    public static float BottomOf(Control panel) =>
        Alive.Is(panel) ? panel.GlobalPosition.Y + panel.Size.Y : 0f;

    /// <summary>
    /// Прижать ярус к нижнему краю соседа сверху. Отступ переписывается только при
    /// изменении: постоянная запись в тему заставляла бы пересчитывать раскладку
    /// каждый кадр без всякой на то причины.
    /// </summary>
    public static void StackUnder(MarginContainer margin, ref int current, float edge)
    {
        int top = edge > 0f ? Mathf.RoundToInt(edge) : TopMargin;

        if (top == current || !Alive.Is(margin))
            return;

        current = top;
        margin.AddThemeConstantOverride("margin_top", top);
    }
}
