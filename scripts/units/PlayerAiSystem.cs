using Godot;

/// <summary>
/// Распределение задач на стороне игрока: чем занять того, кому игрок ничего не приказал.
///
/// ЧТО ИСПОЛНИТЕЛЬ БЕРЁТ НА СЕБЯ САМ, А ЧТО ТОЛЬКО ПО ПРИКАЗУ. Прежде фабрикатор без дела
/// сам убегал строить и чинить через полкарты, и отряд строителей растекался по ней
/// сразу после того, как игрок его собрал. Теперь правило такое:
///
/// — СТРОЙКУ сам берёт только НЕПОДВИЖНЫЙ (башня-сборщик) и только в пределах манипулятора:
///   ему не нужно никуда бежать, он обслуживает то, что оказалось у него под рукой.
///   Подвижный строит по приказу — и это не ограничение, а смысл: постановка плана и есть
///   приказ строить, и отдаётся он тем же щелчком;
/// — РЕМОНТ сам берёт ЧИСТЫЙ РЕМОНТНИК, чей инструмент строить не умеет. Роль выводится
///   из снаряжения, а не задаётся признаком: рука, которой нельзя построить, заведена ровно
///   затем, чтобы чинить, и ждать на неё приказа незачем;
/// — ОГОНЬ по цели в пределах внимания берут все вооружённые: оборона не ждёт указаний.
///
/// ВСЁ САМОСТОЯТЕЛЬНОЕ ОГРАНИЧЕНО РАДИУСОМ ВНИМАНИЯ вокруг якоря (см. <see cref="IWorker.Anchor"/>),
/// а не вокруг текущего положения. Поэтому отлучка всегда возвращает исполнителя туда,
/// куда его послали, и цепочка «нашёл цель — отошёл — от новой позиции нашёл следующую»
/// больше не уводит отряд с рубежа.
///
/// ОДНА СИСТЕМА НА ПОДВИЖНЫХ И НЕПОДВИЖНЫХ. Башня-сборщик обслуживается здесь же, а не
/// отдельной системой: она есть тот же фабрикатор, только здание. Различаются они пределами
/// поиска, и те выводятся из определения — из подвижности и дальности инструмента.
///
/// Сопровождение — не работа, а отсутствие работы: юнит с таким приказом считается свободным
/// и бросит его, как только появится что-то полезное. Поэтому юниты не толкутся на месте
/// и не убегают от базы, оставшись без дела.
///
/// ПАРА К <see cref="EnemyAiSystem"/>, А НЕ ЧАСТНЫЙ СЛУЧАЙ ОБЩЕЙ СИСТЕМЫ. Класс юнита один
/// на обе стороны, но задачи сторонам раздают две равноправные системы, названные по стороне:
/// принципы выдачи у них разные и будут расходиться дальше.
///
/// Исполнение приказа ни одной из них не принадлежит: приказ отрабатывает сама сущность,
/// а зовёт её единственная <see cref="OrderSystem"/>.
///
/// Коммандер сюда не входит: он единственный, кем игрок распоряжается напрямую,
/// и подставлять ему занятия помимо приказов нельзя.
/// </summary>
public partial class PlayerAiSystem : GameSystem
{
    public override void Step(double dt)
    {
        foreach (var worker in GM.Index.All<IWorker>())
        {
            if (worker.Definition == null || worker.Faction != Faction.Player
                || worker is Commander)
                continue;

            if (worker is IMobile { Movement.Leaving: true })
                continue;

            // Отсчёт до переигровки цели ведём у всех подвижных: он нужен и тому,
            // кто сейчас идёт следом, — иначе цель искалась бы каждый кадр
            if (worker is Unit unit)
                unit.TickRetarget(dt);

            if (!IsFree(worker))
                continue;

            var order = ChooseJob(worker);

            // Недопустимый вид приказа очередь не примет — второй сети не нужно.
            // Именно поэтому башне не достанется ни атака, ни сопровождение
            if (order != null)
            {
                order.Leashed = true;
                worker.Orders.TrySet(order);
            }
        }
    }

    /// <summary>
    /// Свободен тот, у кого нет приказа или кто просто идёт следом. У неподвижного
    /// сопровождения не бывает, поэтому для него условие сводится к отсутствию приказа.
    /// </summary>
    private static bool IsFree(IWorker worker)
    {
        var orders = worker.Orders;

        return orders.Idle || orders.Current.Kind == OrderKind.Follow;
    }

    private Order ChooseJob(IWorker worker)
    {
        var def = worker.Definition;
        var anchor = worker.Anchor;

        // Стройка сама собой достаётся неподвижному: бежать ему некуда, он обслуживает
        // то, что попало под манипулятор
        if (def.CanBuild && !def.IsMobile)
        {
            var site = Jobs.NearestSite(worker.GlobalPosition, def.WorkRangePx);

            if (site != null)
                return Order.Work(OrderKind.Build, site);
        }

        if (SelfRepairs(def))
        {
            var damaged = Jobs.NearestDamaged(anchor, RepairReach(def), def.CanRepairUnits);

            if (damaged != null)
                return Order.Repair(damaged);
        }

        if (worker is Unit unit && ChooseTarget(unit) is { } attack)
            return attack;

        var commander = GM.Commander;

        // Неподвижному идти некуда, а уже идущему следом приказ переигрывать незачем:
        // точка обновляется сама
        if (!def.IsMobile || commander == null
            || worker.Orders.Current?.Kind == OrderKind.Follow)
            return null;

        // Посланный игроком остаётся там, куда его послали. За коммандером идёт только тот,
        // кому не приказывали ничего: иначе отряд, оставленный держать рубеж, снимался бы
        // с него сам, едва закончив дело, и якорь внимания не значил бы ничего
        if (worker is Unit { Posted: true })
            return null;

        return Order.Follow(commander);
    }

    /// <summary>
    /// Берётся ли исполнитель за ремонт без приказа. Неподвижный берётся всегда — он для
    /// того и поставлен; подвижный — только если строить его рукой нельзя, то есть если
    /// он ремонтник, а не строитель.
    /// </summary>
    private static bool SelfRepairs(UnitDefinition def) =>
        def.CanRepair && (!def.IsMobile || !def.CanBuild);

    /// <summary>
    /// Докуда искать повреждённое. У подвижного предел — радиус внимания вокруг якоря:
    /// бегать через полкарты чинить забор не то поведение, которого от него ждёшь.
    /// У неподвижного предел — длина манипулятора: дальше он не дотянется.
    /// </summary>
    private static float RepairReach(UnitDefinition def) =>
        def.IsMobile ? def.AttentionRadiusPx : def.WorkRangePx;

    /// <summary>
    /// Кого бить, если работы нет. Цель ищется ТОЛЬКО В ПРЕДЕЛАХ ВНИМАНИЯ вокруг якоря —
    /// этим выдача задач на стороне игрока и отличается от выдачи у противника, который
    /// идёт к базе через всю карту. Без предела оборона разбежалась бы за одиночками
    /// по всему полю, и рубеж держать стало бы некому.
    ///
    /// Приказ, выданный здесь, помечается поводком (см. <see cref="Order.Leashed"/>):
    /// цель, ушедшая за пределы внимания, его обрывает, и юнит возвращается к якорю.
    /// Прямое указание игрока поводка не имеет и ведёт юнита за целью сколько угодно далеко.
    /// </summary>
    private Order ChooseTarget(Unit unit)
    {
        if (unit.Weapon == null || !unit.NeedsTarget)
            return null;

        var victim = Targeting.Nearest(unit.Anchor, Faction.Hostile,
            unit.Definition.AttentionRadiusPx);

        if (victim is not Node2D node)
            return null;

        unit.NoteTargeted();

        return Order.Attack(node);
    }
}
