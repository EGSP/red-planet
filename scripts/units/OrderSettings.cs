using Godot;

/// <summary>
/// Настройка приказов: величины, которые подбираются по ощущению от игры, а не выводятся
/// из правил.
///
/// ПОЧЕМУ РЕСУРС, А НЕ КОНСТАНТЫ. Сколько юнит стоит на месте в области патруля и с какого
/// радиуса круг считается областью — вопросы вкуса, и ответ на них находится подбором:
/// покрутить, посмотреть, поправить. Константа требует пересборки проекта на каждый оборот
/// этого цикла, тогда как ресурс правится в инспекторе рядом с остальным тюнингом
/// (<c>resources/tuning/orders.tres</c>), как это уже сделано для навигации и мира.
///
/// Действующий набор живёт в <see cref="Order.Settings"/>: его спрашивают и исполнители
/// приказов, и разбор жеста, то есть код, которому менеджер сессии не нужен.
/// </summary>
[Tool]
[GlobalClass]
public partial class OrderSettings : Resource
{
    [ExportGroup("Патруль")]

    /// <summary>
    /// Сколько секунд исполнитель стоит на выбранном месте внутри области патруля, прежде
    /// чем выбрать следующее. Ноль означает непрерывную беготню — на глаз это дёрганье.
    /// </summary>
    [Export(PropertyHint.Range, "0,15,0.5")]
    public float PatrolPause = 3f;

    /// <summary>
    /// Сколько секунд исполнитель проводит в области патруля, прежде чем идти дальше
    /// по кольцу.
    ///
    /// Ограничение применяется только тогда, когда в маршруте есть куда идти дальше:
    /// одиночный патруль не кончается вовсе, и ограничивать его нечем и незачем.
    /// </summary>
    [Export(PropertyHint.Range, "5,180,1")]
    public float PatrolDwell = 30f;

    [ExportGroup("Указание области")]

    /// <summary>
    /// Наименьший радиус области приказа, пикселей. Круг мельче считается указанием точки:
    /// дрожание руки на десяток пикселей означает щелчок, а обходить область размером
    /// с собственный корпус юниту негде.
    /// </summary>
    [Export(PropertyHint.Range, "16,512,1")]
    public float MinAreaRadiusPx = Const.Unit * 1.5f;
}
