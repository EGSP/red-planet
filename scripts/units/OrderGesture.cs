using System.Collections.Generic;
using Godot;

/// <summary>
/// Каким способом вид приказа указывается протаскиванием. У каждого вида способ ровно один,
/// и это свойство самого вида, а не выбор игрока: круг у атаки означает «бей всё внутри»,
/// линия у движения — «встаньте вдоль неё», а у ремонта и сопровождения смысла в жесте нет
/// вовсе, потому что цель им нужна под указателем.
/// </summary>
public enum GestureForm
{
    /// <summary>Растягивать нечего: приказ отдаётся сразу по нажатию.</summary>
    Point,

    /// <summary>Круг от точки нажатия до указателя.</summary>
    Area,

    /// <summary>Линия произвольной формы, повторяющая жест целиком.</summary>
    Line,
}

/// <summary>
/// Жест указания приказа: что игрок нарисовал между нажатием и отпусканием кнопки.
///
/// ЗАЧЕМ ОТДЕЛЬНОЙ СУЩНОСТЬЮ. Состояние жеста — это восемь значений, живущих вместе и ровно
/// столько, сколько длится нажатие: вид приказа, точка начала, решение о дописывании,
/// происхождение вида, записанная линия, места вдоль неё и приказ одиночного исполнителя,
/// ведомый прямо по ходу. Держать их полями системы означало бы, что читать и обнулять их
/// приходится в шести разных местах разбора нажатий, а забытое обнуление проявляется
/// на следующем жесте.
///
/// ЗДЕСЬ НЕТ ВЫДАЧИ ПРИКАЗОВ. Жест отвечает на вопрос «что нарисовано», а решение, какой
/// приказ из этого следует и кому он уйдёт, принимает <see cref="CommandSystem"/>: раздача
/// требует выделения, набора приказов и веток очередей, до которых жесту дела нет.
/// </summary>
public sealed class OrderGesture
{
    /// <summary>
    /// Дальше этого протаскивания жест считается указанием области или линии, а не щелчком
    /// по точке. Порог тот же по смыслу, что у рамки выделения, но свой: промах рукой при
    /// щелчке и намеренное растягивание различаются в этих двух местах по-разному,
    /// и связывать их одним числом незачем.
    /// </summary>
    public const float Threshold = 12f;

    /// <summary>
    /// Наименьший радиус, при котором растягивание считается указанием области. Порог здесь
    /// строже общего: щелчок от области отличает уже <see cref="Threshold"/>, а этот порог
    /// отделяет намеренную область от круга, в котором исполнителю нечего делать. Живёт
    /// в <see cref="настройках приказов"/> — величина мировая, а не свойство жеста.
    /// </summary>
    public static float MinRadius => Order.Settings.MinAreaRadiusPx;

    private readonly List<Vector2> _path = new();
    private readonly List<Vector2> _spots = new();

    /// <summary>Вид приказа, который отдаст этот жест.</summary>
    public OrderKind Kind { get; private set; }

    /// <summary>Точка нажатия: центр круга либо начало линии.</summary>
    public Vector2 Anchor { get; private set; }

    /// <summary>
    /// Дописывается ли приказ к прежним. Читается в момент НАЖАТИЯ и держится до конца
    /// жеста: между нажатием и отпусканием игрок успевает отпустить Shift, а решение
    /// принимается один раз — тогда, когда жест начат. Иначе одиночный исполнитель,
    /// которого рисование ведёт прямо по ходу, менял бы это решение посреди дела.
    /// </summary>
    public bool Queue { get; private set; }

    /// <summary>
    /// Вид задан игроком клавишей, а не выведен из цели под указателем. Различие нужно
    /// в двух местах: короткий жест отдаёт приказ разными путями (заданный вид против
    /// выведенного из контекста), а по окончании режим приказа держится только у заданного.
    /// </summary>
    public bool Forced { get; private set; }

    /// <summary>Нарисованная линия. Пуста, пока жест не начат.</summary>
    public IReadOnlyList<Vector2> Path => _path;

    /// <summary>
    /// Приказ одиночного исполнителя, ведомый прямо по ходу рисования. У одного юнита
    /// распределять нечего, и линия для него означает не строй, а непрерывно уточняемую
    /// точку назначения.
    /// </summary>
    public Order Drawn { get; set; }

    /// <summary>Кому этот приказ отдан. Нужен, чтобы проверить, не исполнен ли он уже.</summary>
    public IOrderable Actor { get; set; }

    /// <summary>
    /// Ведущего уже искали. Признак нужен потому, что искать его следует ровно один раз
    /// и не в начале жеста: пока линия коротка, жест неотличим от щелчка, и приказ выдавать
    /// рано, — а когда она выросла, перебирать выделение каждый кадр незачем. Отрицательный
    /// исход поиска (исполнителей не один) тоже окончателен: состав выделения посреди жеста
    /// не меняется.
    /// </summary>
    public bool Led { get; set; }

    /// <summary>Каким способом указывается вид приказа.</summary>
    public static GestureForm FormOf(OrderKind kind) => kind switch
    {
        OrderKind.Move => GestureForm.Line,
        OrderKind.Attack or OrderKind.Build or OrderKind.Patrol => GestureForm.Area,
        _ => GestureForm.Point,
    };

    /// <summary>Способ указания у начатого жеста.</summary>
    public GestureForm Form => FormOf(Kind);

    public void Begin(OrderKind kind, Vector2 anchor, bool queue, bool forced)
    {
        End();

        Kind = kind;
        Anchor = anchor;
        Queue = queue;
        Forced = forced;

        if (Form == GestureForm.Line)
            _path.Add(anchor);
    }

    /// <summary>Убрать след жеста. Приказ к этому мигу либо отдан, либо отменён.</summary>
    public void End()
    {
        _path.Clear();
        _spots.Clear();
        Drawn = null;
        Actor = null;
        Led = false;
    }

    /// <summary>Записать положение указателя в линию, если он отошёл достаточно далеко.</summary>
    public void Track(Vector2 point) => DrawnPath.Append(_path, point);

    /// <summary>Радиус круга при указателе в этой точке.</summary>
    public float RadiusTo(Vector2 point) => Anchor.DistanceTo(point);

    /// <summary>
    /// Растянут ли жест настолько, чтобы считаться указанием области или линии. У круга
    /// мерой служит расстояние от центра, у линии — её длина: короткий круг и короткая
    /// линия одинаково означают, что игрок просто щёлкнул.
    /// </summary>
    public bool Stretched(Vector2 point) => Form switch
    {
        GestureForm.Area => RadiusTo(point) >= MinRadius,
        GestureForm.Line => DrawnPath.Length(_path) >= Threshold,
        _ => false,
    };

    /// <summary>
    /// Места вдоль линии для указанного числа исполнителей. Список принадлежит жесту
    /// и перезаписывается при каждом обращении: считается он каждый кадр показа,
    /// и выделять под него память заново незачем.
    /// </summary>
    public List<Vector2> Spread(int count)
    {
        DrawnPath.Spread(_path, count, _spots);
        return _spots;
    }
}
