/// <summary>
/// Тот, кто сам находит себе работу инструментом: подвижный фабрикатор и неподвижная
/// башня-сборщик. Признак существует затем, чтобы система выдачи задач обходила один разрез
/// вместо двух и раздавала занятия по единым правилам.
///
/// ЧЕМ ЭТИ ДВОЕ РАЗЛИЧАЮТСЯ. Ничем, кроме чисел определения. Башня — это тот же фабрикатор,
/// только здание: работу он делает тем же инструментом и по тому же порядку предпочтений,
/// а разница в том, что подвижный к работе идёт, а неподвижный ждёт, пока работа окажется
/// в пределах манипулятора. Оба этих обстоятельства выводятся из определения — скорости
/// и дальности инструмента, — поэтому отдельной системы для башни не нужно.
///
/// Определение здесь добавлено к <see cref="IOrderable"/> именно поэтому: выбор занятия
/// целиком опирается на то, чем сущность снабжена, и других сведений ему не требуется.
/// </summary>
public interface IWorker : IOrderable
{
    UnitDefinition Definition { get; }
}
