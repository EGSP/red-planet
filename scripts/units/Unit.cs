using Godot;

/// <summary>
/// Юнит с очередью приказов. Движется к цели, а войдя в радиус инструмента —
/// подключается к узлу работы. Сам ресурсы не двигает: только сообщает свою мощность.
///
/// Он же цель для чужой стороны и он же носитель ствола, если ствол задан справочником.
/// Огонь ведётся при любом приказе, кроме работы: занятие у исполнителя одно в единицу
/// времени, и стройка из этого правила не изъята — см. <see cref="CanFire"/>.
///
/// Приказы юнит только ИСПОЛНЯЕТ. Кто их раздаёт — игрок через CommandSystem или мозговая
/// система — его не касается, а чего ему отдать нельзя, отсекает набор AllowedOrders.
///
/// ОДИН КЛАСС НА ОБЕ СТОРОНЫ. Отдельного класса Enemy больше нет: противник — такой же юнит,
/// и различие сторон выражается полем Faction, а не типом узла. Раньше два класса повторяли
/// друг за другом подход к цели, доворот, дистанцию остановки, гибель и отрисовку, причём
/// с расхождениями в мелочах, — а расходились они именно потому, что правку вносили в один
/// файл из двух. Из этого следует и правило для систем: сторону надо спрашивать у сущности,
/// а не выводить из того, в каком разрезе она нашлась.
/// </summary>
public partial class Unit : Entity, IFacing, IDamageable, IArmed, IEconomyActor, IVision,
    IRepairable, IOrderable, IWorker, IMobile
{
    /// <summary>
    /// Определение. Ставит Spawner при создании: узел юнита собственной сцены не имеет,
    /// и связать его со справочником больше некому.
    /// </summary>
    public UnitDefinition Definition { get; set; }

    public int Id { get; set; }

    public OrderQueue Orders { get; }

    /// <summary>
    /// Намерение двигаться. Сам юнит себя не перемещает: он объявляет, куда хочет попасть,
    /// а путь, обход соседей и выталкивание из зданий делает <see cref="MovementSystem"/>.
    /// </summary>
    public Movement Movement { get; } = new();

    private WorkNode _attached;

    /// <summary>
    /// Куда рабочая рука тянется в этом шаге по заявке приказа. Пусто — заявки не было,
    /// и рука наводится на подключённый узел либо возвращается к оси корпуса.
    /// См. <see cref="AimWorkAt"/>.
    /// </summary>
    private Vector2? _workAim;

    /// <summary>Сколько осталось до переигровки цели. Ведёт мозговая система, она же и решает.</summary>
    private float _retarget;

    /// <summary>
    /// Цель, на которую исполнитель отвлёкся по дороге при приказе «идти с боем».
    /// Приказу не принадлежит: он общий на отряд, а отвлекается каждый на своё.
    /// </summary>
    private IDamageable _engaged;

    /// <summary>
    /// Сколько секунд подряд драться не с кем. По нему отличается конец боя от паузы
    /// между двумя противниками — см. <see cref="Regroup"/>.
    /// </summary>
    private float _calm;

    /// <summary>
    /// Приказ патруля, который исполняется прямо сейчас. По смене ссылки обнуляются
    /// случайная точка и отсчёт пребывания: они принадлежат одному приказу, и переход
    /// к следующей точке маршрута начинает счёт заново.
    /// </summary>
    private Order _patrolled;

    /// <summary>Случайное место внутри области патруля, к которому исполнитель идёт сейчас.</summary>
    private Vector2? _patrolPoint;

    /// <summary>Сколько секунд исполнитель провёл в области патруля.</summary>
    private float _patrolFor;

    /// <summary>Сколько секунд осталось стоять на выбранном месте внутри области.</summary>
    private float _patrolPause;

    /// <summary>
    /// Якорь внимания — см. <see cref="IWorker.Anchor"/>. Ставится при рождении и меняется
    /// только приказом игрока: занятие, выбранное самостоятельно, якоря не сдвигает,
    /// иначе отлучка за целью переносила бы участок вслед за юнитом.
    /// </summary>
    private Vector2 _anchor;

    /// <summary>
    /// Чужой приказ, в котором юнит помогает ведущему прямо сейчас. Своей очереди
    /// не принадлежит и в неё не попадает: помощь длится ровно пока идёт сопровождение.
    /// </summary>
    private Order _assisted;

    /// <summary>
    /// Инструменты юнита с их углами и перезарядками. Корпус при этом смотрит
    /// по <see cref="Node2D.Rotation"/> — туда, куда едет.
    /// </summary>
    public AimRig Aim { get; } = new();

    /// <summary>
    /// Экземпляр сцены изображения, если вид ею снабжён. Дочерний узел, поэтому поворот
    /// корпуса достаётся ему от <see cref="Node2D.Rotation"/> самого юнита; коду остаётся
    /// доворачивать инструменты.
    /// </summary>
    private UnitModel _model;

    /// <summary>
    /// Слой пометок поверх модели: полоса прочности и луч работы. Есть только у юнита
    /// с моделью — собственные команды узла выполняются до потомков, и без слоя пометки
    /// ушли бы под корпус (см. <see cref="ModelLayer"/>).
    /// </summary>
    private ModelLayer _marks;

    public Unit() => Orders = new OrderQueue(this);

    public Vector2 Anchor => _anchor;

    /// <summary>
    /// Юнита уже посылали. Признак нужен единственному правилу: приставленный к месту
    /// не бросает его ради коммандера, а тот, кому ничего не приказывали, идёт за ним,
    /// как и раньше. Без этого различия отряд, оставленный держать рубеж, уходил бы
    /// с него сам, едва закончив дело, — и якорь внимания не значил бы ничего.
    /// </summary>
    public bool Posted { get; private set; }

    /// <summary>
    /// Перенести якорь внимания. Зовёт тот, кто отдаёт приказ по воле игрока:
    /// <see cref="CommandSystem"/> и завод, раздающий новорождённым точку сбора.
    /// </summary>
    public void SetAnchor(Vector2 point)
    {
        _anchor = point;
        Posted = true;
    }

    /// <summary>
    /// Пора ли искать цель заново. Прежняя может быть и жива — просто рядом выросло что-то
    /// ближе, поэтому выбор переигрывается по таймеру, а не только по гибели цели.
    ///
    /// Свойство общее для обеих сторон: юнит игрока без работы выбирает цель по тем же
    /// правилам, что и юнит противника.
    /// </summary>
    public bool NeedsTarget => Orders.Idle || _retarget <= 0f;

    public void TickRetarget(double dt) => _retarget -= (float)dt;

    public void NoteTargeted() => _retarget = Const.RetargetDelay;

    public bool Idle => Orders.Idle;

    public Order Current => Orders.Current;

    public Health Health { get; protected set; }

    public int EntityId => Id;

    public string DefinitionId => Definition?.Id ?? "";

    public string DisplayName => Definition?.DisplayName ?? "юнит";

    /// <summary>
    /// Чья сторона. Ставит Spawner при создании, и после этого значение постоянно: разрезы
    /// индекса по стороне пересобираются раз в кадр и смены ключа посреди партии не терпят.
    ///
    /// Сторона не берётся из определения намеренно. Определение описывает, что сущность
    /// собой представляет, а кому она принадлежит — обстоятельство создания: один и тот же
    /// вид должна иметь возможность выставить любая сторона.
    /// </summary>
    public Faction Faction { get; set; } = Faction.Player;

    /// <summary>
    /// Откуда юнит взялся. Смысл имеет только у стороны противника: по этому признаку
    /// система давления отличает постоянный фон, который занимает место в бюджете,
    /// от волны, которая приходит поверх него. У стороны игрока значение не читается.
    /// </summary>
    public PressureOrigin Origin { get; set; } = PressureOrigin.Ambient;

    /// <summary>
    /// Приказы, которые очередь принимает. Состав задаёт секция <c>[orders]</c> определения
    /// в пересечении с тем, что юнит умеет по снабжению и классу.
    /// </summary>
    public virtual OrderSet AllowedOrders => Definition?.AcceptedOrders ?? OrderSet.None;

    /// <summary>
    /// Умеет, но в определении не разрешено — для панели со звёздочкой на время проверки
    /// полноты <c>[orders]</c>.
    /// </summary>
    public OrderSet SoftOrders => Definition?.SoftOrders ?? OrderSet.None;

    public SelectionGroup SelectionGroup => Definition?.SelectionGroup ?? SelectionGroup.Bots;

    /// <summary>Ось корпуса: куда юнит повёрнут целиком. От неё отсчитываются секторы.</summary>
    public float BodyFacing => Rotation;

    /// <summary>
    /// Ось главного ствола. У безоружного и у того, чей ствол закреплён жёстко,
    /// совпадает с осью корпуса.
    /// </summary>
    public float Facing => Aim.PrimaryWeapon?.World(Rotation) ?? Rotation;

    /// <summary>
    /// Куда смотрит изображение инструмента прямо сейчас. Ствол в приоритете перед рукой:
    /// подсказки и отладочная отрисовка спрашивают именно про него.
    /// </summary>
    public float ToolFacing =>
        (Aim.PrimaryWeapon ?? Aim.PrimaryWork)?.World(Rotation) ?? Rotation;

    /// <summary>
    /// Откуда вылетает снаряд. Модель отвечает на этот вопрос точкой
    /// <see cref="ModelTool.Muzzle"/>; без модели снаряд рождается в центре сущности,
    /// как было до её появления.
    ///
    /// РАСЧЁТ ЭТИМ НЕ МЕНЯЕТСЯ. Дальность, конус и выбор цели считаются от центра
    /// (<see cref="WeaponSystem"/>), поэтому вынос точки вылета сдвигает только то место,
    /// откуда показан уже состоявшийся выстрел.
    /// </summary>
    public Vector2 MuzzlePosition =>
        Aim.PrimaryWeapon?.Muzzle(GlobalPosition) ?? GlobalPosition;

    /// <summary>Откуда тянется луч работы. Без модели — от центра сущности.</summary>
    private Vector2 WorkBeamOrigin =>
        Aim.PrimaryWork?.Muzzle(GlobalPosition) ?? GlobalPosition;

    public float HitRadius => Definition?.RadiusPx ?? Const.Unit * 0.35f;

    public float VisionRadius => Definition?.VisionRadiusPx ?? 0f;

    /// <summary>
    /// Курс ремонта. Раньше его приходилось складывать из двух определений — прочность
    /// брать из одного, цену из другого, — потому что юнит описывался двумя файлами.
    /// Теперь оба числа лежат рядом, и курс считает само определение.
    ///
    /// У коммандера секции сборки нет — значит нет и цены, а без цены нет курса,
    /// и чинить его нечем. Он и не нуждается: урон он копит, но не гибнет.
    /// </summary>
    public float HealthPerMetal => Definition?.HealthPerMetal ?? 0f;

    public WeaponDefinition Weapon => Definition?.Weapon;

    /// <summary>
    /// Занят делом: подключён к узлу работы или чинит. Такому не до стрельбы.
    /// </summary>
    private bool Busy => Alive.Is(_attached) || RepairTarget != null;

    /// <summary>
    /// Стреляем всегда, кроме как за работой. Прежде огонь вели только без приказов,
    /// и сопровождающий отряд молча шёл мимо противника, потому что приказ у него был.
    /// Сопровождение и движение стрельбе не мешают: прикрытие строителей — не отдельная
    /// задача, а то, что вооружённый делает попутно.
    ///
    /// ПОЧЕМУ РАБОТА ОСТАЁТСЯ ИСКЛЮЧЕНИЕМ. Раздельные посадочные места (<see cref="AimRig"/>)
    /// позволяют стрелять и за работой: рука и ствол доворачиваются врозь. Запрет тем не
    /// менее сохранён и означает выбор занятия, а не нехватку снаряжения: строящий занят
    /// стройкой, и вести огонь заодно с нею ему не полагается. Одно занятие в один
    /// промежуток времени — общее правило исполнителя, и стрельба из него не изъята.
    ///
    /// Приказ атаки стреляет и на работе — но работать и атаковать одновременно нельзя,
    /// поэтому случай этот вырожденный и оставлен ради ясности правила.
    /// </summary>
    public virtual bool CanFire => Current?.Kind == OrderKind.Attack || !Busy;

    /// <summary>
    /// По приказу бьём именно назначенную жертву, даже если рядом мельтешит другая:
    /// приказ игрока не должен перебиваться выбором «кто ближе».
    /// </summary>
    public IDamageable FireTarget =>
        Current?.Kind == OrderKind.Attack ? Current.Entity as IDamageable : null;

    public override void _Ready()
    {
        Health ??= new Health(Definition?.MaxHealth ?? 80f);

        // Якорь ставится сразу: юнит, которому ещё ничего не приказывали, обязан
        // держаться места своего появления, а не расползаться за целями от него
        _anchor = GlobalPosition;

        AttachModel();

        // Стенд собирается после модели: части изображения связываются с инструментами
        // по идентификатору, и без поднятой сцены связывать было бы не с чем
        Aim.Bind(Definition, _model);
        Aim.Snap();
        Aim.Apply();

        QueueRedraw();
    }

    /// <summary>
    /// Поднять сцену изображения, если вид ею снабжён. Сторона к этому моменту уже
    /// выставлена Spawner-ом, поэтому окраска назначается сразу и больше не меняется:
    /// перейти на другую сторону сущность не может.
    /// </summary>
    private void AttachModel()
    {
        _model = ModelLibrary.Instantiate(Definition?.Model);

        if (_model == null)
            return;

        AddChild(_model);
        _model.ApplyTeamColor(TeamPalette.Of(Faction));

        // Слой добавляется ПОСЛЕ модели: порядок отрисовки задан порядком в дереве
        _marks = ModelLayer.Attach(this, PaintMarks, "Marks");
    }

    /// <summary>
    /// Пометки поверх корпуса: полоса прочности и луч к узлу работы. Без модели их рисует
    /// сам юнит в конце <see cref="_Draw"/>, с моделью — слой, идущий следом за ней.
    /// </summary>
    private void PaintMarks(CanvasItem canvas)
    {
        if (Definition == null)
            return;

        float radius = Definition.RadiusPx;

        HealthBar.Draw(canvas, Health, radius * 2.4f, -radius - 10f, Rotation);

        // Луч к узлу работы — это «работа идёт», а не приказ: очередь рисует оверлей.
        // Запасное изображение: вид, объявивший в модели луч, рисует его сам
        if (Alive.Is(_attached) && Aim.WorkBeam == null)
            ShapeDraw.Line(canvas, ToLocal(WorkBeamOrigin), ToLocal(_attached.GlobalPosition),
                DrawTheme.Line(VizKind.WorkBeamBuild));
    }

    /// <summary>
    /// Выровнять инструмент по корпусу без доворота. Нужен после внешней установки
    /// <see cref="Node2D.Rotation"/> при рождении: иначе ствол остаётся на старом угле.
    /// </summary>
    public void SnapToolToBody()
    {
        Aim.Snap();
        Aim.Apply();
    }

    /// <summary>
    /// Заявка в экономику. Чужая сторона своей экономики не ведёт, поэтому её юниты выходят
    /// сразу: ведомость в игре одна, и складывать в неё производство противника значило бы
    /// приписывать игроку чужой доход.
    /// </summary>
    public void Declare(EconomyLedger ledger)
    {
        if (Definition == null || Faction != Faction.Player)
            return;

        ledger.AddIncome(ResourceKind.Energy, Definition.EnergyProduction);
        ledger.AddIncome(ResourceKind.Metal, Definition.MetalProduction);

        // Ремонт — это и есть стройка тем же инструментом, поэтому и заявка та же:
        // метал по мощности руки плюс энергия на неё же
        if (RepairTarget != null && Definition.BuildTool is { } arm)
            Repair.Declare(ledger, arm.Power, arm.EnergyPerPower);
    }

    /// <summary>Своё производство идёт всегда, просадка производительности его не касается.</summary>
    public void Run(double dt, EconomyRates rates)
    {
        if (Definition == null || Faction != Faction.Player)
            return;

        var events = GameManager.I.Events;

        if (Definition.EnergyProduction > 0f)
            events.Append(new ResourceGained
            {
                Kind = ResourceKind.Energy,
                Amount = Definition.EnergyProduction * (float)dt,
            });

        if (Definition.MetalProduction > 0f)
            events.Append(new ResourceGained
            {
                Kind = ResourceKind.Metal,
                Amount = Definition.MetalProduction * (float)dt,
            });

        var target = RepairTarget;
        if (target != null && Definition.BuildTool is { } arm)
            Repair.Run(target, arm.Power, arm.EnergyPerPower, dt, rates);
    }

    public void AimAt(Vector2 point, double dt) =>
        Aim.AimWeapons(Rotation, GlobalPosition, point, dt);

    public override void _Process(double delta)
    {
        AimWork(delta);

        // Стенд закрывает шаг: ненаведённые инструменты возвращаются к оси корпуса,
        // а накопленные требования сводятся в один желаемый угол корпуса
        float request = Aim.Advance(Rotation, delta);

        TurnBody(request, delta);

        // Инструменты модели ведутся здесь, а не в _Draw: узел модели рисует себя сам,
        // и к моменту его отрисовки поворот обязан быть уже выставлен
        Aim.Apply();

        // Слой повреждения ведётся отсюда же: доля прочности принадлежит сущности,
        // а материалом задаётся всё остальное — см. UnitModel.ApplyDamage
        _model?.ApplyDamage(Health?.Ratio ?? 1f);

        // Луч работы ведётся после наведения: рука к этому мигу уже повёрнута, и начало
        // луча стоит там, где ему быть
        Aim.DriveWorkBeam(WorkBeamAim);

        QueueRedraw();
        _marks?.QueueRedraw();
    }

    /// <summary>
    /// Навести рабочую руку на то, над чем юнит трудится. Отдельно от стрельбы, потому что
    /// цель у работы своя: система стрельбы про узел работы не знает и наводить на него
    /// не станет.
    ///
    /// Отсюда же берётся поведение коммандера, ради которого рабочей руке и дан круговой
    /// сектор: рука сама тянется к каркасу, требования к корпусу не оставляет, и корпус
    /// остаётся свободен для доворота ствола.
    /// </summary>
    private void AimWork(double dt)
    {
        Aim.AimWork(Rotation, GlobalPosition, WorkAim, dt);
        _workAim = null;
    }

    /// <summary>
    /// Куда рука тянется в этом шаге. Подключённый узел и цель ремонта важнее заявки
    /// приказа: работа уже идёт, и рука обязана смотреть на то, над чем трудится, а не
    /// на то, к чему шли.
    ///
    /// Тот же порядок предпочтений действует у башни-сборщика (см. <c>Assembler.WorkAim</c>):
    /// правило принадлежит инструменту, а не тому, подвижен ли его носитель.
    /// </summary>
    private Vector2? WorkAim => Alive.Is(_attached)
        ? _attached.GlobalPosition
        : (RepairTarget as Node2D)?.GlobalPosition ?? _workAim;

    /// <summary>
    /// Куда тянуть луч работы. Отличается от <see cref="WorkAim"/> одним: заявка приказа
    /// сюда не входит. Наведение начинается заранее, чтобы рука встретила цель уже
    /// повёрнутой, а луч означает «работа идёт», и тянуть его к месту, до которого ещё
    /// едут, значило бы строить издалека.
    /// </summary>
    private Vector2? WorkBeamAim => Alive.Is(_attached)
        ? _attached.GlobalPosition
        : (RepairTarget as Node2D)?.GlobalPosition;

    /// <summary>
    /// Заявить, куда рука тянется в этом шаге. Наводит её <see cref="AimWork"/> в конце
    /// шага, поскольку наведение обязано случиться один раз: приказ и работа над узлом
    /// нередко указывают на одно и то же место, и два доворота за шаг удвоили бы скорость.
    ///
    /// ЗАЧЕМ ЗАМЕНИЛО <see cref="AimAt"/>. Прежде приказы стройки и ремонта разворачивали
    /// к месту работы ВСЕ СТВОЛЫ, потому что при единственном инструменте разворот носителя
    /// и разворот его снаряжения были одним и тем же действием. У коммандера, снабжённого
    /// и рукой, и пушкой, это означало, что пушка отворачивается от противника на каркас,
    /// хотя каркасу от неё ничего не нужно.
    /// </summary>
    private void AimWorkAt(Vector2 point) => _workAim = point;

    /// <summary>
    /// Дистанция подхода к месту работы, отсчитанная от центра цели. Считается тем же
    /// вызовом и с тем же <c>approach_hold</c>, что и подход к бою: расходиться в глубине
    /// сближения ствол и рабочая рука не должны.
    /// </summary>
    private float WorkApproach(object body, float reach) =>
        Reach.ApproachDistance(GlobalPosition, body, reach,
            Reach.Slack(reach, Definition?.ApproachHoldFraction ?? 1f));

    /// <summary>
    /// Сблизиться с точкой. Истина означает, что подход ещё идёт и ход этим кадром исчерпан;
    /// ложь — что ближе подходить незачем либо некуда.
    ///
    /// ЕДИНСТВЕННЫЙ РАСЧЁТ ПРИБЫТИЯ У ИСПОЛНИТЕЛЯ. Прежде сравнение расстояния с дистанцией
    /// остановки было выписано в каждом обработчике приказа отдельно, и признак
    /// <see cref="Movement.SettledAt"/> спрашивали только три обработчика из восьми. Отсюда
    /// следовал тупик: система движения объявляла ход законченным — упор в толпу, конец
    /// пути, отказ кружить вокруг близкой цели, — а приказ продолжал считать, что идти ещё
    /// далеко, и каждый кадр заново заявлял намерение, которое та же система тут же гасила.
    /// Исполнитель стоял на месте до отмены приказа.
    ///
    /// ПРИБЫТИЕ НЕ ОЗНАЧАЕТ ПРАВА ДЕЙСТВОВАТЬ. Ближе не пройти — это ответ движения, а не
    /// инструмента: цель может оказаться недостижимой вовсе. Достаёт ли рука или ствол,
    /// решается отдельно и по границе досягаемости (<see cref="Reach.Reaches"/>).
    /// </summary>
    private bool Closing(Vector2 point, float stop, bool fluid = false)
    {
        if (Movement.SettledAt(point) || GlobalPosition.DistanceTo(point) <= stop)
            return false;

        Movement.Seek(point, stop, fluid);
        return true;
    }

    /// <summary>
    /// Довернуть корпус ради инструментов. Только СТОЯ: на ходу корпус принадлежит системе
    /// движения, и разворот к цели поперёк курса означал бы, что юнит едет боком.
    ///
    /// NaN означает «требований нет либо они уже удовлетворены» — см. <see cref="AimRig.Advance"/>.
    /// </summary>
    private void TurnBody(float request, double dt)
    {
        if (float.IsNaN(request) || Movement.Velocity.LengthSquared() > 0.0001f)
            return;

        float step = (Definition?.TurnSpeed ?? Mathf.Pi) * (float)dt;
        Rotation = Heading.TurnToward(Rotation, request, step);
    }

    /// <summary>
    /// Приказов нет: узел работы отпускается, а противник в поле внимания принимается
    /// к бою по тому же правилу, что и в приказе «идти с боем» (см. <see cref="Engaged"/>).
    ///
    /// Бой по своему почину ограничен режимом из справочника (<see cref="Engagement"/>):
    /// одни виды держат место, другие преследуют. Оставшись без целей, юнит возвращается
    /// к якорю — иначе преследование раз за разом уводило бы отряд с рубежа, на который
    /// его поставили.
    /// </summary>
    public void OnIdle(double dt)
    {
        _assisted = null;
        Detach();

        if (Definition == null || !FightsOnOwn)
            return;

        if (Engaged(own: true))
        {
            _calm = 0f;
            return;
        }

        _calm += (float)dt;

        Regroup();
    }

    /// <summary>
    /// Вернуться на своё место, когда драться не с кем.
    ///
    /// ВОЗВРАТ НАЧИНАЕТСЯ НЕ СРАЗУ. Промежуток между гибелью одного противника и выбором
    /// следующего — обычное дело в бою: волна подходит не разом, а цель на месте павшей
    /// находится в ближайшие мгновения. Немедленный возврат превращал такой промежуток
    /// в рывок назад с последующим разворотом обратно. Отсчёт тишины
    /// (<see cref="Const.RegroupDelay"/>) отличает конец боя от паузы в нём.
    ///
    /// Возвращается только ПОСТАВЛЕННЫЙ (<see cref="Posted"/>) — тот, кому игрок указал место
    /// либо кого завод отправил в точку сбора. У прочих якорем служит место появления,
    /// и возврат к нему означал бы, что юнит противника после боя уходит обратно за карту.
    ///
    /// Допуск в клетку нужен против дрожания: строй расталкивает соседей, и точное совпадение
    /// с якорем недостижимо — без допуска юнит подправлял бы положение вечно.
    /// </summary>
    private void Regroup()
    {
        if (!Posted || !Definition.IsMobile || _calm < Const.RegroupDelay)
            return;

        if (GlobalPosition.DistanceTo(_anchor) > Const.Unit)
            Movement.Seek(_anchor, 0f);
    }

    /// <summary>
    /// Вступает ли сущность в бой без приказа. Истинно у всех, кроме коммандера: им игрок
    /// распоряжается напрямую, и уводить его с места по своему усмотрению нельзя — гибель
    /// коммандера завершает партию. Стрелять с места это ему не мешает.
    /// </summary>
    protected virtual bool FightsOnOwn => true;

    /// <summary>
    /// Отработать приказ за кадр. Снимать невыполнимое с головы очереди не наше дело —
    /// это уже сделала OrderSystem, сюда приказ приходит заведомо годным.
    /// </summary>
    public void RunOrder(Order order, double dt)
    {
        if (Definition == null)
            return;

        // Помощь ведущему живёт ровно один кадр и подтверждается заново: приказ
        // сопровождения мог смениться, а ведущий — закончить работу
        _assisted = null;

        // Цель, выбранная по дороге или в круге, принадлежит одному приказу и одному
        // исполнителю: сменился приказ — прежняя цель ничего не значит
        if (order.Kind is not (OrderKind.AttackMove or OrderKind.AttackArea or OrderKind.Patrol))
            _engaged = null;

        switch (order.Kind)
        {
            case OrderKind.Move:
                RunMove(order, dt);
                return;

            case OrderKind.Attack:
                RunAttack(order, dt);
                return;

            case OrderKind.AttackMove:
                RunAttackMove(order, dt);
                return;

            case OrderKind.AttackArea:
                RunAttackArea(order);
                return;

            case OrderKind.Patrol:
                RunPatrol(order, dt);
                return;

            case OrderKind.Repair:
                RunRepair(order);
                return;

            case OrderKind.Follow:
                RunFollow(order, dt);
                return;

            case OrderKind.Delete:
                Demolish();
                return;

            default:
                RunWork(order);
                return;
        }
    }

    /// <summary>
    /// Снос через тот же канал, что и гибель от урона: документ DamageDealt разбирает
    /// DamageSystem в React. Прямой QueueFree из Simulate оставил бы журнал без следа.
    /// </summary>
    private void Demolish()
    {
        if (Health == null || Health.IsDead || IsQueuedForDeletion())
            return;

        float amount = Mathf.Max(Health.Current, 1f);
        GameManager.I.Events.Append(new DamageDealt
        {
            TargetId = Id,
            SourceId = Id,
            Amount = amount,
            Pos = GlobalPosition,
        });
    }

    /// <summary>
    /// Движение с ожиданием отставших.
    ///
    /// ОТРЯД СОБИРАЕТСЯ, А НЕ РАСТЯГИВАЕТСЯ. Приказ движения, отданный нескольким, снимается
    /// только тогда, когда дошли все его участники: дошедший первым стоит и ждёт. Иначе
    /// быстрый юнит уходил бы к следующему приказу цепочки в одиночку, и отряд, посланный
    /// в две точки подряд, прибывал бы во вторую по частям.
    ///
    /// Ждать не приходится тому, кто получил приказ один: он сам себе весь состав. Копии
    /// приказа, которые завод раздаёт новорождённым, состав тоже не разделяют — см.
    /// <see cref="Order"/>.
    ///
    /// Приказ считается исполненным и тогда, когда ближе не пройти из-за своих: всему отряду
    /// в одну точку не поместиться, и ждать этого бессмысленно.
    /// </summary>
    private void RunMove(Order order, double dt)
    {
        Detach();

        if (Closing(order.Pos, Const.Unit * 0.2f, order.Fluid))
            return;

        order.Arrive(Id);

        // Стоим на месте: неподтверждённое намерение движения гаснет само,
        // и юнит удерживает позицию, пока подтягиваются остальные
        if (order.PartyReady)
            Orders.DropCurrent();
    }

    /// <summary>
    /// Стройка: дойти до места работы, а как только рука достала — поставить каркас, если
    /// это план, или подключиться к нему инструментом, если это уже каркас.
    ///
    /// Приказ объявляет намерение. Сам ход и доворот корпуса на ходу делает система
    /// движения: обходя препятствие, юнит едет не туда, куда его послали, и разворот
    /// к цели выглядел бы движением боком вперёд.
    ///
    /// РАБОТА НАЧИНАЕТСЯ ПО ГРАНИЦЕ ДОСЯГАЕМОСТИ, А НЕ ПО ПРИБЫТИЮ. Это две разные
    /// величины: подход ведёт вплотную к каркасу, граница отстоит от него на всю длину
    /// руки, и между ними лежит запас (см. <see cref="Reach.Slack"/>). Поэтому
    /// исполнитель, остановленный по дороге толпой или отказом кружить вокруг цели,
    /// всё равно оказывается внутри границы и работать начинает. Сближение при этом
    /// не прекращается: подключённый строитель продолжает подъезжать к стене.
    /// </summary>
    private void RunWork(Order order)
    {
        var target = order.Target.GlobalPosition;

        // Дальность принадлежит инструменту, а не юниту: раньше одно число служило всем
        // занятиям сразу, хотя тянутся они на разное
        var tool = Definition.BuildTool;
        float reach = tool?.RangePx ?? Const.Unit;

        // Дистанция меряется до КРАЯ места работы, а не до его середины: строитель,
        // вставший по диагонали от постройки, дотягивается до её угла, и отвергать его
        // на этом основании нельзя. Поправку на габарит цели держит Reach, а сюда она
        // приходит уже перенесённой на расстояние от центра — движение ведёт к центру
        Closing(target, WorkApproach(order.Body, reach));

        if (!Reach.Reaches(GlobalPosition, order.Body, reach))
        {
            Detach();
            return;
        }

        // Достали: к месту работы тянется рука, а стволы остаются у системы стрельбы
        AimWorkAt(target);
        order.Arrive(Id);

        if (tool == null)
        {
            Orders.DropCurrent();
            return;
        }

        // План неосязаем и мощности не принимает: его нужно превратить в каркас.
        //
        // Раннего выхода здесь нет намеренно: воплотившись, план объявляет о смене, и цель
        // приказа к следующей строке — уже каркас, к которому можно подключиться тем же
        // кадром. Если же место оказалось занято и план тихо отменился, целью остался он сам,
        // и подключаться не к чему — проверка ниже отработает вхолостую
        if (order.Target is BuildPlan plan)
        {
            Detach();
            plan.Realize();
        }

        if (order.Target is WorkNode node && _attached != node)
        {
            Detach();

            // Узлу сообщаем и мощность, и прожорливость: энергию тратит инструмент,
            // а сколько именно — записано в нём же
            node.AttachWorker(Id, tool.Power, tool.EnergyDrain);
            _attached = node;
        }
    }

    /// <summary>
    /// Приказ атаковать: подойти на дальность своего ствола и держаться. Сам выстрел —
    /// дело WeaponSystem, сюда попадает только подход.
    ///
    /// В пределах дальности инструмент крутит система стрельбы; корпус на ходу
    /// по-прежнему доворачивает система движения. Своего доворота здесь нет.
    /// </summary>
    private void RunAttack(Order order, double dt)
    {
        Detach();

        var victim = order.Entity;
        var target = victim as IDamageable;
        var to = victim.GlobalPosition;

        // Поводок: цель, которую юнит выбрал себе сам, не уводит его дальше внимания
        // от якоря. Прямое указание игрока поводка не имеет и ведёт куда угодно
        if (order.Leashed && _anchor.DistanceTo(to) > Definition.AttentionRadiusPx)
        {
            Orders.DropCurrent();
            return;
        }

        Approach(victim, target);
    }

    /// <summary>
    /// Атака по области: бить всё, что стоит в круге, а опустевший круг оставлять.
    ///
    /// ЦЕЛЬ ИЩЕТСЯ ОТ ЦЕНТРА КРУГА, А НЕ ОТ СЕБЯ. Круг задан игроком и с места не сходит,
    /// поэтому исполнитель, стоящий далеко, видит его содержимое целиком и идёт к ближайшей
    /// к центру цели. Отсчёт от себя означал бы, что приказ исчерпан всякий раз, когда до
    /// круга ещё не дошли.
    ///
    /// ПУСТОЙ КРУГ НЕ СНИМАЕТ ПРИКАЗ СРАЗУ: исполнитель обязан дойти до центра области.
    /// Иначе приказ, отданный по месту, где противника пока не видно, исчезал бы в тот же
    /// кадр, и отряд оставался бы стоять — а игрок, указывая круг, посылает отряд именно
    /// туда. Дойдя до центра и никого не найдя, исполнитель приказ оставляет.
    ///
    /// ЖДАТЬ ОТСТАВШИХ ЗДЕСЬ НЕ НУЖНО, в отличие от приказа движения. Сбор отряда нужен
    /// затем, чтобы следующая точка цепочки бралась всеми разом; а круг оставляет каждый
    /// по своему основанию — один нашёл цель и дерётся, другой дошёл до пустого центра, —
    /// и общего мига, до которого имело бы смысл ждать, у них нет.
    ///
    /// ПОИСК ВЕДЁТСЯ КАЖДЫЙ КАДР, пока цели нет, — в отличие от приказа «идти с боем»,
    /// где перебор растянут отсчётом переигровки. Отложить поиск здесь нельзя: пока он
    /// не сделан, неизвестно, идти ли к центру или драться. Дорого это не обходится:
    /// без цели приказ живёт ровно столько, сколько занимает дорога.
    /// </summary>
    private void RunAttackArea(Order order)
    {
        Detach();

        // Цель, павшая или вытесненная за границу круга, приказу больше не принадлежит
        if (_engaged != null
            && (!Targeting.IsValid(_engaged as GodotObject)
                || _engaged.GlobalPosition.DistanceTo(order.Pos) > order.Radius))
            _engaged = null;

        _engaged ??= Targeting.Nearest(order.Pos, Faction.Opposite(), order.Radius);

        if (_engaged != null)
        {
            Approach(_engaged as Node2D, _engaged);
            return;
        }

        if (Closing(order.Pos, Const.Unit * 0.2f))
            return;

        Orders.DropCurrent();
    }

    /// <summary>
    /// Подход к цели боя. Правило одно на приказ атаки и на атаку по области: расходиться
    /// в том, где именно юнит останавливается, два способа указать одну и ту же цель
    /// не должны.
    ///
    /// Подходим до дистанции, заведомо лежащей ВНУТРИ огневой границы, а не до самой
    /// границы. Остановка по признаку «уже достаю» оставляла юнита ровно на краю,
    /// откуда любое смещение цели или толчок соседа выводили его из радиуса.
    /// Обзор подход больше не режет: право на выстрел даёт разведка стороны, а не личное
    /// зрение стрелка. Безоружный подходит на длину инструмента: приказ хотя бы не зависает.
    /// </summary>
    private void Approach(Node2D victim, IDamageable target)
    {
        if (!Alive.Is(victim))
            return;

        float stop = Weapon != null
            ? Targeting.ApproachDistance(Weapon, GlobalPosition, target,
                Definition.ApproachHoldFraction)
            : Reach.StopDistance(GlobalPosition, victim, Definition.WorkRangePx);

        Closing(victim.GlobalPosition, stop);
    }

    /// <summary>
    /// Идти с боем: то же движение, но с остановками на всякую цель, попавшую в поле
    /// внимания по дороге.
    ///
    /// СТРЕЛЯЕТ НЕ ЭТОТ КОД. Огонь ведёт <see cref="WeaponSystem"/>, и ведёт он его сам,
    /// без всякого приказа: цель в пределах ствола и обзора обстреливается любым, кто
    /// не занят работой. Здесь решается единственное — стоять или идти дальше, потому что
    /// без остановки отряд проезжал бы мимо противника, огрызаясь на ходу.
    ///
    /// ЦЕЛЬ ИЩЕТСЯ НЕ КАЖДЫЙ КАДР. Перебор врагов стоит дорого, а обстановка за доли секунды
    /// не меняется, поэтому используется общий отсчёт переигровки (<see cref="NeedsTarget"/>),
    /// тот же, которым пользуется выдача задач. Найденная цель держится, пока жива
    /// и не ушла за пределы внимания.
    ///
    /// ПРИКАЗ ОТ ГИБЕЛИ ЦЕЛИ НЕ КОНЧАЕТСЯ: цели по дороге ему не принадлежат, и он живёт
    /// до прихода в точку, как обычное движение.
    /// </summary>
    private void RunAttackMove(Order order, double dt)
    {
        Detach();

        if (Engaged())
            return;

        RunMove(order, dt);
    }

    /// <summary>
    /// Отвлечение на цель в поле внимания: правило, общее для приказов «идти с боем»
    /// и «патрулировать» и для юнита БЕЗ приказов. Возвращает true, если исполнитель занят
    /// боем и дальше идти ему сейчас не следует.
    ///
    /// ПОЧЕМУ ПРАВИЛО ОДНО НА ПРИКАЗ И НА ПРОСТОЙ. Прежде незанятый юнит стоял на месте,
    /// и «отреагировать на противника» означало для него только выстрелить с места. Виду
    /// с коротким стволом это не оставляло никакой возможности вступить в бой: огнемётчик
    /// с дальностью в одну клетку ждал, пока противник подойдёт вплотную сам, и со стороны
    /// это читалось как отсутствие реакции. Сближение — такая же часть реакции, как выстрел,
    /// и зависеть от наличия приказа оно не должно.
    ///
    /// Цель принадлежит исполнителю, а не приказу: приказ общий на отряд, а отвлекается
    /// каждый на своё. Подход считается той же формулой огневой границы, что и у приказа
    /// атаки, — расходиться в ней виды приказов не должны.
    ///
    /// ЦЕЛЬ ИЩЕТСЯ В ПРЕДЕЛАХ СОБСТВЕННОГО ОБЗОРА, И ЭТО НЕ ТО ЖЕ, ЧТО ПРАВО НА ВЫСТРЕЛ.
    /// Сближаться юнит готов с тем, что видит сам: идти на цель, разведанную соседом
    /// за полкарты, он не должен. Стрелять же он вправе по всему разведанному стороной
    /// в пределах ствола — см. <see cref="Sight"/>. Отсюда и разное поведение видов: зоркий
    /// с коротким стволом сам едет на противника, слепой с длинным стоит и бьёт по цели,
    /// разведанной союзником.
    ///
    /// ПРЕДЕЛ УХОДА ЗАДАН РЕЖИМОМ БОЯ И ДЕЙСТВУЕТ ПРИ ВЫБОРЕ ЦЕЛИ. <paramref name="own"/>
    /// означает, что юнит вступает в бой по своему почину, а не по приказу; тогда режим
    /// <see cref="Engagement.Hold"/> оставляет только те цели, к которым можно подойти
    /// на дистанцию огня, не покинув поля внимания вокруг якоря, а <see cref="Engagement.Pursue"/>
    /// не ограничивает ничего. Приказ режима не касается вовсе: указание игрока ведёт
    /// исполнителя куда угодно далеко, и отвлечение по дороге тоже.
    ///
    /// ОТБОР ИДЁТ ИМЕННО ПРИ ВЫБОРЕ, А НЕ ПРИ ДВИЖЕНИИ. Прежде поводок останавливал уже
    /// начатое сближение, и юнит с коротким стволом замирал на полпути: цель у него была,
    /// а дистанции огня он не достигал и потому не стрелял вовсе. Отвергнутая заранее цель
    /// такого положения не создаёт — юнит либо доходит и бьёт, либо не идёт совсем.
    /// </summary>
    private bool Engaged(bool own = false)
    {
        if (Weapon == null)
            return false;

        float sight = Definition.VisionRadiusPx;

        // Цель, павшая, ушедшая из виду или ставшая недостижимой, перестаёт задерживать.
        //
        // ОТСЧЁТ ПЕРЕИГРОВКИ ПРИ ЭТОМ СБРАСЫВАЕТСЯ, и это важно: отсчёт нужен затем, чтобы
        // не перебирать целей каждый кадр при ЖИВОЙ цели, а не затем, чтобы выдерживать
        // паузу после её гибели. Без сброса юнит полторы секунды считался свободным
        // и успевал тронуться назад к якорю, прежде чем находил следующего противника
        if (_engaged != null
            && (!Targeting.IsValid(_engaged as GodotObject)
                || GlobalPosition.DistanceTo(_engaged.GlobalPosition) > sight
                || (own && !Reachable(_engaged))))
        {
            _engaged = null;
            _retarget = 0f;
        }

        // Выбор переигрывается по отсчёту, а не каждый кадр: у юнита без приказов признак
        // Orders.Idle истинен всегда, и поиск по нему шёл бы полным перебором целей
        // на каждом кадре у каждого незанятого
        if (_engaged == null && _retarget <= 0f)
        {
            _engaged = Targeting.Nearest(GlobalPosition, Faction.Opposite(), sight,
                own ? Reachable : null);

            NoteTargeted();
        }

        if (_engaged == null)
            return false;

        float hold = Targeting.ApproachDistance(Weapon, GlobalPosition, _engaged,
            Definition.ApproachHoldFraction);

        Closing(_engaged.GlobalPosition, hold);

        return true;
    }

    /// <summary>
    /// Годится ли цель для боя по своему почину. При <see cref="Engagement.Pursue"/> годится
    /// любая; при <see cref="Engagement.Hold"/> — та, до которой юнит достанет, оставаясь
    /// в поле внимания вокруг якоря.
    ///
    /// Дистанция подхода считается ОТ ЯКОРЯ, а не от нынешнего места: юнит пойдёт к цели
    /// именно оттуда, куда ему позволено вернуться, и поправка на габарит цели должна быть
    /// взята с той же стороны.
    /// </summary>
    private bool Reachable(IDamageable target)
    {
        if (Definition.Engagement != Engagement.Hold)
            return true;

        float approach = Targeting.ApproachDistance(Weapon, _anchor, target,
            Definition.ApproachHoldFraction);

        return _anchor.DistanceTo(target.GlobalPosition) - approach
               <= Definition.AttentionRadiusPx;
    }

    /// <summary>
    /// Патруль: обход точки либо беготня по области, а по дороге — бой со всяким, кто попал
    /// в поле внимания.
    ///
    /// СОБСТВЕННОГО ОКОНЧАНИЯ У ПРИКАЗА НЕТ. Приказ, после которого идти некуда, не снимается
    /// вовсе: исполнитель ходит по нему, пока игрок не отдаст другой. Это и есть «бегать,
    /// пока не отменить явно», и никакого особого механизма отмены оно не требует — новый
    /// приказ заменяет очередь, как и всякий другой. Кольцевание же живёт в очереди
    /// (<see cref="OrderQueue.Ringed"/>), а не здесь: маршрут — свойство очереди, а не шага.
    ///
    /// ОТСЧЁТ ВРЕМЕНИ В ОБЛАСТИ НУЖЕН НЕ ВСЕГДА. Он ограничивает пребывание только тогда,
    /// когда переходить есть куда, — то есть когда в маршруте больше одного приказа. Иначе
    /// ограничивать нечем: уйти из единственной области означало бы бросить приказ.
    ///
    /// СОСТОЯНИЕ ПАТРУЛЯ ЛИЧНОЕ. Случайная точка внутри круга и отсчёт пребывания
    /// принадлежат исполнителю, а не приказу: приказ общий на отряд, а в область юниты
    /// приходят в разное время и бегают каждый по-своему.
    /// </summary>
    private void RunPatrol(Order order, double dt)
    {
        Detach();

        if (!ReferenceEquals(_patrolled, order))
        {
            _patrolled = order;
            _patrolPoint = null;
            _patrolFor = 0f;
            _patrolPause = 0f;
        }

        if (Engaged())
            return;

        if (order.Radius > 0f)
            RunPatrolArea(order, dt);
        else
            RunPatrolPoint(order);
    }

    /// <summary>Точка обхода: дойти и уступить место следующему приказу маршрута.</summary>
    private void RunPatrolPoint(Order order)
    {
        if (Closing(order.Pos, Const.Unit * 0.2f))
            return;

        // Прибытие в составе приказа здесь не отмечается: сбор отряда патрулю не нужен —
        // маршрут каждый проходит сам, и подпись «ждём отставших» на нём означала бы
        // ожидание, которого нет
        if (Orders.HasMore)
            Orders.DropCurrent();
    }

    /// <summary>
    /// Область патруля: бегать по случайным местам внутри круга. Место выбирается заново,
    /// как только исполнитель до него добрался или упёрся, — так получается непрерывный
    /// обход без заданного маршрута.
    ///
    /// Отсчёт пребывания идёт с прихода в круг, а не с получения приказа: дорога до области
    /// патрулём не является, и мерить её тем же временем значило бы, что дальняя область
    /// охраняется меньше ближней.
    /// </summary>
    private void RunPatrolArea(Order order, double dt)
    {
        bool inside = GlobalPosition.DistanceTo(order.Pos) <= order.Radius;

        if (inside)
            _patrolFor += (float)dt;

        if (Orders.HasMore && _patrolFor >= Order.Settings.PatrolDwell)
        {
            Orders.DropCurrent();
            return;
        }

        // Передышка на месте: намерение движения не подтверждается, и юнит стоит.
        // Без неё он менял бы место сразу по прибытии и метался бы по кругу без остановки
        if (_patrolPause > 0f)
        {
            _patrolPause -= (float)dt;
            return;
        }

        // Первое место выбирается без передышки: стоять до начала обхода не за чем
        if (_patrolPoint is not { } point)
        {
            _patrolPoint = PatrolPoint(order);
            return;
        }

        if (Closing(point, Const.Unit * 0.2f))
            return;

        // Дошли или ближе не пройти: постоять, а следующее место выбрать после передышки
        _patrolPoint = null;
        _patrolPause = Order.Settings.PatrolPause;
    }

    /// <summary>
    /// Случайное место внутри круга. Корень из случайной доли даёт равномерность по площади:
    /// без него места сгущались бы к середине, и края области оставались бы без обхода.
    /// </summary>
    private static Vector2 PatrolPoint(Order order)
    {
        float angle = GD.Randf() * Mathf.Tau;
        float distance = order.Radius * Mathf.Sqrt(GD.Randf());

        return order.Pos + Vector2.Right.Rotated(angle) * distance;
    }

    /// <summary>
    /// Ремонт: подойти вплотную и стоять. Само восстановление прочности идёт в Run —
    /// ремонт стоит ресурсов и потому проходит через экономику, как и стройка.
    ///
    /// Подход и право чинить разведены так же, как у стройки: сближение ведёт к самой
    /// цели, а чинит <see cref="Repairing"/> по границе досягаемости инструмента.
    /// </summary>
    private void RunRepair(Order order)
    {
        Detach();

        var to = order.Entity.GlobalPosition;
        float reach = Definition.BuildTool?.RangePx ?? Definition.WorkRangePx;

        Closing(to, WorkApproach(order.Body, reach));

        if (Reach.Reaches(GlobalPosition, order.Body, reach))
            AimWorkAt(to);
    }

    /// <summary>
    /// Сопровождение: держаться рядом, но не наступать на пятки.
    ///
    /// СОПРОВОЖДЕНИЕ ВКЛЮЧАЕТ ПОМОЩЬ. Строитель, приставленный к строителю, берётся
    /// за то же дело, что и ведущий, — в том числе когда ведущий сам сопровождает
    /// другого строителя: помощь идёт по цепочке Follow вглубь.
    ///
    /// ОЧЕРЕДЬ ПОСЛЕ FOLLOW. Пока помощь или прикрытие заняты делом, сопровождение
    /// держится. Иначе, если за Follow уже стоит следующий приказ, сопровождение
    /// снимается, как только исполнитель дошёл до ведущего или ведущий без дела:
    /// иначе Shift-цепочка после Follow никогда бы не началась.
    /// </summary>
    private void RunFollow(Order order, double dt)
    {
        if (Assist(order) || Guard(order))
            return;

        Detach();

        if (Orders.HasMore && FollowDone(order))
        {
            Orders.DropCurrent();
            return;
        }

        Closing(order.Entity.GlobalPosition, FollowRange);
    }

    /// <summary>
    /// Дистанция сопровождения: 2.5 собственных размера. Размер — диаметр корпуса
    /// (два радиуса), поэтому стоп = <c>5 · HitRadius</c>.
    /// </summary>
    private float FollowRange => HitRadius * 5f;

    /// <summary>
    /// Сопровождение исчерпано для очереди с хвостом: либо уже рядом с ведущим,
    /// либо ведущему нечего делать и ждать больше нечего.
    /// </summary>
    private bool FollowDone(Order order)
    {
        if (!Alive.Is(order.Entity))
            return true;

        if (GlobalPosition.DistanceTo(order.Entity.GlobalPosition) <= FollowRange)
            return true;

        return order.Entity is IOrderable { Orders.Idle: true };
    }

    /// <summary>
    /// Прикрытие ведущего: подойти к противнику на дистанцию огня и держаться, пока тот
    /// не уйдёт. Приказ сопровождения при этом не тратится и не отменяется, поэтому
    /// сопровождающий возвращается к ведущему сам, как только стрелять станет не в кого.
    ///
    /// ЗОНА ИНТЕРЕСА ОТСЧИТЫВАЕТСЯ ОТ ВЕДУЩЕГО, А НЕ ОТ СЕБЯ. Отсчёт от себя означал бы, что
    /// каждый шаг за целью расширяет область поиска, и охранение утягивалось бы за одиночкой
    /// через всю карту — ровно то, ради чего заведён якорь внимания.
    ///
    /// Стрельбу отсюда никто не ведёт: она разрешена самим фактом сопровождения
    /// (см. <see cref="CanFire"/>), а стреляет <see cref="WeaponSystem"/>.
    /// </summary>
    private bool Guard(Order order)
    {
        if (Weapon == null || !Alive.Is(order.Entity))
            return false;

        var center = order.Entity.GlobalPosition;

        if (Targeting.Nearest(center, Faction.Opposite(), Definition.AttentionRadiusPx)
            is not Node2D victim)
            return false;

        Detach();

        float stop = Targeting.ApproachDistance(Weapon, GlobalPosition, victim as IDamageable,
            Definition.ApproachHoldFraction);

        Closing(victim.GlobalPosition, stop);

        return true;
    }

    /// <summary>
    /// Помощь ведущему: делать то же, что делает он, пока это в пределах внимания.
    ///
    /// ЧУЖОЙ ПРИКАЗ НЕ ПОПАДАЕТ В СВОЮ ОЧЕРЕДЬ. Помощь — не приказ, а поведение внутри
    /// сопровождения: ведущий бросит работу, и помощник тут же вернётся к нему, ничего
    /// не отменяя. Попади приказ в очередь — его пришлось бы оттуда вынимать, а до тех пор
    /// помощник считался бы занятым и сопровождение бы потерял.
    ///
    /// ЦЕПОЧКА СОПРОВОЖДЕНИЯ. Ведущий, который сам идёт по <see cref="OrderKind.Follow"/>,
    /// считается занятым тем же делом, что и его ведущий: иначе помощник смотрел бы
    /// только на приказ сопровождения и к стройке не подключался. Искать «исходного»
    /// строителя снаружи не нужно — разбор идёт по ссылкам Follow вглубь.
    ///
    /// Предел внимания отсчитывается от непосредственного ведущего: помощник ходит за
    /// ним, а не за его работой, и уходить от него дальше, чем видит, не должен.
    /// </summary>
    private bool Assist(Order order)
    {
        if (Definition.BuildTool == null || order.Entity is not IOrderable leader)
            return false;

        var work = AssistedWork(leader);

        if (work == null || !Orders.Allows(work.Kind))
            return false;

        var point = work.Point;

        if (order.Entity.GlobalPosition.DistanceTo(point) > Definition.AttentionRadiusPx)
            return false;

        _assisted = work;

        // До края того, над чем работает ведущий, а не до середины: помощник, оказавшийся
        // с дальней стороны каркаса, дотягивается до ближней к нему стены. Подход и право
        // работать разведены так же, как в RunWork
        float reach = Definition.BuildTool.RangePx;

        Closing(point, WorkApproach(work.Body, reach));

        if (!Reach.Reaches(GlobalPosition, work.Body, reach))
        {
            Detach();
            return true;
        }

        AimWorkAt(point);

        // Ремонт идёт через RepairTarget, а каркас ставит сам ведущий: помощнику
        // остаётся подключиться к тому, что уже стоит
        if (work.Target is WorkNode node && _attached != node)
        {
            Detach();
            node.AttachWorker(Id, Definition.BuildTool.Power, Definition.BuildTool.EnergyDrain);
            _attached = node;
        }
        else if (work.Kind == OrderKind.Repair)
        {
            Detach();
        }

        return true;
    }

    /// <summary>
    /// Стройка или ремонт, которым занят ведущий, в том числе через цепочку Follow.
    /// Предел глубины отсекает циклы A→B→A без выделения списка на каждый кадр.
    /// </summary>
    private Order AssistedWork(IOrderable leader)
    {
        const int depthLimit = 16;

        for (int i = 0; i < depthLimit; i++)
        {
            var work = leader.Orders.Current;

            if (work == null)
                return null;

            if (work.Kind is OrderKind.Build or OrderKind.Repair)
                return work;

            if (work.Kind != OrderKind.Follow || work.Entity is not IOrderable next)
                return null;

            // Цикл, вернувшийся к помощнику, или сопровождение самого себя
            if (ReferenceEquals(next, this) || ReferenceEquals(next, leader))
                return null;

            leader = next;
        }

        return null;
    }

    /// <summary>
    /// Кого чиним прямо сейчас: свой приказ ремонта либо чужой, в котором помогаем.
    /// Цель обязана быть в пределах инструмента — иначе чинить нечего.
    /// </summary>
    private IRepairable RepairTarget => Repairing(Current) ?? Repairing(_assisted);

    private IRepairable Repairing(Order order)
    {
        if (order?.Kind != OrderKind.Repair || Definition == null || !Definition.CanRepair)
            return null;

        if (order.Entity is not IRepairable repairable || !Targeting.IsValid(order.Entity))
            return null;

        if (order.Entity is Unit && !Definition.CanRepairUnits)
            return null;

        // САМ СЕБЯ НЕ ЧИНИТ НИКТО. Инструмент чинит то, до чего дотягивается, а не своего
        // носителя, иначе любой ремонтник превращал бы метал в собственную прочность
        // сколько угодно долго. Правило живёт здесь, потому что здесь единственное место,
        // через которое проходят все пути: и свой приказ, и чужой, в котором помогают, —
        // а помощь ведущему, чинящему как раз этого помощника, ни одним отсевом
        // при выдаче приказа не ловится.
        //
        // Источники приказа отсеивают этот случай и сами (CommandSystem.IssueResolved
        // и IssueForced, Jobs.NearestDamaged): без этого приказ выдавался бы и висел, ничего
        // не делая, — а исполнитель считался бы занятым
        if (ReferenceEquals(order.Entity, this))
            return null;

        // Допуск общий на весь проект и живёт в Reach: прежде он был здесь и только здесь,
        // а стройка и башня-сборщик обходились без него
        return Reach.Reaches(GlobalPosition, order.Entity, Definition.BuildTool.RangePx)
            ? repairable
            : null;
    }

    private void Detach()
    {
        if (Alive.Is(_attached))
            _attached.DetachWorker(Id);

        _attached = null;
    }

    /// <summary>Узел работы уходит из игры — забываем его, не касаясь мёртвой ноды.</summary>
    public void OnTargetLost(WorkNode node)
    {
        if (_attached == node)
            _attached = null;

        Orders.DropAllFor(node);
    }

    public override void _ExitTree()
    {
        Detach();
        base._ExitTree();
    }

    /// <summary>Прочность кончилась: отпустить узел работы. EntityStore снимает Spawner.</summary>
    public virtual void OnDestroyed()
    {
        Detach();
        Orders.Clear();

        // Реестр по id чистит подписка Spawner на выбытие из индекса
        Retire();
    }

    public override void _Draw()
    {
        if (Definition == null)
            return;

        float radius = Definition.RadiusPx;

        float toolLocal = ToolFacing - Rotation;

        UnitGizmos.Draw(this, GizmoTools.From(Definition), Faction,
            selected: GizmoGate.IsSelected(this),
            facingOffset: toolLocal);

        // Модель рисует себя сама дочерним узлом, поэтому запасной круг при ней не нужен:
        // два изображения одного корпуса наложились бы друг на друга.
        // Пометки при модели рисует слой, идущий после неё
        if (_model != null)
            return;

        UnitVisual.Draw(this, Definition, radius);
        PaintMarks(this);
    }
}
