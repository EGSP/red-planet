/// <summary>
/// Чем игрок занят прямо сейчас. Значения взаимно исключают друг друга по устройству,
/// а не по стечению условий.
///
/// ЗАЧЕМ ПЕРЕЧИСЛЕНИЕ. Прежде состояние ввода выражали четыре поля — рамка, раскладка,
/// признак поставленного и выбранная постройка, — допускавшие шестнадцать сочетаний,
/// из которых осмысленны четыре. Остальные не встречались не потому, что были запрещены,
/// а потому, что ветви разбора стояли в порядке, до них не доходившем. Приоритет разбора
/// был тем самым порядком строк, а не записанным правилом.
///
/// Имя <c>CommandState</c>, а не <c>Phase</c>: последнее занято фазами кадра планировщика.
/// Значение <see cref="Aiming"/>, а не <c>Targeting</c>: последнее занято статическим
/// классом проверки целей.
/// </summary>
public enum CommandState
{
    /// <summary>Ничего не начато: щелчок выделяет, протаскивание тянет рамку.</summary>
    Idle,

    /// <summary>Кнопка нажата, тянется рамка выделения.</summary>
    Banding,

    /// <summary>В панели выбрана постройка, раскладка ещё не начата.</summary>
    Placing,

    /// <summary>Кнопка нажата, тянется раскладка партии построек.</summary>
    Laying,

    /// <summary>Выбран вид приказа, ожидается указание цели.</summary>
    Aiming,
}

/// <summary>
/// Смысл, в котором разбирается нажатие клавиши. Одна и та же клавиша означает разное
/// в зависимости от того, чем игрок занят: A при непустом выделении — приказ атаки,
/// при пустом — отбор боевых машин на экране.
///
/// КОНТЕКСТ ВЫЧИСЛЯЕТСЯ, А НЕ ХРАНИТСЯ. Отдельное поле было бы вторым источником истины,
/// который пришлось бы согласовывать с <see cref="CommandState"/> при каждом переходе.
/// Поэтому контекст есть функция от состояния и наличия выделения, и вызывается она
/// в единственном месте — там, где разбирается нажатие.
/// </summary>
public enum InputContext
{
    /// <summary>Выделения нет: клавиши отбирают, кого выделить.</summary>
    Selection,

    /// <summary>Выделение есть: клавиши задают вид приказа.</summary>
    Orders,

    /// <summary>Вид приказа выбран: клавиши меняют его, всё прочее молчит.</summary>
    Aiming,

    /// <summary>Идёт жест мышью: клавиши, кроме отмены, молчат.</summary>
    Gesture,
}
