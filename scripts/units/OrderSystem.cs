using Godot;

/// <summary>
/// Единый исполнитель приказов: обходит всё, чему их можно отдать, — ботов, коммандера,
/// врагов, турели и башни, — и даёт каждому отработать свой текущий приказ.
///
/// ЗАЧЕМ ОДНА СИСТЕМА НА ВСЕХ. Раздают приказы разные мозги: у союзных ботов свой,
/// у врагов свой, у башен свой, а игрок отдаёт приказы руками. Но снимать с очереди
/// невыполнимое и звать исполнение нужно всем одинаково, и держать эту одинаковую часть
/// в трёх системах значило бы трижды её потом чинить.
///
/// Отсев тоже общий и живёт в самом приказе: невыполнимость — свойство приказа, а не того,
/// кто его получил. Поэтому исполнителю приказ достаётся заведомо годным, и проверять
/// живость цели в каждой ветке движения не нужно.
/// </summary>
public partial class OrderSystem : GameSystem
{
	/// <summary>
	/// Настройки приказов: передышка и время в области патруля, наименьший радиус области.
	/// Назначаются здесь, а действуют через <see cref="Order.Settings"/> — их спрашивают
	/// и исполнители приказов, и разбор жеста указания, то есть код, до которого ресурс
	/// пришлось бы вести по цепочке зависимостей ради одного числа.
	///
	/// Ресурс висит на СВОЕЙ системе, а не на композиционном корне: у настроек приказов
	/// владелец есть, и это она. Корню достаётся лишь то, чему владельца не нашлось, —
	/// границы мира и порог клиренса, которые спрашивает код без всякой системы.
	/// </summary>
	[Export] public OrderSettings Tuning;

	/// <summary>
	/// Первая фаза: настройки объявляются до того, как заработает хоть один шаг. Соседи
	/// здесь ещё не нужны — ресурс приходит из сцены.
	/// </summary>
	protected override void OnRegister()
	{
		if (Tuning != null)
			Order.Settings = Tuning;
	}

	public override void Step(double dt)
	{
		foreach (var actor in GM.Index.All<IOrderable>())
		{
			// Выезд из корпуса — жёсткое ограничение, не приказ: пока юнит Leaving,
			// очередь не исполняется и не завершается (иначе скопированный rally
			// с завода счёл бы себя исполненным ещё внутри корпуса)
			if (actor is IMobile { Movement.Leaving: true })
				continue;

			var orders = actor.Orders;

			// Цель пала, каркас достроен, месторождение выработано — приказ исчерпан
			orders.DropInvalid();

			var current = orders.Current;

			if (current == null)
				actor.OnIdle(dt);
			else
				actor.RunOrder(current, dt);
		}
	}
}
