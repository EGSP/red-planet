using Godot;

/// <summary>
/// Распределение задач на стороне противника: единый мозг, раздающий цели всем юнитам своей
/// стороны. Сейчас задача одна — назначить каждому цель приказом атаки; ход по приказу делает
/// сам юнит, а зовёт его <see cref="OrderSystem"/>.
///
/// ПАРА К <see cref="PlayerAiSystem"/>. Системы равноправны и названы по стороне: класс юнита
/// у них общий, а принципы выдачи задач разные и будут расходиться дальше. У игрока юнит
/// выбирает занятие по обстановке вокруг себя, здесь решение принимается за сторону целиком —
/// блуждающие сами по себе юниты стороне противника не нужны.
///
/// Предела дальности у выбора цели нет намеренно: противник обязан дойти до базы через всю
/// карту, иначе давления не возникает. На стороне игрока предел, наоборот, есть.
///
/// Сколько юнитов у стороны и когда они выходят на карту, решает не она, а
/// <see cref="PressureSystem"/>: порождение есть производство силы, а не командование ею.
///
/// Цель переигрывается по таймеру, а не только по гибели прежней: рядом могло вырасти
/// что-то поближе, и упрямо идти через полкарты к дальнему складу юнит не должен.
/// </summary>
public partial class EnemyAiSystem : GameSystem
{
    public override void Step(double dt)
    {
        foreach (var unit in GM.Units[Faction.Hostile])
        {
            unit.TickRetarget(dt);

            if (!unit.NeedsTarget)
                continue;

            if (Targeting.Nearest(unit.GlobalPosition, Faction.Player) is not Node2D victim)
                continue;

            if (unit.Orders.TrySet(Order.Attack(victim)))
                unit.NoteTargeted();
        }
    }
}
