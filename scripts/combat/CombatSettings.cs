using Godot;

/// <summary>
/// Настройки боя, общие на всю партию. Сейчас в них одно — форма спада урона по области.
///
/// ПОЧЕМУ ФОРМА СПАДА ОБЩАЯ, А НЕ СВОЯ У КАЖДОГО ОРУЖИЯ. Радиус и урон в центре суть
/// свойства ствола и потому живут в .toml, а вот то, как урон убывает от центра к краю,
/// есть правило игры: разные кривые у разных орудий означали бы, что игрок не может
/// перенести опыт с одного оружия на другое. Одна кривая на все взрывы подбирается
/// в одном месте и действует всюду.
///
/// ОТКУДА БЕРЁТСЯ ДЕЙСТВУЮЩИЙ СВОД. Основной источник — поле
/// <see cref="GameManager.CombatTuning"/>; незаполненное поле оставляет загрузку
/// по фиксированному пути, а отсутствие файла — запасную линейную форму. Тот же порядок,
/// что у <see cref="GraphicsSettings"/>, и по той же причине: спад спрашивают и там,
/// куда сцена сессии не дотягивается.
/// </summary>
[Tool]
[GlobalClass]
public partial class CombatSettings : Resource
{
    private const string Path = "res://resources/tuning/combat.tres";

    /// <summary>
    /// Спад урона по области: по оси X доля радиуса (ноль в точке взрыва, единица на краю),
    /// по оси Y доля урона от заявленного в центре.
    ///
    /// Кривая определена на отрезке от нуля до единицы, и за его пределами не спрашивается:
    /// цели дальше радиуса отсеиваются до обращения к ней.
    /// </summary>
    [Export] public Curve SplashFalloff;

    /// <summary>
    /// Чем показывается взрыв. Сцена одна на все виды оружия — как и кривая спада, это
    /// правило игры, а не свойство ствола.
    ///
    /// ПОЧЕМУ ССЫЛКА ЛЕЖИТ ЗДЕСЬ, А НЕ У <see cref="EffectSystem"/>, где лежат вспышка
    /// попадания и общий взрыв. Те объявлены полями узла в сцене сессии, и вне партии
    /// до них не дотянуться, тогда как взрыв нужно показывать и в поле редактора
    /// контента: радиус подбирается по картинке, а не по числу. Свод боя загружается
    /// по фиксированному пути и потому читается в обоих местах.
    ///
    /// У инструмента собственного изображения по-прежнему нет — см. <see cref="ToolDefinition"/>.
    /// Понадобится разный взрыв разному оружию — ссылка переедет в справочник, а эта
    /// останется общим запасным видом.
    /// </summary>
    [Export] public PackedScene SplashEffect;

    /// <summary>
    /// Во сколько раз растянуть эффект на клетку радиуса взрыва. Множитель нужен потому,
    /// что размер эффекта задан рисунком частиц, а радиус — числом справочника, и совпадать
    /// они не обязаны: единица означает, что сцена нарисована ровно под радиус в клетку.
    /// </summary>
    [Export] public float SplashEffectScale = 1f;

    private static CombatSettings _active;

    /// <summary>
    /// Действующий свод. Пока сессия не объявила свой через <see cref="Use"/>, загружается
    /// по фиксированному пути при первом обращении; нет и файла — берутся умолчания полей.
    /// </summary>
    public static CombatSettings Active
    {
        get
        {
            if (_active != null)
                return _active;

            var loaded = ResourceLoader.Exists(Path) ? GD.Load<CombatSettings>(Path) : null;

            if (loaded == null)
            {
                GD.PushWarning($"[CombatSettings] нет ресурса {Path}, взяты умолчания");
                loaded = new CombatSettings();
            }

            _active = loaded;
            return _active;
        }
    }

    /// <summary>Объявить свод действующим. Пустая ссылка возвращает загрузку по пути.</summary>
    public static void Use(CombatSettings settings) => _active = settings;

    /// <summary>
    /// Доля урона на заданной доле радиуса. Кривая не назначена — спад линейный: урон
    /// в центре полный, на краю нулевой. Запасная форма нужна потому, что взрыв без
    /// настроек обязан всё же взрываться.
    /// </summary>
    public static float Falloff(float distanceRatio)
    {
        float t = Mathf.Clamp(distanceRatio, 0f, 1f);
        var curve = Active.SplashFalloff;

        return Mathf.Max(curve != null ? curve.Sample(t) : 1f - t, 0f);
    }

    /// <summary>
    /// Во сколько раз растянуть эффект взрыва радиуса <paramref name="radiusPx"/>.
    /// Считается здесь, а не у вызывающего: перевод радиуса в размер эффекта — свойство
    /// свода, и в поле редактора он обязан выйти тем же, что в бою.
    /// </summary>
    public static float SplashSize(float radiusPx) =>
        Mathf.Max(radiusPx / Const.Unit * Active.SplashEffectScale, 0.01f);
}
