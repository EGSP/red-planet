using Godot;

/// <summary>
/// Состояние ствола: всё, что меняется у оружия по ходу боя. Сам справочник (WeaponDefinition)
/// неизменяем и общий на всех носителей, поэтому перезарядку держим здесь — рядом с носителем.
/// </summary>
public sealed class WeaponState
{
    public float Cooldown { get; private set; }

    public bool Ready => Cooldown <= 0f;

    public void Tick(double dt) => Cooldown = Mathf.Max(0f, Cooldown - (float)dt);

    /// <summary>Выстрелить, если ствол готов. Вернула true — выстрел состоялся.</summary>
    public bool TryFire(float interval)
    {
        if (Cooldown > 0f)
            return false;

        Cooldown = Mathf.Max(0.01f, interval);
        return true;
    }
}

/// <summary>
/// Носитель оружия: враг, турель или коммандер. WeaponSystem обходит разрез по этому
/// признаку и для каждого решает одно и то же — есть ли цель, довёрнут ли ствол,
/// готов ли выстрел.
///
/// Сущность не стреляет сама: она лишь отвечает на вопросы системы и умеет доворачиваться.
/// </summary>
public interface IArmed
{
    int EntityId { get; }

    Faction Faction { get; }

    /// <summary>
    /// Справочник ГЛАВНОГО ствола — первого в списке <c>tools</c>. Null означает,
    /// что сущность безоружна и система стрельбы её пропустит.
    ///
    /// По нему решаются вопросы с единственным ответом на всю сущность: вооружена ли она
    /// и на какое расстояние ей сближаться. Стреляют же все стволы — их держит
    /// <see cref="Aim"/>, каждый со своей перезарядкой и своим сектором.
    /// </summary>
    WeaponDefinition Weapon { get; }

    /// <summary>
    /// Стенд наведения: все инструменты носителя с их углами и перезарядками.
    /// Система стрельбы обходит его стволы, а не одно поле.
    /// </summary>
    AimRig Aim { get; }

    /// <summary>
    /// Ось ГЛАВНОГО ствола в радианах. У турели это поворот башни, у подвижного —
    /// направление ствола с учётом его сектора.
    /// </summary>
    float Facing { get; }

    /// <summary>
    /// Ось корпуса в радианах. От неё отсчитываются секторы наведения инструментов,
    /// поэтому она нужна системе стрельбы наравне с осью ствола: у подвижного корпус
    /// поворачивается движением, а башня — наведением, и это разные углы.
    /// </summary>
    float BodyFacing { get; }

    Vector2 GlobalPosition { get; }

    /// <summary>
    /// Точка, в которой рождается снаряд. По умолчанию совпадает с центром сущности;
    /// носитель со сценой изображения (<see cref="UnitModel"/>) переопределяет её точкой
    /// вылета своего ствола.
    ///
    /// ПОЧЕМУ ЭТО НЕ ЛОМАЕТ ГРАНИЦУ МЕЖДУ ГРАФИКОЙ И СИМУЛЯЦИЕЙ. Дальность, конус
    /// прицеливания и выбор цели считаются от <see cref="GlobalPosition"/> и о выносе ствола
    /// не знают; отсюда следует, что модель не может ни продлить дальность, ни расширить
    /// сектор. Она задаёт лишь место, откуда показан выстрел, — и без неё сущность стреляет
    /// по прежней схеме, из центра.
    /// </summary>
    Vector2 MuzzlePosition => GlobalPosition;

    /// <summary>Позволено ли открывать огонь сейчас: коммандер стреляет только без приказов.</summary>
    bool CanFire { get; }

    /// <summary>
    /// Своя цель, если сущность её уже выбрала (враг идёт именно к ней).
    /// Null — система сама найдёт ближайшую в радиусе.
    /// </summary>
    IDamageable FireTarget { get; }

    /// <summary>
    /// Довернуть ВСЕ стволы к точке за этот кадр, каждый в своём секторе и со своей
    /// скоростью. Требование к развороту корпуса при этом только накапливается: удовлетворит
    /// его носитель или нет, решает он сам — у турели основание неподвижно, а у подвижного
    /// корпус на ходу принадлежит системе движения.
    /// </summary>
    void AimAt(Vector2 point, double dt);
}
