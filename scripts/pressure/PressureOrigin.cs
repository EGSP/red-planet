/// <summary>
/// Откуда юнит противника взялся на карте. Признак ставится в миг создания и больше
/// не меняется.
///
/// ЗАЧЕМ ОН НУЖЕН. Постоянное давление ограничено бюджетом суммарной мощи, а волна —
/// напряжение в моменте, и бюджетом она не ограничена сознательно. Считать волновых юнитов
/// занятым местом было бы неверно: тогда после волны фон замер бы на всё время их жизни,
/// то есть за пиком следовала бы тишина неопределённой длины — не передышка заданной меры,
/// а побочный эффект. Различать их по определению нельзя: один и тот же вид приходит и в фоне,
/// и в волне.
/// </summary>
public enum PressureOrigin
{
    /// <summary>Постоянное давление: занимает место в бюджете и восполняется по таймеру.</summary>
    Ambient,

    /// <summary>Волна: приходит поверх бюджета и в занятое место не входит.</summary>
    Wave,
}
