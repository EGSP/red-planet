using Godot;

/// <summary>
/// Настройка давления: сколько противника стоит на карте и как быстро восполняются потери.
///
/// ПОЧЕМУ ЭТО ОТДЕЛЬНО ОТ НАСТРОЙКИ ТЕРРОРА. Террор отвечает на вопрос «насколько игрок себя
/// обнаружил» и ничего не знает о противнике. Давление отвечает на вопрос «сколько за это
/// приходит», и переводом одного в другое занят ровно один коэффициент — <see cref="PowerPerTerror"/>.
/// Держать оба набора в одном ресурсе значило бы смешать меру и следствие, и подбирать их
/// на партиях пришлось бы вместе, хотя подбираются они по разным признакам.
/// </summary>
[GlobalClass]
public partial class PressureSettings : Resource
{
    /// <summary>
    /// Сколько боевой мощи противника даёт одно очко террора.
    ///
    /// Это единственное место, где очки террора переводятся в мощь, и коэффициент нужен
    /// именно потому, что величины разной природы: очки складываются из трёх слагаемых,
    /// прошедших через кривые насыщения, а мощь считается в тех же единицах, в которых
    /// задан ключ army_power определения. Приравнять их напрямую нельзя.
    /// </summary>
    [Export] public float PowerPerTerror = 0.2f;

    /// <summary>
    /// Наименьший бюджет, ниже которого давление не опускается. Нужен на самое начало партии:
    /// пол по времени даёт слагаемое времени в самом терроре, но в первые секунды и оно
    /// близко к нулю, а пустая карта в начале партии — это не передышка, а отсутствие игры.
    /// </summary>
    [Export] public float MinimumPower = 1f;

    /// <summary>Пауза между появлениями, секунд. Задаёт, как быстро восполняется бюджет.</summary>
    [Export] public float SpawnInterval = Const.EnemySpawnDelay;

    /// <summary>Отсрочка первого появления — время развернуть базу.</summary>
    [Export] public float FirstDelay = Const.EnemyFirstDelay;
}
