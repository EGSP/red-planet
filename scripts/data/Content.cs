using Godot;

/// <summary>
/// Содержимое игры — всё, что не меняется от сессии к сессии: справочники, а со временем
/// и темы интерфейса, локализация, наборы правил. Единственная автозагрузка проекта.
///
/// Зачем отдельно от GameManager. Автозагрузка живёт столько же, сколько само приложение,
/// и это верно для контента, но неверно для сессии: журнал, проекции, сетка занятости
/// и счётчик идентификаторов обязаны умирать вместе с миром, который их породил.
/// Пока менеджер сам был автозагрузкой, эти два срока жизни были склеены — и первый же
/// перезапуск сессии унёс бы в новый мир склад, занятые клетки и призраков прошлой игры.
/// Здесь граница проведена по существу: автозагрузка — приложение, GameManager — сессия.
///
/// Ленивая загрузка внизу нужна не игре, а инструментам: тесту или редакторскому скрипту,
/// поднятому без дерева сцены, справочники всё равно достанутся.
/// </summary>
public partial class Content : Node
{
    private static Catalog _catalog;

    /// <summary>Справочники. Читаются с диска один раз за запуск.</summary>
    public static Catalog Catalog => _catalog ??= LoadCatalog();

    public override void _EnterTree() => _ = Catalog;

    private static Catalog LoadCatalog()
    {
        var catalog = new Catalog();
        catalog.LoadAll();
        return catalog;
    }
}
