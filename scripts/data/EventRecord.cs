using System;

/// <summary>
/// Документ — запись о том, что уже случилось. Основа event sourcing в проекте.
///
/// ЗАЧЕМ. Системы не дёргают друг друга напрямую, а обмениваются документами через EventStore.
/// Система стройки не знает про систему мира: она дописывает BlueprintPlaced, а кто на это
/// отреагирует — её не касается. Так связи между системами не превращаются в клубок.
///
/// КАК ПРИМЕНЯТЬ. Объявляй структурой (не классом) и называй в прошедшем времени —
/// «что произошло», а не «что сделать»: ResourceSpent, OreDepleted, ConstructionCompleted.
/// Приказы и намерения документами НЕ являются: документ — это уже свершившийся факт,
/// его нельзя отменить или отклонить.
///
/// Структура, а не класс, потому что документов публикуются десятки в секунду,
/// а значимый тип не грузит сборщик мусора.
///
/// Внутри — только данные и стабильные идентификаторы (EntityId, строковый DefinitionId),
/// НИКОГДА ссылки на ноды. Нода умирает, а документ должен переживать её и сохранение.
/// </summary>
public interface IEventRecord
{
    /// <summary>
    /// Порядковый номер в своём потоке, его проставляет сам поток при дозаписи.
    /// Нужен потребителям, которые читают пачкой и должны понимать, что уже разобрали
    /// (курсор), а также для воспроизводимого порядка при разборе.
    /// </summary>
    int SequenceId { get; set; }
}

/// <summary>
/// Помечает документ как живущий один кадр: в конце кадра его поток чистится целиком.
///
/// ЗАЧЕМ. Большинство документов нужны лишь для того, чтобы системы среагировали здесь и сейчас
/// (искра урона, «руда пришла», «слот освободился»). Если их не чистить, журнал будет расти
/// всю сессию и съест память.
///
/// КОГДА СТАВИТЬ. Ставь по умолчанию. Не ставь только там, где запись обязана дожить
/// до сохранения или до отложенного разбора — тогда её придётся усекать вручную
/// (см. раздел про ужатие журналов в docs/system-design.md).
///
/// Почему атрибут, а не интерфейс-маркер: время жизни — это метаданные о записи,
/// а не её разновидность. Наследованием это выражать неправильно.
/// </summary>
[AttributeUsage(AttributeTargets.Struct | AttributeTargets.Class, Inherited = false)]
public sealed class TransientEventAttribute : Attribute { }
