using Godot;

/// <summary>
/// Кто отвечает за доворот корпуса, когда цель лежит вне сектора инструмента.
///
/// ЗАЧЕМ ПРАВИЛО ЖИВЁТ У ИНСТРУМЕНТА, А НЕ У НОСИТЕЛЯ. Один и тот же носитель снабжён
/// разными инструментами, и требования у них противоположны: строительная рука с круговым
/// сектором доворота не требует никогда, а жёстко закреплённое орудие требует всегда.
/// Держать правило на носителе значило бы, что коммандер обязан выбрать одно поведение
/// на оба своих инструмента, тогда как нужное поведение — «стройка корпусу безразлична,
/// стрельба корпус разворачивает».
/// </summary>
public enum BodyAssist
{
    /// <summary>
    /// Корпус к цели не доворачивается вовсе. Инструмент довольствуется своим сектором;
    /// цель вне сектора для него попросту недоступна.
    /// </summary>
    Never,

    /// <summary>
    /// Доворот запрашивается, только когда цель вышла за сектор инструмента. Умолчание:
    /// пока башня достаёт сама, корпус стоит, и лишних движений не возникает.
    /// </summary>
    WhenBlocked,

    /// <summary>
    /// Корпус доворачивается прямо на цель всегда. Так ведёт себя жёстко закреплённое
    /// орудие (<see cref="ToolDefinition.AimArcDegrees"/> равен нулю), которому иначе
    /// не прицелиться ни во что.
    /// </summary>
    Always,
}

/// <summary>
/// Инструмент — то, чем сущность действует на мир: ствол, строительная рука.
///
/// ПОЧЕМУ ОТДЕЛЬНОЕ ОПРЕДЕЛЕНИЕ, А НЕ ПОЛЯ ВНУТРИ ЮНИТА. Раньше строительная мощность
/// и её прожорливость лежали прямо в определении юнита, а дальность была одна на все
/// занятия, тогда как у ствола она своя. Инструмент как отдельная вещь снимает и то,
/// и другое: дальность принадлежит тому, кто её применяет, а одну и ту же руку можно
/// выдать двум разным юнитам, не повторяя чисел в двух файлах.
///
/// Модель взята из PA, где юнит носит список tools со ссылками на спецификации.
/// </summary>
public abstract class ToolDefinition
{
    public string Id = "";
    public string DisplayName = "";

    /// <summary>
    /// Дальность действия в юнитах мира.
    ///
    /// ИЗОБРАЖЕНИЯ У ИНСТРУМЕНТА НЕТ. Ствол и манипулятор рисуются частью
    /// <see cref="ModelTool"/> в сцене модели носителя, поэтому собственного пути к спрайту
    /// определение не держит: инструмент выдаётся нескольким видам, а сидит на каждом
    /// по-своему, и одно изображение на всех означало бы, что положение части задаётся
    /// не там, где его видно.
    /// </summary>
    public float Range = 3f;

    // ── наведение: сектор, скорость доворота, возврат, требование к корпусу ───────
    //
    // Четыре ключа ниже описывают одно и то же явление — поворот инструмента
    // относительно корпуса, — и потому носят общий префикс aim_ в файле .toml.
    // Пятый ключ (aim_priority) вступает в силу только при нескольких инструментах.

    /// <summary>
    /// ПОЛОВИНА сектора поворота относительно оси корпуса, в градусах. Инструмент
    /// доворачивается в пределах ±этого угла и дальше упирается, продолжая двигаться
    /// вместе с корпусом.
    ///
    /// ГРАНИЧНЫЕ ЗНАЧЕНИЯ ЗАДАЮТ ДВА ОСНОВНЫХ СЛУЧАЯ. 180 — круговая башня, ограничения
    /// нет вовсе. 0 — жёстко закреплённый инструмент: его ось всегда совпадает с осью
    /// корпуса, и навести его можно только разворотом носителя. Промежуточные значения
    /// описывают сектор обстрела — например, 90 у бортового орудия.
    ///
    /// Половина, а не полный раствор, — чтобы число читалось как «на сколько градусов
    /// вправо и влево», и чтобы сравнение с <see cref="Heading.Delta"/> шло без деления.
    /// Так же устроен ключ yaw_range в Planetary Annihilation.
    /// </summary>
    public float AimArcDegrees = 180f;

    /// <summary>
    /// Скорость доворота инструмента в градусах в секунду. Число собственное, а не общее
    /// с корпусом: у машины башня обыкновенно вертлявее шасси, и одно число на оба поворота
    /// не даёт выразить ни быструю башню на медленном корпусе, ни обратное.
    ///
    /// Смысл имеет только вместе с <see cref="AimArcDegrees"/>: у жёстко закреплённого
    /// инструмента (сектор ноль) поворачивать нечего, и скорость не читается.
    /// </summary>
    public float AimRateDegrees = 180f;

    /// <summary>
    /// Сколько секунд инструмент держит последний угол после того, как цель пропала,
    /// прежде чем вернуться к оси корпуса.
    ///
    /// Задержка нужна против дрожания: без неё смена цели у скорострельного оружия
    /// заставляет ствол каждый раз проходить путь до походного положения и обратно.
    /// Ноль означает немедленный возврат.
    /// </summary>
    public float AimIdleDelay = 2f;

    /// <summary>
    /// Требует ли инструмент доворота корпуса, когда цель вне его сектора.
    /// См. <see cref="global::BodyAssist"/>: смысл значений описан там.
    /// </summary>
    public BodyAssist BodyAssist = BodyAssist.WhenBlocked;

    /// <summary>
    /// Чьё требование к развороту корпуса важнее, когда инструментов несколько и угодить
    /// сразу всем нельзя. Больше — важнее; при равенстве побеждает тот, кто раньше стоит
    /// в списке <c>tools</c> носителя.
    ///
    /// ЗАПАСНОЕ ПРАВИЛО, А НЕ ОСНОВНОЕ. Сперва носитель ищет угол корпуса, при котором цель
    /// попадает в секторы ВСЕХ инструментов разом (см. <see cref="AimRig"/>), и приоритет
    /// вступает в силу лишь тогда, когда такого угла не существует, — например, у машины
    /// с двумя орудиями по разным бортам.
    /// </summary>
    public int AimPriority;

    public float RangePx => Range * Const.Unit;

    /// <summary>Половина сектора поворота в радианах — в такой форме её и спрашивают.</summary>
    public float AimArc => Mathf.DegToRad(AimArcDegrees);

    public float AimRate => Mathf.DegToRad(AimRateDegrees);

    /// <summary>
    /// Инструмент закреплён жёстко: поворачиваться ему некуда, и ось его совпадает
    /// с осью корпуса. Отдельным свойством, поскольку проверка встречается и в наведении,
    /// и в отрисовке, и в редакторе.
    /// </summary>
    public bool Fixed => AimArcDegrees <= 0f;

    /// <summary>
    /// Сектор кругов: ограничения нет, и доворот корпуса такому инструменту не нужен
    /// ни при каком положении цели.
    /// </summary>
    public bool FullCircle => AimArcDegrees >= 180f;
}

/// <summary>
/// Ствол. Отдельным определением от носителя, потому что оружие — самостоятельная вещь:
/// коммандеру досталась пушка со средними числами, и это тот же тип данных, что у противника.
///
/// Все дальности и скорости заданы в юнитах мира (1 юнит = клетка), в пиксели переводят
/// свойства с суффиксом Px — чтобы в файле числа читались в игровых, а не экранных величинах.
/// </summary>
public sealed class WeaponDefinition : ToolDefinition
{
    /// <summary>Урон одного снаряда.</summary>
    public float Damage = 10f;

    /// <summary>Секунд между выстрелами. Меньше — плотнее очередь.</summary>
    public float FireInterval = 1f;

    /// <summary>Скорость снаряда в юнитах в секунду.</summary>
    public float ProjectileSpeed = 14f;

    /// <summary>Случайный увод ствола в градусах — кучность очереди.</summary>
    public float SpreadDegrees = 1.5f;

    /// <summary>
    /// ПОЛОВИНА сектора, внутри которого разрешён выстрел, в градусах: пока цель за его
    /// пределами, стрелок только доворачивается.
    ///
    /// ЧЕМ ОТЛИЧАЕТСЯ ОТ <see cref="ToolDefinition.AimArcDegrees"/>. Сектор наведения
    /// отвечает на вопрос «куда ствол может повернуться» и потому измеряется от оси корпуса.
    /// Сектор стрельбы отвечает на вопрос «достаточно ли точно ствол уже наведён» и потому
    /// измеряется от оси самого ствола. Первый есть свойство крепления, второй — точности,
    /// и числа у них разного порядка: сектор наведения обыкновенно десятки градусов,
    /// сектор стрельбы — единицы.
    /// </summary>
    public float FireArcDegrees = 8f;

    /// <summary>Радиус снаряда в юнитах — и размер на экране, и радиус попадания.</summary>
    public float ProjectileRadius = 0.08f;

    public Color ProjectileColor = new(1f, 0.85f, 0.4f);

    public float SpeedPx => ProjectileSpeed * Const.Unit;

    public float ProjectileRadiusPx => ProjectileRadius * Const.Unit;

    /// <summary>Половина сектора стрельбы в радианах — в такой форме его и спрашивают.</summary>
    public float FireArc => Mathf.DegToRad(FireArcDegrees);

    public float Spread => Mathf.DegToRad(SpreadDegrees);

    /// <summary>
    /// Сколько снаряду жить: дальность полёта плюс запас на промах, чтобы пуля
    /// не гасла ровно на границе радиуса и мимо цели улетала чуть дальше.
    /// </summary>
    public float Lifetime => SpeedPx <= 0f ? 0.1f : RangePx / SpeedPx * 1.25f;
}

/// <summary>
/// Виды работ, которые инструмент выполняет. Ремонт следует из стройки, см. ниже.
/// Вид пока один, но перечисление флагов остаётся: инструмент по своей природе умеет
/// несколько дел разом, и возвращать сюда второй вид не должно означать смену типа.
/// </summary>
[System.Flags]
public enum WorkKinds
{
    None = 0,
    Build = 1,
    Repair = 2,
}

/// <summary>
/// Рабочий инструмент: строительная рука.
///
/// ЕДИНАЯ МОЩНОСТЬ. Отдельной ремонтной мощности нет: чинит та же рука, что и строит,
/// и тратит столько же энергии. Так же устроено в PA, где build power одна на стройку,
/// ремонт и достройку чужого.
///
/// Энергозатраты живут здесь, а не в определении постройки: энергию потребляет инструмент,
/// а не бетон. Один и тот же каркас обойдётся дороже прожорливому коммандеру и дешевле
/// экономному фабрикатору.
/// </summary>
public sealed class WorkToolDefinition : ToolDefinition
{
    /// <summary>Мощность, единиц работы в секунду. Для стройки это метал в секунду.</summary>
    public float Power = 1f;

    /// <summary>Сколько энергии в секунду съедает единица мощности.</summary>
    public float EnergyPerPower = 5f;

    /// <summary>Что инструмент умеет.</summary>
    public WorkKinds Kinds = WorkKinds.None;

    /// <summary>
    /// Берётся ли инструмент чинить юнитов, а не только постройки. Отдельным признаком,
    /// потому что это вопрос не умения, а назначения: ремонтник поля боя и строитель базы
    /// пользуются одной и той же рукой.
    /// </summary>
    public bool RepairsUnits;

    public bool CanBuild => Kinds.HasFlag(WorkKinds.Build);

    /// <summary>
    /// Ремонт может быть отдельным умением: у боевого ремонтника стройки нет,
    /// а чинить он обязан. Если в файле указана только стройка — ремонт следует из неё,
    /// как в PA (одна мощность на оба занятия).
    /// </summary>
    public bool CanRepair =>
        Kinds.HasFlag(WorkKinds.Repair) || Kinds.HasFlag(WorkKinds.Build);

    /// <summary>Годен ли инструмент хоть на какую-то работу. По нему юнит получает руку.</summary>
    public bool CanWork => Kinds != WorkKinds.None;

    /// <summary>Расход энергии в секунду при работе на полную мощность.</summary>
    public float EnergyDrain => Power * EnergyPerPower;
}
