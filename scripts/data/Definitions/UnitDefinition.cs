using System.Collections.Generic;
using Godot;

/// <summary>Какой класс поднимает Spawner. Поведение задаётся кодом, числа — определением.</summary>
public enum UnitClass
{
    /// <summary>Юнит: ходит, сам ищет себе занятие, приказы игрока не слушает.</summary>
    Bot,

    /// <summary>
    /// Машина: гусеничный или колёсный корпус (силуэт — прямоугольник). По поведению
    /// как бот, выпускается заводом машин, а не ботов.
    /// </summary>
    Vehicle,

    /// <summary>Коммандер: единственный, кто слушает приказы; гибель — поражение.</summary>
    Commander,

    /// <summary>Постройка без собственного поведения: склад, генератор, стена.</summary>
    Structure,

    /// <summary>
    /// Переработка: жжёт энергию и даёт метал. Так устроены и синтезатор, и экстрактор —
    /// механика у них одна, а различаются они курсом и тем, что экстрактор требует
    /// под собой точку метала.
    /// </summary>
    Factory,

    /// <summary>Турель: постройка со стволом и вращающейся башней.</summary>
    Turret,

    /// <summary>Башня-сборщик: строит и чинит в радиусе обзора, с места не сходит.</summary>
    Assembler,

    /// <summary>
    /// Вид, которым распоряжается противник. Узел поднимается тот же самый, что и у юнита
    /// игрока: род нужен затем, чтобы система давления могла перечислить, из чего ей
    /// набирать давление. Сторона задаётся не здесь, а тем, кто сущность создаёт.
    /// </summary>
    Enemy,

    /// <summary>
    /// Завод юнитов: очередь производства без каркаса на карте, выпуск с выездом из корпуса.
    /// Не путать с <see cref="Factory"/> — тот жжёт энергию в метал.
    /// </summary>
    Plant,
}

/// <summary>
/// Силуэт корпуса подвижной сущности. Хитбокс при этом остаётся кругом.
///
/// Первые три выражаются одной фигурой; остальные раскладываются на выпуклые части —
/// см. <see cref="HullGeometry"/>. Составные заведены ради крупных машин: круг радиусом
/// в клетку читается как пятно, и отличить одну такую машину от другой нечем.
/// </summary>
public enum HullShape
{
    Circle,
    Rect,
    Hex,

    /// <summary>Стреловидный: клин носа и два отнесённых назад крыла.</summary>
    Arrow,

    /// <summary>Подкова: кольцевая полоса, разомкнутая вперёд, с клыками.</summary>
    Crescent,

    /// <summary>Звезда: шесть лучей попеременной длины вокруг ядра.</summary>
    Star,

    /// <summary>Блочная крепость: длинный корпус с надстройкой и спонсонами.</summary>
    Fortress,

    /// <summary>Серп: полоса, сходящаяся к остриям, раствором вперёд.</summary>
    Sickle,

    /// <summary>Венец: восьмигранное тело с носовым клином, бортовыми блоками и ядром.</summary>
    Crown,
}

/// <summary>
/// Надстройка силуэта — признак тира, не рода войск.
///
/// ПОЧЕМУ ОТДЕЛЬНО ОТ <see cref="HullShape"/>. Базовая форма означает род войск (окружность —
/// бот, прямоугольник — машина, шестигранник — шагающий тяжёлый), и отдавать T2 собственную
/// форму значило бы занимать род войск тиром: именно так вышло, когда шестигранник
/// одновременно достался среднему танку T1 и боту T2, и тир перестал читаться. Надстройка
/// накладывается поверх любой базовой формы, поэтому тир и род войск выражаются независимо.
///
/// Титаны надстройки не получают: у них составные силуэты из <see cref="HullGeometry"/>,
/// которые и так ни с чем не спутать.
/// </summary>
public enum HullTrim
{
    None,

    /// <summary>
    /// Плечи: два выступа по бортам и клин носа. Признак продвинутого тира.
    /// </summary>
    Shoulders,
}

/// <summary>Параметры завода юнитов. Секции нет — сущность не производит очередь.</summary>
public sealed class PlantDefinition
{
    /// <summary>Пауза после того, как выпущенный юнит покинул корпус, секунд.</summary>
    public float FactoryCooldown = 3f;

    /// <summary>Мощность сборки: метал в секунду при полной производительности базы.</summary>
    public float BuildPower = 10f;

    /// <summary>Расход энергии на единицу мощности сборки.</summary>
    public float EnergyPerPower = 1f;

    /// <summary>
    /// Локальные направления выезда относительно facing корпуса. Ось вперёд — +X.
    /// Пустой список — перед и зад по умолчанию.
    /// </summary>
    public Vector2[] RolloffDirections = { Vector2.Right, Vector2.Left };

    /// <summary>
    /// На сколько клеток вперёд от точки выезда проверяется продолжение дороги.
    /// Ноль означает, что проверяется только само место выезда.
    ///
    /// ПОЧЕМУ ЭТО НАСТРОЙКА, А НЕ ЧИСЛО В КОДЕ. Проверка продолжения нужна, чтобы завод
    /// предпочёл ту сторону, откуда есть куда ехать, но её область неизбежно заезжает
    /// на соседние постройки при плотной застройке, и выезд объявляется закрытым там,
    /// где юнит спокойно вышел бы и повернул вбок. Насколько далеко смотреть — свойство
    /// конкретного завода и плотности базы, а не общего правила, поэтому величина живёт
    /// в справочнике и по умолчанию выключена.
    /// </summary>
    public float RolloffClearance;

    public float RolloffClearancePx => RolloffClearance * Const.Unit;
}

/// <summary>
/// Как раскладываются места, когда игрок ставит строение с протаскиванием мыши.
///
/// Паттерн принадлежит определению, а не выводится из движения курсора: у стены и у турели
/// движение одно и то же, а нужны им разные раскладки, и угадывать намерение по геометрии
/// значило бы отнимать выбор у того, кто описывает сущность.
/// </summary>
public enum BuildPattern
{
    /// <summary>Раскладки нет: сколько ни тяни, встанет одно строение.</summary>
    None,

    /// <summary>Цепочка вдоль протаскивания. Так выкладываются стены и ряды генераторов.</summary>
    Line,

    /// <summary>Сплошная решётка в области протаскивания — плотная застройка.</summary>
    Square,

    /// <summary>
    /// Ромб вокруг первой постройки: протаскивание задаёт радиус в шагах, а раскладка
    /// расходится кольцами во все стороны от неё. Так расставляют турели — им важнее
    /// перекрытие секторов обстрела, чем плотность застройки.
    /// </summary>
    Diamond,

    /// <summary>
    /// Все точки метала в круге вокруг начала протаскивания. Единственная раскладка,
    /// которая берёт места не из решётки, а из карты: экстрактор ставится не туда,
    /// где ровно, а туда, где залежь.
    /// </summary>
    MetalArea,
}

/// <summary>Что нужно, чтобы сущность построить. Секции нет — сущность не строится вовсе.</summary>
public sealed class AssemblyDefinition
{
    /// <summary>
    /// Полная стоимость в метале. Она же объём работы: время стройки равно стоимости,
    /// делённой на суммарную мощность строителей, как в PA.
    /// </summary>
    public float CostMetal;

    /// <summary>
    /// Прочность каркаса, пока идёт стройка. Отдельным числом от прочности готовой сущности:
    /// раньше оба значения назывались MaxHealth и лежали в разных файлах одного юнита,
    /// из-за чего по файлам было не понять, что это две разные величины.
    ///
    /// Не задано — берётся прочность готовой сущности. Так и было у построек, и повторять
    /// одно число в каждом файле незачем: своё значение нужно там, где каркас крепче
    /// или слабее того, что из него получится.
    /// </summary>
    public float FrameHealth;
}

/// <summary>
/// Переработка или чистый расход энергии. У синтезатора — жжёт энергию и даёт метал;
/// у портала — только расход в активном состоянии, без выхода.
/// </summary>
public sealed class ConversionDefinition
{
    /// <summary>Сколько энергии в секунду потребляет при полной производительности.</summary>
    public float EnergyDrain;

    /// <summary>Сколько метала в секунду выдаёт при полной производительности. Ноль — чистый расход.</summary>
    public float MetalOutput;
}

/// <summary>
/// Определение сущности мира: бота, постройки или противника. Одно на всех, потому что
/// разница между ними — это набор заполненных секций, а не разные виды данных.
///
/// РАНЬШЕ БЫЛО ТРИ ОПРЕДЕЛЕНИЯ И РАЗЪЕЗЖАЛИСЬ. Фабрикатор описывался тремя файлами:
/// BuildableDef с ценой и формой, UnitDef с ходовыми числами и сценой, которая их связывала.
/// Имя и цвет были записаны дважды дословно, а ключ MaxHealth в двух файлах означал разное —
/// прочность каркаса и прочность собранного юнита. Здесь и то, и другое названо своими
/// именами: MaxHealth и Assembly.FrameHealth.
///
/// СЕКЦИИ ВМЕСТО ПРИЗНАКОВ. Признака «это юнит» больше нет: сущность занимает клетки,
/// если у неё задана форма (Rows), и строится, если задана секция сборки. Роль выводится
/// из того, чем сущность снабжена, а не из отдельного переключателя, который можно
/// выставить вразрез с остальными полями.
///
/// Размеры и скорости заданы в юнитах мира (1 юнит = клетка), перевод в пиксели —
/// свойства с суффиксом Px.
/// </summary>
public sealed class UnitDefinition
{
    public string Id = "";
    public string DisplayName = "";

    public UnitClass Class = UnitClass.Structure;

    /// <summary>Категории, которыми определение помечает себя. См. TagRegistry.</summary>
    public TagSet Tags = TagSet.Empty;

    public Color Color = new(0.6f, 0.6f, 0.65f);

    public float MaxHealth = 100f;

    /// <summary>Радиус корпуса подвижной сущности в юнитах: и рисуется по нему, и попадают в него.</summary>
    public float Radius = 0.35f;

    /// <summary>Силуэт корпуса. На хитбокс и навигацию не влияет.</summary>
    public HullShape Hull = HullShape.Circle;

    /// <summary>Надстройка силуэта — признак тира. См. <see cref="HullTrim"/>.</summary>
    public HullTrim HullTrim = HullTrim.None;

    /// <summary>Отношение длины к ширине для <see cref="HullShape.Rect"/>.</summary>
    public float HullAspect = 1.5f;

    /// <summary>Число дополнительных контуров брони вокруг корпуса.</summary>
    public int ArmorRings;

    /// <summary>
    /// Залитая передняя часть корпуса — признак ближнего боя из свода соответствий
    /// (docs/gamedesign/units.md, «Визуальный язык»).
    ///
    /// Признак задаётся явно, а не выводится из дальности оружия порогом: порог пришлось бы
    /// подбирать под нынешний набор стволов, и любая правка дальности меняла бы силуэт
    /// сама собой. Остальные части силуэта — hull, armor_rings — заданы так же.
    /// </summary>
    public bool FrontPlate;

    /// <summary>Радиус обзора в юнитах. Он же рабочая зона для башни-сборщика.</summary>
    public float VisionRange = 8f;

    /// <summary>Скорость хода в юнитах в секунду. Ноль — сущность неподвижна.</summary>
    public float Speed;

    /// <summary>Скорость вращения корпуса или башни в градусах в секунду.</summary>
    public float TurnSpeedDegrees = 180f;

    /// <summary>
    /// Разгон в юнитах за секунду в квадрате. Ноль означает «взять из скорости»:
    /// подставляется десятикратная скорость, то есть выход на полный ход за одну десятую
    /// секунды. Отношение взято из PA, где оно выдержано у всех подвижных, от бота-бомбы
    /// до фабрикатора; на глаз такой разгон неотличим от мгновенного, но снимает рывок
    /// с места.
    /// </summary>
    public float Acceleration;

    /// <summary>
    /// Торможение в юнитах за секунду в квадрате. ОТРИЦАТЕЛЬНОЕ ЗНАЧЕНИЕ — «останавливается
    /// мгновенно», и это умолчание.
    ///
    /// Здесь проходит граница между шагающим и колёсным. В PA у всех без исключения ботов
    /// и у коммандера стоит brake = −1, а у машин, кораблей и авиации — конечное число,
    /// обычно равное разгону. Смысл прямой: ноги останавливаются шагом, колёса катятся.
    /// Шагающий поэтому идёт с постоянной скоростью и встаёт разом, а колёсный сбрасывает
    /// ход заранее, чтобы остановиться там, где нужно.
    /// </summary>
    public float Brake = -1f;

    /// <summary>
    /// Форма в клетках: '#' — занятая клетка, '.' — пустая. ["##", "##"] — квадрат 2x2,
    /// ["###", ".#."] — Т-образная форма. Пусто — сущность клеток не занимает, она ходит.
    /// </summary>
    public string[] Rows = System.Array.Empty<string>();

    /// <summary>
    /// Куда смотрит неподвижная сущность, в градусах (0 — вправо). Здание ноду не крутит:
    /// визуал привязан к клеткам сетки. Ось нужна ради единого правила — направление
    /// есть у любой сущности мира.
    /// </summary>
    public float FacingDegrees;

    /// <summary>
    /// Ставится только на точку метала и обязана её накрыть. Признак принадлежит месту,
    /// а не постройке, поэтому и живёт рядом с формой: и то, и другое отвечает на вопрос
    /// «куда это встанет». Проверяет его Placement.CanPlace, причём в обе стороны —
    /// постройка без этого признака на точку не встанет вовсе, чтобы не занять её
    /// безвозвратно. Он же включает притяжение призрака к точке под курсором.
    /// </summary>
    public bool RequiresMetalSpot;

    /// <summary>Раскладка при протаскивании. По умолчанию раскладки нет.</summary>
    public BuildPattern Pattern = BuildPattern.None;

    /// <summary>
    /// Раскладка под зажатым Alt. Не задана — Alt ничего не меняет.
    ///
    /// Пара нужна затем, что у одной и той же постройки есть два осмысленных строя, и какой
    /// из них главный, зависит от постройки: стене привычнее линия, а про запас нужен квадрат;
    /// турели наоборот — ромб основной, а линия пригождается вдоль края базы.
    /// </summary>
    public BuildPattern PatternAlt = BuildPattern.None;

    /// <summary>
    /// Множитель обязательного зазора между местами в раскладке. Промежуток считается
    /// как размер строения плюс <see cref="Const.BuildMarginPx"/>, умноженный на это число.
    ///
    /// Единица (narrow) даёт сплошной ряд: соседи стоят вплотную, разделённые только тем
    /// зазором, без которого растр навигации даёт щели. Двойка (margin) оставляет между
    /// рядами промежуток. Дробное и большее значения задаются числом.
    ///
    /// Отдельного размера площадки, как placement_size в PA, здесь намеренно нет: размер
    /// уже задан формой, и второе число, обязанное с ней согласовываться, — лишний повод
    /// их рассогласовать.
    /// </summary>
    public float PatternStep = 1f;

    /// <summary>
    /// Чем сущность снабжена, ссылками из файла. Строки живут только до сборки:
    /// компилятор превращает их в Tools и больше к ним не возвращается.
    /// </summary>
    public string[] ToolIds = System.Array.Empty<string>();

    /// <summary>Чем сущность снабжена: ствол, строительная рука, бур. Заполняет компилятор.</summary>
    public ToolDefinition[] Tools = System.Array.Empty<ToolDefinition>();

    /// <summary>Как построить. Null — сущность в мире появляется помимо стройки.</summary>
    public AssemblyDefinition Assembly;

    /// <summary>Переработка ресурсов. Null — сущность ничего не перерабатывает.</summary>
    public ConversionDefinition Conversion;

    /// <summary>Собственное производство, единиц в секунду.</summary>
    public float EnergyProduction;

    public float MetalProduction;

    /// <summary>Насколько сущность поднимает потолок хранилища.</summary>
    public float MetalStorage;

    public float EnergyStorage;

    /// <summary>
    /// Идентификатор строительной панели из resources/buildbars/. Пусто у того, кто строить
    /// не умеет; у строителя панель и есть ответ на вопрос «что ему доступно» — отдельного
    /// списка построек определение не держит.
    /// </summary>
    public string Buildbar = "";

    /// <summary>
    /// Мощь экспансии постройки — абсолютный вес до умножения на коэффициент зоны.
    /// В .toml — ключ <c>expansion_power</c>. Не задано: единица у постройки, ноль
    /// у подвижной сущности.
    ///
    /// Задаётся там, где умолчание неверно. Забор весит около 0.05: их много, места они
    /// занимают столько же, сколько завод, а угрозы не несут — и без отдельного веса
    /// периметр из заборов раздувал бы показатель на ровном месте.
    /// </summary>
    public float? ExpansionPowerWeight;

    /// <summary>
    /// Боевая мощь сущности — одно число на обе стороны. Не задано: единица у подвижного
    /// со стволом, ноль у всех прочих. Строитель армией не является, а турель считается
    /// по экспансии, иначе она вошла бы в показатель дважды.
    ///
    /// Величина служит двум разным потребителям, и это сделано намеренно. У игрока она
    /// складывается в слагаемое «армия» показателя террора; у противника той же величиной
    /// меряется занятое место в бюджете постоянного давления. Шкала одна, поэтому числа
    /// сторон сопоставимы и настраиваются в одних единицах.
    /// </summary>
    public float? ArmyPowerWeight;

    /// <summary>
    /// Не умножать мощь экспансии на коэффициент зоны кольца мира. В .toml — ключ
    /// <c>ignore_modifiers</c> в секции <c>[terror]</c>. Нужен там, где вес задан
    /// абсолютным числом и не должен расти с удалением от точки высадки.
    /// </summary>
    public bool IgnoreTerrorModifiers;

    /// <summary>
    /// На какой доле дальности оружия юнит прекращает сближение и удерживает позицию.
    /// Меньше единицы, чтобы цель не выпадала из радиуса от любого шага в сторону.
    /// В .toml — ключ <c>approach_hold</c>.
    ///
    /// Значение здесь — только запас для определения без предка и без раздела боя. Рабочее
    /// число лежит в <c>/content/units.vars.toml</c> и оттуда достаётся всем подвижным через
    /// base_unit; держим оба одинаковыми, чтобы запас не означал другое поведение.
    /// </summary>
    public float ApproachHoldFraction = 0.89f;

    /// <summary>
    /// Род при выделении рамкой. Выводится компилятором из тега structure и из снабжения
    /// (см. <c>ContentCompiler.SelectionGroupOf</c>), а не задаётся в файле: род — следствие
    /// того, чем сущность является, и расходиться с тегами и инструментами он не должен.
    /// </summary>
    public SelectionGroup SelectionGroup = SelectionGroup.Bots;

    /// <summary>Ствол. Найден компилятором среди инструментов, здесь лежит готовым.</summary>
    public WeaponDefinition Weapon;

    /// <summary>Рабочий инструмент: стройка и/или ремонт.</summary>
    public WorkToolDefinition BuildTool;

    /// <summary>
    /// Явно разрешённые приказы: <c>allow</c> минус <c>deny</c> после слияния base.
    /// Имеет смысл только при <see cref="HasOrderList"/>.
    /// </summary>
    public OrderSet DeclaredOrders = OrderSet.None;

    /// <summary>
    /// Явно запрещённые приказы из <c>deny</c>. В отличие от простого отсутствия в allow,
    /// такой приказ не попадает ни в принятые, ни в мягкий список панели.
    /// </summary>
    public OrderSet DeniedOrders = OrderSet.None;

    /// <summary>В файле была секция <c>[orders]</c> (в том числе с пустым allow или только deny).</summary>
    public bool HasOrderList;

    /// <summary>
    /// Что сущность умеет исполнить по классу и снабжению. Считает компилятор после
    /// связывания инструментов; от объявления в файле не зависит.
    /// </summary>
    public OrderSet ExecutableOrders = OrderSet.None;

    /// <summary>Пересечение объявленного и исполнимого — то, что принимает очередь.</summary>
    public OrderSet AcceptedOrders => DeclaredOrders.Intersect(ExecutableOrders);

    /// <summary>
    /// Исполнимо, но ни разрешено, ни запрещено явно. Панель показывает со звёздочкой;
    /// к исполнению не принимается. Приказы из <see cref="DeniedOrders"/> сюда не входят.
    /// </summary>
    public OrderSet SoftOrders =>
        (HasOrderList ? ExecutableOrders.Except(DeclaredOrders) : ExecutableOrders)
        .Except(DeniedOrders);

    /// <summary>Параметры завода. Заданы только у <see cref="UnitClass.Plant"/>.</summary>
    public PlantDefinition Plant;

    public bool CanBuild => BuildTool is { CanBuild: true };

    /// <summary>Чинит тот, у кого в инструменте есть ремонт — в том числе без права строить.</summary>
    public bool CanRepair => BuildTool is { CanRepair: true };

    /// <summary>Берётся ли строитель за юнитов, а не только за постройки.</summary>
    public bool CanRepairUnits => BuildTool is { RepairsUnits: true };

    /// <summary>
    /// На какое расстояние юнит вообще дотягивается работой. Нужно там, где занятие ещё
    /// не выбрано, — например, безоружному, которому приказали атаковать: подойти он должен
    /// хотя бы на длину того, чем располагает.
    /// </summary>
    public float WorkRangePx => BuildTool?.RangePx ?? Const.Unit;

    /// <summary>
    /// Постройка или подвижная сущность. Выводится из класса, и только из него: тот же
    /// вопрос решает Spawner, выбирая, какой узел поднять, и два ответа обязаны совпадать.
    ///
    /// По форме это определять НЕЛЬЗЯ, хотя соблазн есть. Форма нужна и юниту: его каркас
    /// занимает клетку, пока идёт сборка, иначе на одно место встанет десяток каркасов,
    /// да и приказать «достроить вот этот» будет некому — цель под курсором ищется
    /// по занятости сетки. Клетку юнит освобождает, когда собран, а не когда поставлен.
    /// </summary>
    public bool IsStructure => Class is UnitClass.Structure or UnitClass.Factory
        or UnitClass.Turret or UnitClass.Assembler or UnitClass.Plant;

    /// <summary>
    /// Занимает ли сущность место: у каркаса — на время стройки, у постройки — всегда.
    /// Форма задаёт и размер занятого прямоугольника, и сам факт занятости.
    /// </summary>
    public bool Occupies => Rows.Length > 0;

    public bool IsMobile => Speed > 0f;

    /// <summary>
    /// Мощь экспансии с подставленным умолчанием. Считается при обращении, а не при сборке:
    /// умолчание зависит от рода, а род известен только после связывания определения.
    /// </summary>
    public float ExpansionPower => ExpansionPowerWeight ?? (IsStructure ? 1f : 0f);

    /// <summary>Боевая мощь с подставленным умолчанием.</summary>
    public float ArmyPower => ArmyPowerWeight ?? (IsMobile && Weapon != null ? 1f : 0f);

    public int Width => Rows.Length > 0 ? Rows[0].Length : 1;

    public int Height => Rows.Length > 0 ? Rows.Length : 1;

    public Vector2I Size => new(Width, Height);

    public float TurnSpeed => Mathf.DegToRad(TurnSpeedDegrees);

    public float RadiusPx => Radius * Const.Unit;

    public float VisionRadiusPx => VisionRange * Const.Unit;

    /// <summary>
    /// Радиус внимания: докуда сущность отходит от своего якоря ради занятия, выбранного
    /// без приказа, — прикрыть строителя, добить подошедшего, починить соседа.
    ///
    /// РАВЕН ОБЗОРУ И ОТДЕЛЬНЫМ ЧИСЛОМ НЕ ЗАДАЁТСЯ. Внимание есть готовность отреагировать
    /// на то, что сущность видит; заводить для него второе число значило бы позволить
    /// юниту реагировать на то, чего он не видит, либо не реагировать на то, что видит.
    /// Свойство существует ради имени: в местах применения речь идёт именно о внимании,
    /// а не об обзоре, и совпадение чисел там читается как случайное.
    /// </summary>
    public float AttentionRadiusPx => VisionRadiusPx;

    public float SpeedPx => Speed * Const.Unit;

    /// <summary>
    /// Разгон в пикселях. Незаданный выводится из скорости: держать в каждом файле число,
    /// которое всегда вдесятеро больше соседнего, значит заводить лишний повод их рассогласовать.
    /// </summary>
    public float AccelerationPx =>
        (Acceleration > 0f ? Acceleration : Speed * DefaultAccelerationFactor) * Const.Unit;

    /// <summary>
    /// Торможение в пикселях. Отрицательное сохраняется отрицательным: это не число,
    /// а признак мгновенной остановки, и переводить его в пиксели незачем.
    /// </summary>
    public float BrakePx => Brake < 0f ? -1f : Brake * Const.Unit;

    /// <summary>Во сколько раз разгон превышает скорость, когда задан только второй.</summary>
    private const float DefaultAccelerationFactor = 10f;

    /// <summary>Полный объём работы. Меряется металом: мощность строителя — это метал в секунду.</summary>
    public float TotalWork => Assembly?.CostMetal ?? 0f;

    public bool IsGenerator => EnergyProduction > 0f;

    /// <summary>
    /// Сколько прочности даёт единица метала при ремонте. Курс не выдуманный: он выведен
    /// из самой сущности, поэтому починить её с нуля стоит ровно столько же, сколько
    /// построить, и занимает столько же времени — инструмент-то один и тот же.
    ///
    /// Ноль означает «ремонту не подлежит»: у сущности без цены курса быть не может.
    /// Коммандеру цена задана ради одного этого курса — построить его всё равно негде,
    /// ни в одной панели он не значится.
    /// </summary>
    public float HealthPerMetal => TotalWork > 0f ? MaxHealth / TotalWork : 0f;

    public bool CanBeRepaired => HealthPerMetal > 0f;

    /// <summary>Прочность каркаса на время стройки.</summary>
    public float FrameHealth => Assembly?.FrameHealth ?? 100f;
}
