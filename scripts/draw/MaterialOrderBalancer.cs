using System.Collections.Generic;
using Godot;

/// <summary>
/// Балансировщик порядка отрисовки: раздаёт картинкам номера уровней <c>z</c> так, чтобы
/// одинаковые оказались на общем уровне и сложились в один вызов отрисовки, а заданный
/// порядок наложения при этом сохранился.
///
/// ЧТО ИЗМЕРЕНО И ЗАЧЕМ ЭТО НУЖНО. Godot складывает соседние двумерные картинки в один вызов,
/// пока у них совпадают вещество, текстура и фильтр; расхождение любого из трёх обрывает
/// объединение. Стенд из двухсот пар картинок: всё совпадает — один вызов на четыреста
/// картинок; различаются текстуры, либо фильтры, либо вещества — четыреста вызовов; те же
/// различающиеся картинки, разведённые по двум уровням <c>z</c>, — снова два вызова.
///
/// Отсюда задача. Общего вещества мало: нужно ещё, чтобы одинаковые картинки шли в очереди
/// команд ПОДРЯД. Сервер отрисовки строит очередь по уровням <c>z</c> для всего холста сразу
/// — сперва весь нижний уровень, затем следующий, — а внутри уровня идёт порядок дерева.
/// Поэтому картинки, сгруппированные вокруг своего владельца, чередуются: тень, корпус, тень,
/// корпус, и объединение обрывается на каждом переходе. Разложи их по уровням — и очередь
/// станет «все тени, все корпуса», то есть двумя вызовами на любое число владельцев.
///
/// ВХОД — ТРЕБОВАНИЯ К ПОРЯДКУ. Каждое требование есть последовательность ключей, взаимный
/// порядок которых обязан сохраниться: что стоит раньше, то и рисуется ниже. Откуда взялись
/// последовательности, балансировщику безразлично; его дело — согласовать их между собой.
///
/// ВЫХОД — НОМЕР УРОВНЯ НА КАЖДЫЙ КЛЮЧ, согласованный со всеми требованиями сразу. Один ключ
/// получает ровно один уровень, поэтому одинаковые картинки из РАЗНЫХ требований ложатся
/// на общий уровень и складываются между собой.
///
/// СЧИТАЕТСЯ ЭТО УКЛАДКОЙ ПО ЯРУСАМ, а не простой топологической сортировкой. Ключ есть
/// вершина, соседство внутри требования — ребро, а ярус вершины есть длина НАИБОЛЬШЕГО пути
/// к ней от начала. Ярус и означает глубину картинки: что во всех требованиях стоит первым,
/// лежит на нулевом ярусе, что вторым — на первом, и так далее.
///
/// ЗАЧЕМ ЯРУСЫ. Простая сортировка выдала бы уровни требованиями подряд: сперва все картинки
/// первого требования, затем все картинки второго. Порядок внутри каждого при этом соблюдён,
/// но тень второго вида оказалась бы ВЫШЕ корпуса первого, и машина стояла бы в чужой тени.
/// Ярусы кладут рядом то, что находится на одной глубине: сперва все тени всех видов, затем
/// все корпуса, затем всё, что поверх корпуса.
///
/// РАЗНЫЕ КЛЮЧИ ОДНОГО ЯРУСА ВСЁ РАВНО ПОЛУЧАЮТ РАЗНЫЕ УРОВНИ, идущие подряд. Иначе они
/// чередовались бы внутри общего уровня и объединение бы не работало: ради него всё
/// и затевалось. Ярус, таким образом, задаёт не общий уровень, а соседство.
///
/// ПОЧЕМУ РАСЧЁТОМ, А НЕ ПРАВИЛОМ ПО РОЛИ. Роль картинки — тень, корпус, ствол — порядка
/// не определяет: один владелец кладёт ствол НИЖЕ корпуса, другой выше. Достоверен только
/// сам заданный порядок, и раскладка выводится из него.
///
/// ЭТО ОБЪЕКТ-ВЫЧИСЛИТЕЛЬ. Раскладка целиком определяется поданными требованиями и после
/// сборки не меняется; изменились требования — собирается новый балансировщик. Держать его
/// вправе кто угодно, а результатом вправе пользоваться кто угодно; о моделях, сценах
/// и слоях мира балансировщик не знает ничего.
/// </summary>
public sealed class MaterialOrderBalancer
{
    /// <summary>
    /// Чем картинка отличима от соседки с точки зрения объединения. Ровно три величины,
    /// и все три измерены: расхождение любой обрывает объединение.
    ///
    /// Идентификаторами, а не ссылками: ключ живёт в раскладке всё время её жизни, а держать
    /// ссылку на текстуру значило бы не давать выгрузить ресурс, которым больше никто
    /// не пользуется.
    /// </summary>
    public readonly struct Key : System.IEquatable<Key>
    {
        private readonly ulong _material;
        private readonly ulong _texture;
        private readonly int _filter;

        public Key(Material material, Texture2D texture, CanvasItem.TextureFilterEnum filter)
        {
            _material = material == null ? 0UL : material.GetInstanceId();
            _texture = texture == null ? 0UL : texture.GetInstanceId();
            _filter = (int)filter;
        }

        private Key(ulong single)
        {
            _material = ulong.MaxValue;
            _texture = single;
            _filter = -1;
        }

        /// <summary>
        /// Ключ, не совпадающий ни с одним другим. Нужен тому, что объединять не с чем:
        /// собранной отдельно сцене со своим веществом и своей текстурой. Собственный уровень
        /// такому нужен ради обратного — чтобы оно не разделяло собой уровень картинок,
        /// между которыми стоит.
        ///
        /// <paramref name="id"/> обязан быть постоянным: раскладка должна давать один и тот же
        /// ответ на один и тот же вход.
        /// </summary>
        public static Key Single(ulong id) => new(id);

        public bool Equals(Key other) => _material == other._material
                                         && _texture == other._texture
                                         && _filter == other._filter;

        public override bool Equals(object obj) => obj is Key other && Equals(other);

        public override int GetHashCode() =>
            System.HashCode.Combine(_material, _texture, _filter);
    }

    /// <summary>Ключ → номер уровня.</summary>
    private readonly Dictionary<Key, int> _level;

    /// <summary>Сколько уровней занято. Номера идут подряд от нуля.</summary>
    public int Count => _level.Count;

    /// <summary>
    /// Собрать раскладку по требованиям к порядку.
    ///
    /// <paramref name="capacity"/> — сколько уровней вправе занять ответ. Величина нужна
    /// не расчёту, а проверке: вызывающий кладёт уровни в ограниченный промежуток <c>z</c>,
    /// и о переполнении надо сказать, а не выяснять его по искажённой картинке.
    /// </summary>
    public MaterialOrderBalancer(IEnumerable<IReadOnlyList<Key>> demands, int capacity)
    {
        // Вершины в порядке первой встречи: при равных правах топологическая сортировка
        // обязана давать один и тот же ответ, иначе раскладка плясала бы от порядка требований
        var order = new List<Key>();
        var rank = new Dictionary<Key, int>();
        var after = new Dictionary<Key, HashSet<Key>>();
        var debt = new Dictionary<Key, int>();

        foreach (var demand in demands)
        {
            Key previous = default;
            bool has = false;

            foreach (var key in demand)
            {
                if (!debt.ContainsKey(key))
                {
                    rank[key] = order.Count;
                    order.Add(key);
                    after[key] = new HashSet<Key>();
                    debt[key] = 0;
                }

                // Соседство внутри требования и есть предписание порядка. Повтор ключа подряд
                // предписанием не является: одинаковые картинки ложатся на общий уровень
                // и сохраняют взаимный порядок деревом
                if (has && !previous.Equals(key) && after[previous].Add(key))
                    debt[key]++;

                previous = key;
                has = true;
            }
        }

        // Ярус вершины: длина наибольшего пути к ней от начала. Считается по ходу обхода,
        // и это законно ровно потому, что вершина берётся лишь после всех своих предков
        var tier = new Dictionary<Key, int>(order.Count);
        var settled = new List<Key>(order.Count);
        var ready = new List<Key>();

        foreach (var key in order)
        {
            tier[key] = 0;

            if (debt[key] == 0)
                ready.Add(key);
        }

        while (ready.Count > 0)
        {
            // Из готовых берётся встреченный раньше: ответ не должен зависеть от того,
            // в каком порядке вершины освобождались
            int pick = 0;

            for (int i = 1; i < ready.Count; i++)
                if (rank[ready[i]] < rank[ready[pick]])
                    pick = i;

            var key = ready[pick];
            ready.RemoveAt(pick);
            settled.Add(key);

            foreach (var later in after[key])
            {
                if (tier[later] < tier[key] + 1)
                    tier[later] = tier[key] + 1;

                if (--debt[later] == 0)
                    ready.Add(later);
            }
        }

        if (settled.Count < order.Count)
        {
            // Круг означает, что два требования предписывают противоположный порядок одной
            // и той же паре ключей. Разорвать его без произвола нельзя, поэтому оставшиеся
            // кладутся поверх всего в порядке встречи: объединение сохраняется, а порядок
            // наложения в одном из требований расходится с заданным
            GD.PushWarning("[MaterialOrderBalancer] требования предписывают противоположный " +
                           "порядок одним и тем же картинкам; часть порядка наложения " +
                           "не соблюдена");

            int last = 0;

            foreach (var value in tier.Values)
                last = Mathf.Max(last, value);

            foreach (var key in order)
                if (!settled.Contains(key))
                {
                    tier[key] = last + 1;
                    settled.Add(key);
                }
        }

        // Уровни раздаются по ярусам, а внутри яруса — в порядке встречи. Ключи одного яруса
        // получают разные уровни, идущие подряд: общий уровень свёл бы их в чередование
        // и отменил объединение
        settled.Sort((a, b) => tier[a] != tier[b]
            ? tier[a].CompareTo(tier[b])
            : rank[a].CompareTo(rank[b]));

        _level = new Dictionary<Key, int>(settled.Count);

        for (int i = 0; i < settled.Count; i++)
            _level[settled[i]] = i;

        if (_level.Count > capacity)
            GD.PushWarning($"[MaterialOrderBalancer] уровней {_level.Count} при промежутке " +
                           $"в {capacity}: часть картинок выйдет за отведённые пределы");
    }

    /// <summary>
    /// Номер уровня ключа. Ноль у ключа, которого в раскладке нет: картинка нарисуется
    /// у нижнего края промежутка, но не пропадёт.
    /// </summary>
    public int Level(in Key key) => _level.TryGetValue(key, out int z) ? z : 0;
}
