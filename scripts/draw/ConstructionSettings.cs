using Godot;

/// <summary>
/// Настройка вида каркаса строящейся постройки. Подсистема графики; отрисовкой заведует
/// шейдер <c>construction.gdshader</c>, а <see cref="Blueprint"/> подставляет ему долю
/// готовности и признак того, работает ли кто-нибудь над каркасом.
///
/// ЧТО ИЗОБРАЖАЕТСЯ. Спрайт разделён по высоте уровнем готовности: ниже уровня видна
/// полупрозрачная проекция корпуса, выше — сетка одного цвета, а по самому уровню идёт
/// светлая полоса фронта. Линии сетки проходят через обе части, поэтому конструкция
/// сохраняет общий эффект до завершения. Приём взят из Planetary Annihilation, где шейдер
/// <c>prelight_pa_unit_fab</c>
/// строит модель снизу вверх по <c>build_fraction</c>, отсекая всё выше уровня и подсвечивая
/// границу отдельным цветом.
///
/// ЧЕМ ОТЛИЧАЕТСЯ ПРОСТОЙ КАРКАС ОТ СТРОЯЩЕГОСЯ. Каркас, к которому никто не подключён,
/// рисуется тем же шейдером, но без движения: волнение уровня и бег полос умножаются на
/// признак активности, и при нуле остаётся неподвижная сетка. Так по одному взгляду видно,
/// идёт ли работа, и при этом каркас не превращается в другой объект.
/// </summary>
[Tool]
[GlobalClass]
public partial class ConstructionSettings : Resource
{
    [ExportGroup("Отображение")]

    /// <summary>
    /// Применять ли шейдер к каркасам. Выключение возвращает прежний вид — спрайт,
    /// непрозрачность которого растёт с готовностью.
    /// </summary>
    [Export] public bool Enabled = true;

    [ExportGroup("Цвета")]

    /// <summary>Цвет недостроенной части. Альфа задаёт её плотность.</summary>
    [Export] public Color Wire = new(0.35f, 0.75f, 1f, 0.3f);

    /// <summary>
    /// Цвет полосы фронта — того уровня, до которого постройка доведена. Альфа задаёт,
    /// насколько полоса перекрывает то, что под ней.
    /// </summary>
    [Export] public Color Edge = new(0.75f, 0.95f, 1f, 0.9f);

    /// <summary>Непрозрачность уже проявленной части конструкции.</summary>
    [Export(PropertyHint.Range, "0,1,0.01")] public float BuiltOpacity = 0.72f;

    [ExportGroup("Фронт")]

    /// <summary>Ширина полосы фронта, доля высоты спрайта.</summary>
    [Export(PropertyHint.Range, "0,0.3,0.005")] public float EdgeWidth = 0.05f;

    [ExportGroup("Сетка")]

    /// <summary>Число полос сетки по высоте спрайта.</summary>
    [Export(PropertyHint.Range, "0,64,1")] public float ScanCount = 18f;

    /// <summary>Сила линий сетки на недостроенной и уже проявленной частях.</summary>
    [Export(PropertyHint.Range, "0,1,0.01")] public float ScanStrength = 0.45f;

    /// <summary>Скорость бега полос. Действует только при активной работе.</summary>
    [Export(PropertyHint.Range, "0,20,0.1")] public float ScanSpeed = 3f;

    [ExportGroup("Волнение")]

    /// <summary>
    /// Размах колебания уровня фронта, доля высоты спрайта. Действует только при активной
    /// работе: у каркаса, к которому никто не подключён, уровень стоит ровно.
    /// </summary>
    [Export(PropertyHint.Range, "0,0.2,0.001")] public float WaveAmplitude = 0.02f;

    /// <summary>Частота колебания уровня вдоль ширины спрайта, периодов на всю ширину.</summary>
    [Export(PropertyHint.Range, "0,20,0.1")] public float WaveFrequency = 5f;

    /// <summary>Скорость колебания уровня.</summary>
    [Export(PropertyHint.Range, "0,20,0.1")] public float WaveSpeed = 2.5f;

    /// <summary>
    /// За сколько секунд признак активности доходит от нуля до единицы и обратно. Резкая
    /// смена выглядела бы рывком, поскольку строитель подключается и отключается мгновенно.
    /// </summary>
    [Export(PropertyHint.Range, "0.01,2,0.01")] public float ActivityFade = 0.35f;
}
