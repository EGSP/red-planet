using Godot;

/// <summary>
/// Настройка запечённого затенения спрайтов: контактной тени под корпусом и затемнения по
/// внутренней кайме. Подсистема графики; поведение описано в <see cref="SpriteOcclusion"/>.
///
/// ПОЧЕМУ ДОЛИ, А НЕ ПИКСЕЛИ. Радиус размытия и отход тени заданы долями меньшей стороны
/// спрайта: изображения имеют разное разрешение, и постоянная в пикселях дала бы у крупного
/// спрайта вдвое более узкую тень.
///
/// ПРАВКА ПОЛЕЙ ПЕРЕСОБИРАЕТ ИЗОБРАЖЕНИЯ. Слои считаются один раз и лежат в кэше, поэтому
/// <see cref="SpriteOcclusion"/> сверяет слепок этих полей с тем, при котором пёк, и при
/// расхождении чистит кэш. Отсюда правка в отладочной панели видна сразу.
/// </summary>
[Tool]
[GlobalClass]
public partial class SpriteOcclusionSettings : Resource
{
    [ExportGroup("Отображение")]

    /// <summary>Рисовать ли контактную тень под корпусом.</summary>
    [Export] public bool ContactEnabled = true;

    /// <summary>Рисовать ли затемнение по внутренней кайме силуэта.</summary>
    [Export] public bool RimEnabled = true;

    [ExportGroup("Общее")]

    /// <summary>
    /// Цвет затенения. Не чистый чёрный: на охристом грунте чёрная тень выглядит провалом,
    /// а слегка холодный тёмный тон читается как затенённая поверхность. Альфа поля не
    /// используется — плотность задают <see cref="ContactOpacity"/> и <see cref="RimOpacity"/>.
    /// </summary>
    [Export] public Color Shade = new(0.05f, 0.04f, 0.07f);

    /// <summary>
    /// Во сколько раз изображение слоя подробнее исходного спрайта.
    ///
    /// Слои рисуются тем же узлом, что и корпус, а фильтр текстур есть свойство узла: ради
    /// резкости пиксельного рисунка там стоит ближайший сосед, и размытая тень при нём
    /// распалась бы на ступени. Подробность запекания и решает эту задачу — ступень
    /// приходится на долю пикселя корпуса. Больше четырёх обычно не требуется.
    /// </summary>
    [Export(PropertyHint.Range, "1,8,1")] public int Upscale = 4;

    [ExportGroup("Контактная тень")]

    /// <summary>Непрозрачность тени вплотную к корпусу.</summary>
    [Export(PropertyHint.Range, "0,1,0.01")] public float ContactOpacity = 0.8f;

    /// <summary>Радиус размытия, доля меньшей стороны спрайта.</summary>
    [Export(PropertyHint.Range, "0,0.3,0.005")] public float ContactBlur = 0.08f;

    /// <summary>Отход тени от центра корпуса, доля меньшей стороны спрайта.</summary>
    [Export(PropertyHint.Range, "0,0.3,0.005")] public float ContactOffset = 0.07f;

    /// <summary>
    /// Направление отхода тени в градусах, отсчитывается от оси +X по часовой стрелке
    /// (ось Y в координатах канвы направлена вниз). Значение около 60 означает свет сверху
    /// и слева, отчего тень уходит вниз и вправо.
    ///
    /// Направление мировое, а не в осях корпуса: свет падает на всю карту одинаково, и у
    /// повёрнутой постройки тень обязана уходить в ту же сторону, что и у неповёрнутой.
    /// </summary>
    [Export(PropertyHint.Range, "0,360,1")] public float ContactAngleDegrees = 59.5f;

    [ExportGroup("Затемнение по кайме")]

    /// <summary>Непрозрачность затемнения на самом краю силуэта.</summary>
    [Export(PropertyHint.Range, "0,1,0.01")] public float RimOpacity = 0.55f;

    /// <summary>Ширина полосы затемнения, доля меньшей стороны спрайта.</summary>
    [Export(PropertyHint.Range, "0,0.3,0.005")] public float RimBlur = 0.06f;

    /// <summary>
    /// Слепок полей, влияющих на запекание. Признаки отображения сюда не входят: они гасят
    /// готовый слой при отрисовке и пересчёта не требуют.
    /// </summary>
    public (Color, int, float, float, float, float, float) BakeKey =>
        (Shade, Upscale, ContactOpacity, ContactBlur, ContactOffset, RimOpacity, RimBlur);
}
