using Godot;

/// <summary>
/// Запись служебной графики в множественные сетки. Собственной работы у системы нет: она
/// задаёт лишь тот миг, когда объявленные за кадр фигуры уходят в буферы.
///
/// ПОЧЕМУ СИСТЕМОЙ, А НЕ УЗЛОМ СО СВОИМ _Process. Запись обязана идти после того, как все
/// владельцы фигур этого кадра высказались, иначе часть графики отстанет на кадр. Порядок
/// задаёт планировщик, а неявный обход дерева нод его не даёт. По той же причине системой
/// сделан <see cref="HealthBarSystem"/>.
///
/// ЗАЧЕМ БОЛЬШОЙ <see cref="GameSystem.StepOrder"/>. Внутри фазы порядок задан этим числом,
/// и запись должна идти последней среди всех, кто объявляет фигуры. Запас взят с избытком,
/// чтобы новая система показа не оказалась случайно позже записи.
/// </summary>
public partial class ShapeMeshSystem : GameSystem
{
    public ShapeMeshSystem()
    {
        // Показ, а не изменение мира: графика ведётся в графическом цикле после ввода
        // и перемещений этого кадра
        Phase = Phase.React;
        UpdateCycle = UpdateCycle.Process;
        StepOrder = 1000;
    }

    public override void Step(double dt) => ShapeMesh.Flush();

    /// <summary>
    /// Сессия уходит вместе со своими узлами, а приёмник фигур статический и переживает её.
    /// Поэтому ссылки на сетки сбрасываются здесь: иначе следующая сессия писала бы
    /// в снесённые узлы.
    /// </summary>
    public override void _ExitTree()
    {
        base._ExitTree();
        ShapeMesh.Forget();
    }
}
