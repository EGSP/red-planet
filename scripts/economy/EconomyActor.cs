/// <summary>
/// Участник экономики: всё, что производит или потребляет ресурсы — генератор, месторождение,
/// каркас, синтезатор металла, да и сам коммандер.
///
/// Кадр всегда идёт в два прохода, и это не церемония, а необходимость: разделить поток
/// между потребителями можно, только зная общий спрос заранее. Сначала все объявляют,
/// сколько хотят, потом узнают общую производительность и работают с ней.
/// </summary>
public interface IEconomyActor
{
    /// <summary>Первый проход: заявить своё производство и потребление, единиц в секунду.</summary>
    void Declare(EconomyLedger ledger);

    /// <summary>
    /// Второй проход: отработать тик с уже известными долями по ресурсам.
    ///
    /// Актор сам выбирает, что из них его касается: тому, кто тратит и метал, и энергию,
    /// нужен темп по худшему (<see cref="EconomyRates.Work"/>), а тому, кто метал только
    /// производит, нехватка метала не помеха.
    /// </summary>
    void Run(double dt, EconomyRates rates);
}
