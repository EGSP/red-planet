using Godot;

/// <summary>
/// Покрытие базового слоя: тайлящаяся текстура и условия, на которых она проявляется.
///
/// СОБСТВЕННОГО ПОЛЯ ШУМА У ПОКРЫТИЯ НЕТ. Поле объявлено на местности целиком, а покрытие
/// лишь занимает на нём отрезок. Иначе покрытия перестали бы делить одну карту и наложились
/// бы друг на друга случайным образом, вместо того чтобы сменять одно другое.
///
/// ТЕМПЕРАТУРА СУЖАЕТ ОБЛАСТЬ БИОМА. Покрытие и так проявляется только в отрезке своего
/// биома; собственный отрезок температуры дополнительно вырезает из него кусок — тем же
/// приёмом, что у декали. Отрезок во всю ширину означает отсутствие дополнительного
/// ограничения.
///
/// ПОРЯДОК СПИСКА ЕСТЬ ПОРЯДОК НАЛОЖЕНИЯ. Покрытия собираются в общий список в порядке
/// биомов местности, а внутри биома — в порядке <see cref="SurfaceBiome.Tiles"/>, и каждое
/// следующее ложится поверх уже собранного цвета. Отсюда правило для художника: где отрезки
/// двух покрытий пересекаются, виднó то, что стоит в списке позже. Разводить отрезки ради
/// того, чтобы одно покрытие перекрыло другое, больше не нужно — достаточно переставить их
/// местами.
///
/// ПЕРВОЕ ПОКРЫТИЕ СПИСКА — ПОДЛОЖКА. Оно кроет область целиком, и собственные отрезки на
/// него не действуют: под ним ничего нет, проявляться ему не на чем. Отсюда пустого места на
/// поверхности не бывает при любых настройках прочих покрытий, а отрезки первого покрытия
/// имеет смысл оставлять раскрытыми во всю ширину, чтобы не вводить в заблуждение.
///
/// ШИРИНА ПЕРЕХОДА ЗАДАНА НА МЕСТНОСТИ. Все отрезки покрытия смягчаются общим для местности
/// <see cref="SurfaceSettings.Smoothness"/>: объявленная граница есть середина перехода, где
/// покрытие проявлено наполовину. Собственного размытия у покрытия нет — почему, изложено
/// при самой настройке.
/// </summary>
[Tool]
[GlobalClass]
public partial class SurfaceTile : Resource
{
    /// <summary>Имя для чтения в инспекторе. На отрисовку не влияет.</summary>
    [Export] public string Id = "";

    /// <summary>
    /// Участвует ли покрытие в базовом слое. Выключенное покрытие не занимает одного из
    /// четырёх мест, которые разбирает шейдер, поэтому им можно временно освободить место
    /// под примерку другого. Отрезок значений при этом остаётся никем не занятым, и там,
    /// где не проявилось ни одно покрытие, шейдер берёт первое включённое.
    /// </summary>
    [Export] public bool Enabled = true;

    /// <summary>Бесшовная текстура покрытия.</summary>
    [Export] public Texture2D Texture;

    /// <summary>Сторона одного повторения текстуры в пикселях мира.</summary>
    [Export(PropertyHint.Range, "64,2048,8")] public float SizePx = 512f;

    /// <summary>
    /// Отрезок значений шума, на котором покрытие проявляется: X — начало, Y — конец.
    /// Граница отрезка есть середина перехода шириной
    /// <see cref="SurfaceSettings.Smoothness"/>. Граница, совпадающая с краем шкалы (ноль
    /// слева, единица справа), ограничением не считается вовсе.
    /// </summary>
    [Export] public Vector2 Range = new(0f, 1f);

    /// <summary>
    /// Отрезок температуры. Сужает область биома, а не расширяет её. Отрезок во всю ширину
    /// означает отсутствие дополнительного ограничения.
    /// </summary>
    [Export] public Vector2 TemperatureRange = new(0f, 1f);

    /// <summary>
    /// Отрезок высот, на котором покрытие допускается. Действует только при заданном поле
    /// высот; отрезок во всю ширину означает отсутствие ограничения.
    /// </summary>
    [Export] public Vector2 HeightRange = new(0f, 1f);

    /// <summary>Оттенок, которым домножается текстура.</summary>
    [Export] public Color Tint = Colors.White;
}
