using Godot;

/// <summary>
/// Покрытие базового слоя: тайлящаяся текстура и диапазон, на котором она проявляется.
///
/// СОБСТВЕННОГО ПОЛЯ ШУМА У ПОКРЫТИЯ НЕТ. Поле объявлено на слое целиком, а покрытие лишь
/// занимает на нём отрезок. Иначе покрытия перестали бы делить одну карту и наложились бы
/// друг на друга случайным образом, вместо того чтобы сменять одно другое.
///
/// ДИАПАЗОНЫ ДОЛЖНЫ ПОКРЫВАТЬ ОТРЕЗОК ОТ НУЛЯ ДО ЕДИНИЦЫ. Там, где не проявилось ни одно
/// покрытие, шейдер берёт первое из списка: пустого места на поверхности быть не должно.
/// </summary>
[Tool]
[GlobalClass]
public partial class SurfaceTile : Resource
{
    /// <summary>Имя для чтения в инспекторе. На отрисовку не влияет.</summary>
    [Export] public string Id = "";

    /// <summary>
    /// Участвует ли покрытие в базовом слое. Выключенное покрытие не занимает одного из
    /// четырёх мест, которые разбирает шейдер, поэтому им можно временно освободить место
    /// под примерку другого. Отрезок значений при этом остаётся никем не занятым, и там,
    /// где не проявилось ни одно покрытие, шейдер берёт первое включённое.
    /// </summary>
    [Export] public bool Enabled = true;

    /// <summary>Бесшовная текстура покрытия.</summary>
    [Export] public Texture2D Texture;

    /// <summary>Сторона одного повторения текстуры в пикселях мира.</summary>
    [Export(PropertyHint.Range, "64,2048,8")] public float SizePx = 512f;

    /// <summary>Отрезок значений шума, на котором покрытие проявляется: X — начало, Y — конец.</summary>
    [Export] public Vector2 Range = new(0f, 1f);

    /// <summary>Ширина перехода по обе стороны отрезка. Ноль даёт резкую границу.</summary>
    [Export(PropertyHint.Range, "0,0.5,0.005")] public float Falloff = 0.08f;

    /// <summary>
    /// Отрезок высот, на котором покрытие допускается. Действует только при заданном поле
    /// высот; отрезок во всю ширину означает отсутствие ограничения.
    /// </summary>
    [Export] public Vector2 HeightRange = new(0f, 1f);

    /// <summary>Оттенок, которым домножается текстура.</summary>
    [Export] public Color Tint = Colors.White;
}
