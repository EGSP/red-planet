using Godot;

/// <summary>
/// Декаль поверхности: отпечаток, который раскладывается при создании мира и дальше не
/// меняется. Камни, трещины, песчаные наносы.
///
/// ПОЧЕМУ ПЛОТНОСТЬ ЗАДАНА ДВУМЯ ЧИСЛАМИ. Шаг решётки кандидатов отвечает за наименьшее
/// расстояние между отпечатками, то есть за то, слипаются они или нет; доля принимаемых
/// кандидатов — за то, насколько густо заполнена подходящая область. Одним числом это не
/// выражается: разрежённая россыпь крупных камней и плотная сыпь мелких дают одинаковую
/// долю покрытия при совершенно разном виде.
///
/// РАЗМЕР И ШАГ ЗАДАНЫ ДОЛЕЙ ОБЛАСТИ, А НЕ ПИКСЕЛЯМИ МИРА. Так же выражены величины
/// температуры (<see cref="SurfaceSettings.IsothermWidth"/> и соседние), и по той же
/// причине: замысел местности состоит в том, как выглядит карта целиком, а сторона арены
/// выводится из настроек мира и меняется вместе с ними. При долях число отпечатков и
/// рисунок сыпи от стороны арены не зависят вовсе — решётка кандидатов всегда даёт одно и
/// то же количество клеток; при пикселях увеличение арены вчетверо давало вчетверо больше
/// мелких отпечатков и совершенно иной вид той же местности.
///
/// СЛЕДСТВИЕ, О КОТОРОМ СЛЕДУЕТ ПОМНИТЬ. Отпечаток на большой арене крупнее в пикселях
/// мира, то есть крупнее относительно машин, размер которых задан в клетках. Пропорция
/// «камень к танку» тем самым перестаёт быть постоянной; постоянной становится пропорция
/// «камень к карте».
///
/// ПОЧЕМУ ГРАНИЦЫ КОЛИЧЕСТВА НЕ ЗАМЕНЯЮТ ПЛОТНОСТЬ. Шаг решётки и доля принимаемых
/// кандидатов задают, как отпечатки распределены; границы количества — сколько их вышло.
/// Одно из другого не выводится: то же число отпечатков получается и редкой сыпью по всей
/// карте, и плотной кучей в углу, где условия совпали. Поэтому границы приложены поверх
/// раскладки, а не вместо неё: они прореживают избыток и добирают недостачу, не меняя
/// правил, по которым выбрано место.
///
/// ПОЧЕМУ НОМЕР СЛОЯ, А НЕ ПОРЯДОК В СПИСКЕ. Порядок наложения должен быть выражен явно,
/// иначе перестановка строк в инспекторе молча меняет вид карты. Номер слоя заодно
/// объединяет декали разных биомов: песок ложится под трещины независимо от того,
/// в каком биоме они объявлены.
///
/// УСЛОВИЯ РАЗМЕЩЕНИЯ ЧИТАЮТСЯ ТЕМ ЖЕ ПРАВИЛОМ, ЧТО И УСЛОВИЯ ПОКРЫТИЯ. Отрезки шума,
/// температуры и высоты вместе с отрезком температуры биома дают долю от нуля до единицы,
/// смягчённую общим для местности <see cref="SurfaceSettings.Smoothness"/>, и доля эта
/// служит вероятностью принять кандидата. Отсюда рваный, а не отрезанный по линии край у
/// каждого условия, а не только у границы биома, как было прежде. Порог здесь неуместен по
/// существу: отдельный отпечаток либо поставлен, либо нет, и постепенность у слоя декалей
/// достижима только прореживанием.
/// </summary>
[Tool]
[GlobalClass]
public partial class SurfaceDecal : Resource
{
    /// <summary>Имя для чтения в инспекторе.</summary>
    [Export] public string Id = "";

    /// <summary>
    /// Участвует ли декаль в раскладке. Раскладка прочих декалей от снятой галки не
    /// меняется: зерно каждой выведено из её порядкового номера, а номер присваивается
    /// и выключенным тоже.
    /// </summary>
    [Export] public bool Enabled = true;

    /// <summary>Изображение отпечатка. Берётся диффузная карта: освещения в двумерии нет.</summary>
    [Export] public Texture2D Texture;

    /// <summary>Порядок наложения: меньший номер лежит ниже.</summary>
    [Export(PropertyHint.Range, "0,23,1")] public int Layer;

    /// <summary>
    /// Поле шума, по которому отбираются места. Не назначено — отбор идёт только по
    /// температуре и высоте.
    /// </summary>
    [Export] public NoiseSettings Noise;

    /// <summary>
    /// Отрезок значений шума, на котором отпечаток допускается. Граница отрезка есть
    /// середина перехода шириной <see cref="SurfaceSettings.Smoothness"/>, у которой
    /// принимается половина кандидатов; граница, совпадающая с краем шкалы, ограничением
    /// не считается.
    /// </summary>
    [Export] public Vector2 NoiseRange = new(0f, 1f);

    /// <summary>Отрезок температуры. Сужает область биома, а не расширяет её.</summary>
    [Export] public Vector2 TemperatureRange = new(0f, 1f);

    /// <summary>Отрезок высоты. Действует только при заданном поле высот.</summary>
    [Export] public Vector2 HeightRange = new(0f, 1f);

    /// <summary>
    /// Шаг решётки кандидатов, долей большей стороны области: наименьший интервал между
    /// отпечатками. Обратная величина есть число клеток по стороне, поэтому 0.02 означает
    /// пятьдесят возможных мест по каждой стороне карты независимо от её размера.
    /// </summary>
    [Export(PropertyHint.Range, "0.005,0.5,0.0001")] public float Spacing = 0.025f;

    /// <summary>Доля кандидатов, принимаемых после проверки условий.</summary>
    [Export(PropertyHint.Range, "0,1,0.01")] public float Chance = 0.5f;

    /// <summary>
    /// Наименьшее число отпечатков. Ноль снимает нижнюю границу. Если правила дали меньше,
    /// недостача добирается из кандидатов, отвергнутых розыгрышем, — но не из тех, что не
    /// прошли отрезки шума, температуры и высоты: условия размещения границы количества не
    /// отменяют, поэтому больше, чем пригодных мест, отпечатков не появится.
    ///
    /// Совпадение с <see cref="CountMax"/> выключает правило целиком: обе границы тогда не
    /// проверяются, и раскладка остаётся такой, какой её дали условия размещения.
    /// </summary>
    [Export(PropertyHint.Range, "0,20000,1")] public int CountMin;

    /// <summary>
    /// Наибольшее число отпечатков. Ноль снимает верхнюю границу, совпадение с
    /// <see cref="CountMin"/> выключает правило целиком. Излишек прореживается по всей
    /// области равномерно, а не отсекается с одного края.
    /// </summary>
    [Export(PropertyHint.Range, "0,20000,1")] public int CountMax;

    /// <summary>Разброс положения внутри клетки решётки, долей шага.</summary>
    [Export(PropertyHint.Range, "0,1,0.01")] public float Jitter = 0.7f;

    /// <summary>Сторона отпечатка, долей большей стороны области.</summary>
    [Export(PropertyHint.Range, "0.002,0.5,0.0001")] public float Size = 0.019f;

    /// <summary>Относительное отклонение размера в обе стороны.</summary>
    [Export(PropertyHint.Range, "0,1,0.01")] public float SizeVariation = 0.25f;

    /// <summary>Случайный поворот. Снят — отпечатки лежат одинаково, что видно как повтор.</summary>
    [Export] public bool RandomRotation = true;

    /// <summary>
    /// Общий оттенок отпечатка вместе с его непрозрачностью: альфа оттенка и есть
    /// непрозрачность, отдельной настройки для неё нет.
    ///
    /// ПОЧЕМУ ОТДЕЛЬНАЯ НЕПРОЗРАЧНОСТЬ УБРАНА. Прежнее поле Opacity умножалось на альфу
    /// оттенка, то есть оба числа сходились в одно, и по инспектору нельзя было понять,
    /// каким из них задана прозрачность отпечатка.
    ///
    /// ЗНАЧЕНИЕ НИЖЕ ЕДИНИЦЫ ДЕЛАЕТ ОТПЕЧАТОК ПРОСВЕЧИВАЮЩИМ ЦЕЛИКОМ. Наложенные друг на
    /// друга полупрозрачные отпечатки складываются в более плотное пятно, поэтому мягкие
    /// края следует держать в альфа-канале самого изображения, а альфу оттенка оставлять
    /// единичной всюду, где отпечаток задуман кроющим.
    /// </summary>
    [Export] public Color Tint = Colors.White;

    /// <summary>
    /// Разброс яркости оттенка: разрушает узнаваемость одного и того же изображения.
    /// Трогает только цвет, но не альфу — иначе разброс менял бы и плотность наложения.
    /// </summary>
    [Export(PropertyHint.Range, "0,1,0.01")] public float TintVariation = 0.08f;
}
