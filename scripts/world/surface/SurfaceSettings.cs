using Godot;

/// <summary>Откуда берётся температура.</summary>
public enum TemperatureSource
{
    /// <summary>
    /// Знаковое расстояние до дуги, пересекающей карту. Обобщает два прежних источника:
    /// нулевая кривизна даёт прямую границу (прежний линейный источник, подобие широты),
    /// большая — окружности вокруг точки высадки (прежний радиальный).
    /// </summary>
    Isotherm = 0,

    /// <summary>Из собственного поля шума: пятна вместо правильного перехода.</summary>
    Noise = 1,
}

/// <summary>
/// Местность целиком: общее поле шума базового слоя, карты температуры и высоты, набор
/// биомов с покрытиями и декалями, вид облаков. Один ресурс — одна разновидность
/// поверхности («пустошь», «лава», «земля»).
///
/// ПОЧЕМУ ЧЕТЫРЕ ПОКРЫТИЯ, А НЕ СКОЛЬКО УГОДНО. Покрытия объявлены в биомах, но шейдер
/// разбирает их общим списком развёрнутым кодом: выбирать текстуру по вычисляемому номеру
/// в языке шейдеров нельзя. Четырёх достаточно: при большем числе переходы становятся
/// неразличимы, а стоимость выборок растёт линейно.
///
/// ЗЕРНО ЗДЕСЬ НЕ ХРАНИТСЯ. Оно принадлежит партии и берётся из
/// <see cref="WorldSettings.Seed"/>: описание местности задаёт правила, а зерно —
/// их конкретное разрешение. Иначе две партии на одной местности были бы неотличимы.
/// </summary>
[Tool]
[GlobalClass]
public partial class SurfaceSettings : Resource
{
    /// <summary>Наибольшее число покрытий базового слоя, которое разбирает шейдер.</summary>
    public const int MaxTiles = 4;

    private TemperatureSource _temperature = TemperatureSource.Isotherm;

    /// <summary>Имя для чтения в инспекторе.</summary>
    [Export] public string Id = "";

    // ── Базовый слой ──────────────────────────────────────────────────────────────

    [ExportGroup("Базовый слой")]

    /// <summary>Поле, по которому базовый слой делится между покрытиями.</summary>
    [Export] public NoiseSettings BaseNoise;

    /// <summary>
    /// Показать базовый шум поверх местности: чёрно-белая карта с полупрозрачностью.
    /// Нужна при подборе <see cref="BaseNoise"/>, чтобы видеть поле без смены покрытия.
    /// В партии игнорируется.
    /// </summary>
    [Export] public bool ShowNoise;

    /// <summary>
    /// Гексагональная укладка: текстура читается трижды со случайным смещением по узлам
    /// треугольной решётки и смешивается по барицентрическим весам. Устраняет видимый
    /// повтор ценой трёх выборок вместо одной, поэтому вынесена в переключатель.
    /// </summary>
    [Export] public bool HexTiling = true;

    /// <summary>
    /// Ширина перехода у всех границ местности, в долях шкалы поля. Одним числом смягчаются
    /// отрезки покрытий (<see cref="SurfaceTile.Range"/>,
    /// <see cref="SurfaceTile.TemperatureRange"/>, <see cref="SurfaceTile.HeightRange"/>),
    /// отрезки декалей (<see cref="SurfaceDecal.NoiseRange"/>,
    /// <see cref="SurfaceDecal.TemperatureRange"/>, <see cref="SurfaceDecal.HeightRange"/>) и
    /// отрезок температуры биома в обоих слоях. Ноль даёт границу, проведённую точно по линии
    /// уровня поля.
    ///
    /// ПОЧЕМУ ОДНО ЧИСЛО НА МЕСТНОСТЬ, А НЕ ПО ОДНОМУ НА ПОКРЫТИЕ. Переход принадлежит стыку
    /// двух покрытий, а не одному из них, поэтому два соседа с разной шириной задают одному
    /// стыку два несовместимых значения, и согласовать их нельзя ни при каком правиле
    /// разрешения: чей бы номер ни был выбран, настройка второго соседа перестаёт что-либо
    /// значить. Прежде такие числа были у покрытия и у биома сразу, отчего одна и та же
    /// граница управлялась то одним из них, то другим, в зависимости от того, каким условием
    /// она задана.
    ///
    /// ПОЧЕМУ ЗНАЧЕНИЕ ВЫРАЖЕНО В ДОЛЯХ ШКАЛЫ, А НЕ В ПИКСЕЛЯХ. Ширина полосы на экране есть
    /// частное от деления этой величины на быстроту изменения поля, а быстрота у полей разная:
    /// базовый шум меняется часто, температура — на всю карту один раз. Отсюда одно и то же
    /// число даёт узкую полосу на стыке покрытий и широкую на стыке биомов, что и требуется.
    /// </summary>
    [Export(PropertyHint.Range, "0,0.3,0.005")] public float Smoothness = 0.06f;

    /// <summary>Общий оттенок поверхности поверх всех покрытий.</summary>
    [Export] public Color Ambient = Colors.White;

    // ── Температура ───────────────────────────────────────────────────────────────

    [ExportGroup("Температура")]

    /// <summary>Откуда берётся температура. При смене список настроек перестраивается.</summary>
    [Export]
    public TemperatureSource Temperature
    {
        get => _temperature;
        set
        {
            _temperature = value;
            NotifyPropertyListChanged();
        }
    }

    /// <summary>
    /// Наибольший изгиб изотермы: конкретное значение разыгрывается от зерна партии в
    /// пределах от минус заданного до плюс заданного, отчего выгнутая и вогнутая стороны
    /// выпадают одинаково часто. Величина безразмерная — это отношение большей стороны
    /// области к радиусу дуги, поэтому одно и то же число даёт одинаковый на вид изгиб при
    /// любом размере арены. Ноль оставляет границу прямой во всех партиях, значения до 0.3
    /// от прямой неотличимы, а свыше четырёх дуга замыкается в пределах карты и источник
    /// вырождается в кольцевой.
    ///
    /// ПОЧЕМУ РАЗМАХ, А НЕ САМО ЗНАЧЕНИЕ. Определённый изгиб настраивать незачем: замысел
    /// местности выражается тем, насколько сильно граница может изогнуться, а не тем, куда
    /// именно она изогнётся в отдельной партии. То же относится к <see cref="IsothermOffset"/>.
    ///
    /// Направление, в котором растёт температура, не настраивается вовсе: оно разыгрывается
    /// на полный оборот. Ограничивать его нечем — у карты нет ни верха, ни сторон света.
    /// </summary>
    [Export(PropertyHint.Range, "0,12,0.1")] public float IsothermCurvature = 3f;

    /// <summary>
    /// Ширина перехода — расстояние, на котором температура проходит весь отрезок от нуля
    /// до единицы, в долях большей стороны области. Единица означает, что переход растянут
    /// на всю карту; меньшие значения сужают полосу смешения биомов, отчего края шкалы
    /// занимают заметную площадь, большие — оставляют в игре только середину шкалы.
    ///
    /// В отличие от изгиба и смещения, здесь задаётся само значение: доля площади, отходящая
    /// каждому биому, есть часть замысла местности, а не то, что стоит отдавать зерну.
    /// </summary>
    [Export(PropertyHint.Range, "0.2,4,0.05")] public float IsothermWidth = 0.9f;

    /// <summary>
    /// Насколько ширина перехода отходит от заданной, в долях её самой. Ноль означает, что
    /// все партии на этой местности получают в точности назначенную ширину, половина — что
    /// ширина выпадает в пределах от половины заданной до полутора.
    /// </summary>
    [Export(PropertyHint.Range, "0,1,0.01")] public float IsothermWidthVariation = 0.25f;

    /// <summary>
    /// Наибольшее смещение изотермы от центра карты вдоль направления роста, в долях большей
    /// стороны области; сторона смещения разыгрывается вместе с величиной. Ноль проводит дугу
    /// через центр во всех партиях, отчего обе половины шкалы занимают равную площадь.
    /// Предел узкий намеренно: уведённая за край карты дуга оставила бы всю арену в одном
    /// биоме, и подобранные отрезки температуры биомов перестали бы работать.
    /// </summary>
    [Export(PropertyHint.Range, "0,0.35,0.01")] public float IsothermOffset = 0.15f;

    /// <summary>
    /// Сила искажения области, в долях большей стороны области. Точка перед вычислением
    /// расстояния сдвигается по векторному полю шума, отчего правильная дуга превращается
    /// в изрезанную линию с выступами и вкраплениями одного биома внутри другого, а общая
    /// закономерность сохраняется. Ноль выключает приём, и граница остаётся правильной
    /// кривой, которая читается как проведённая линия.
    /// </summary>
    [Export(PropertyHint.Range, "0,0.5,0.005")] public float TemperatureWarp = 0.07f;

    /// <summary>Поле, которым ведётся искажение. Не назначено — берётся базовое.</summary>
    [Export] public NoiseSettings TemperatureWarpNoise;

    /// <summary>Поле температуры при шумовом источнике.</summary>
    [Export] public NoiseSettings TemperatureNoise;

    /// <summary>
    /// Показать итоговую температуру поверх местности: синий (холодно) → красный (жарко),
    /// с полупрозрачностью. Отражает то же поле, по которому отбираются биомы.
    /// В партии игнорируется.
    /// </summary>
    [Export] public bool ShowTemperature;

    // ── Высота ────────────────────────────────────────────────────────────────────

    [ExportGroup("Высота")]

    /// <summary>
    /// Поле высот. На вид поверхности само по себе не влияет и рельефа не создаёт:
    /// служит дополнительным условием отбора покрытий и декалей, у которых сужен
    /// соответствующий отрезок. Не назначено — условия по высоте не проверяются.
    /// </summary>
    [Export] public NoiseSettings HeightNoise;

    /// <summary>
    /// Показать поле высот поверх местности: зелёный (низ) → розовый (верх),
    /// с полупрозрачностью. Без <see cref="HeightNoise"/> переключатель ничего не даёт.
    /// В партии игнорируется.
    /// </summary>
    [Export] public bool ShowHeight;

    // ── Биомы ─────────────────────────────────────────────────────────────────────

    [ExportGroup("Биомы")]

    /// <summary>
    /// Биомы местности: каждый несёт свои покрытия и декали. Пересечение отрезков
    /// температуры допустимо.
    /// </summary>
    [Export] public SurfaceBiome[] Biomes = System.Array.Empty<SurfaceBiome>();

    // ── Облака ────────────────────────────────────────────────────────────────────

    [ExportGroup("Облака")]

    /// <summary>
    /// Вид облаков над местностью: цвет, форма, ветер. Ответ на зум камеры лежит внутри
    /// этого ресурса отдельной ссылкой (<see cref="CloudSettings.ZoomFade"/>) и может
    /// шариться между местностями. Не назначены — <see cref="CloudRenderer"/> оставляет
    /// свои прежние настройки.
    /// </summary>
    [Export] public CloudSettings Clouds;

    /// <summary>
    /// Принадлежность значения отрезку с переходом шириной <paramref name="smoothness"/>.
    /// Единственное описание этого правила на стороне C#: по нему считают покрытие пикселя
    /// декали (<see cref="SurfaceLayout"/>) и подпись стенда шумов, а шейдер поверхности
    /// повторяет его же на своём языке. Держать правило в одном месте необходимо потому, что
    /// расхождение хотя бы в одном слагаемом развело бы базовый слой и декали по границам,
    /// проведённым в разных местах одного поля.
    ///
    /// ПЕРЕХОД ПОЛОЖЕН ПОСЕРЕДИНЕ ОБЪЯВЛЕННОЙ ГРАНИЦЫ. На самой границе значение равно
    /// половине, поэтому изменение ширины перехода не сдвигает отрезок.
    ///
    /// ГРАНИЦА, СОВПАДАЮЩАЯ С КРАЕМ ШКАЛЫ, ОГРАНИЧЕНИЕМ НЕ СЧИТАЕТСЯ. Отрезок во всю ширину
    /// означает отсутствие условия; будь край шкалы обыкновенной границей, принадлежность
    /// убывала бы у нуля и единицы, где убывать ей не от чего.
    /// </summary>
    public static float Band(float value, Vector2 range, float smoothness)
    {
        float low = Mathf.Min(range.X, range.Y);
        float high = Mathf.Max(range.X, range.Y);
        float s = Mathf.Max(smoothness, 0.0001f);

        float from = low > 0f ? Mathf.SmoothStep(low - s, low + s, value) : 1f;
        float to = high < 1f ? 1f - Mathf.SmoothStep(high - s, high + s, value) : 1f;

        return from * to;
    }

    /// <summary>Скрыть настройки температуры, не относящиеся к выбранному источнику.</summary>
    public override void _ValidateProperty(Godot.Collections.Dictionary property)
    {
        string name = property["name"].AsString();

        bool isotherm = Temperature == TemperatureSource.Isotherm;

        bool hide = name switch
        {
            nameof(IsothermCurvature) or nameof(IsothermWidth) or
            nameof(IsothermWidthVariation) or nameof(IsothermOffset) or
            nameof(TemperatureWarp) or nameof(TemperatureWarpNoise) => !isotherm,
            nameof(TemperatureNoise) => isotherm,
            _ => false,
        };

        if (hide)
            property["usage"] = (int)PropertyUsageFlags.NoEditor;
    }
}
