using Godot;

/// <summary>
/// Биом: область местности, отобранная по температуре, и её покрытия с декалями.
///
/// ПОЧЕМУ ПОКРЫТИЯ ЖИВУТ ЗДЕСЬ, А НЕ НА МЕСТНОСТИ. Биом отвечает за то, из чего поверхность
/// сделана и чем усыпана в своём отрезке температуры. Покрытия делят общее поле шума
/// местности, но проявляются только там, где биом принят: так устроено и в Planetary
/// Annihilation, где подбиом даёт тайлящуюся текстуру и список декалей.
/// </summary>
[Tool]
[GlobalClass]
public partial class SurfaceBiome : Resource
{
    /// <summary>Имя для чтения в инспекторе.</summary>
    [Export] public string Id = "";

    /// <summary>
    /// Участвует ли биом в раскладке. Снятая галка убирает все его покрытия и декали разом,
    /// не удаляя самого биома из списка: подбор ведётся сравнением, и вернуть набор нужно
    /// тем же движением, каким он выключен. Раскладка прочих биомов при этом не смещается.
    /// </summary>
    [Export] public bool Enabled = true;

    /// <summary>
    /// Отрезок температуры, на котором биом появляется. Служит условием и покрытиям, и
    /// декалям биома; края смягчает общий для местности
    /// <see cref="SurfaceSettings.Smoothness"/>.
    ///
    /// СОБСТВЕННОГО РАЗМЫТИЯ У БИОМА НЕТ. Прежде оно задавалось отдельным числом Falloff и
    /// описывало ту же ширину перехода, что и настройка местности, отчего одна и та же
    /// граница управлялась то одним числом, то другим, смотря каким условием она задана.
    /// </summary>
    [Export] public Vector2 TemperatureRange = new(0f, 1f);

    /// <summary>
    /// Покрытия базового слоя, свойственные этому биому. Порядок значим: покрытия местности
    /// собираются в общий список в порядке биомов, а внутри биома — в этом порядке, и каждое
    /// следующее накладывается поверх предыдущих. Первое среди всех включённых покрытий
    /// местности служит подложкой и кроет область целиком.
    /// </summary>
    [Export] public SurfaceTile[] Tiles = System.Array.Empty<SurfaceTile>();

    /// <summary>Декали, свойственные этому биому.</summary>
    [Export] public SurfaceDecal[] Decals = System.Array.Empty<SurfaceDecal>();
}
