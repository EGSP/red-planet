using Godot;

/// <summary>
/// Ответ облаков на приближение камеры: ужатие доли зума, кривые непрозрачности тени и
/// тела, скорость сближения текущих множителей с целевыми.
///
/// ПОЧЕМУ ОТДЕЛЬНЫЙ РЕСУРС. Вид облаков (цвет, форма, ветер) зависит от местности и потому
/// живёт в <see cref="CloudSettings"/>. Поведение по камере одно и то же для разных видов:
/// игрок крутит колесо одинаково, и кривые ответа не должны копироваться в каждый файл
/// облаков. Отсюда общая ссылка: несколько <see cref="CloudSettings"/> указывают на один
/// <see cref="CloudZoomFade"/>.
///
/// ЧЕГО ЗДЕСЬ НЕТ. Текущие множители непрозрачности (ShadeAmount / BodyAmount) живут на
/// <see cref="CloudRenderer"/>: их пишет сигнал зума камеры и каждый кадр тянет к цели.
/// </summary>
[Tool]
[GlobalClass]
public partial class CloudZoomFade : Resource
{
    /// <summary>
    /// Ужатие краёв диапазона зума перед кривыми. Ноль — доля камеры идёт как есть. При 0.2
    /// значения зума ниже пятой части и выше четырёх пятых считаются крайними, а оставшаяся
    /// середина растягивается на полный отрезок: игрок редко доводит зум до упоров, и без
    /// ужатия облака почти не меняются в обычном диапазоне игры.
    /// </summary>
    [Export(PropertyHint.Range, "0,0.45,0.01")] public float ZoomSqueeze = 0.2f;

    /// <summary>
    /// Кривая тени: вход — доля зума после <see cref="ZoomSqueeze"/>, выход — множитель
    /// непрозрачности тени. Ею задаётся, на каком участке приближения тень появляется и
    /// гаснет. Не задана — выход равен входу.
    /// </summary>
    [Export] public Curve ShadeCurve;

    /// <summary>
    /// Кривая тела облака. Устройство то же, что у <see cref="ShadeCurve"/>: после ужатия
    /// зума по кривой выбирается множитель непрозрачности тела.
    /// </summary>
    [Export] public Curve BodyCurve;

    /// <summary>
    /// Скорость сближения текущих множителей непрозрачности с целевыми от зума:
    /// <c>Lerp(current, target, LerpFactor * delta)</c>. Ноль — мгновенная подстановка
    /// цели; большие значения — более резкий переход. Нужна затем, чтобы тень и тело
    /// проявлялись и гасли плавно при кручении колеса, а не скачком на каждый шаг зума.
    /// </summary>
    [Export(PropertyHint.Range, "0,20,0.1")] public float LerpFactor = 6f;
}
