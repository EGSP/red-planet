using System;
using Godot;

/// <summary>
/// Место работы: то, на что можно отдать приказ строить.
///
/// ЗАЧЕМ ПРИЗНАК ШИРЕ, ЧЕМ <see cref="WorkNode"/>. Мест работы теперь два рода, и требуют
/// они разного. Каркас требует МОЩНОСТИ: исполнитель подключается к нему инструментом,
/// а ресурсы двигает сам узел по суммарному потоку. План требует ПРИСУТСТВИЯ: ни метала,
/// ни энергии он не потребляет, ему нужно, чтобы исполнитель дошёл и поставил каркас.
///
/// Общего у них ровно то, что записано здесь: место в мире, признак незаконченности,
/// способность быть целью приказа и объявление о собственной смене.
/// Всё остальное — частность, и подключение мощности остаётся у <see cref="WorkNode"/>,
/// а не поднимается сюда ради единообразия.
/// </summary>
public interface IWorkSite
{
    int Id { get; }

    Vector2 GlobalPosition { get; }

    /// <summary>Нужна ли ещё работа — по этому признаку и ищут себе занятие.</summary>
    bool NeedsWork { get; }

    /// <summary>
    /// Место работы сменилось другим: план стал каркасом. Приказ, нацеленный сюда,
    /// переводит цель на преемника сам (см. <see cref="Order.Target"/>).
    ///
    /// ЗАЧЕМ ОБЪЯВЛЕНИЕ, А НЕ ПОИСК. Связь «приказ — место работы» была односторонней:
    /// приказ помнил цель, а цель о нацеленных на неё приказах не знала ничего. Найти их
    /// можно было только перебором всех веток приказов через индекс, а индекс впускает
    /// новых членов на границе кадра, и ветка, заведённая щелчком, до ближайшей уборки
    /// в переборе не участвовала: приказ на каркас молча терялся у того исполнителя,
    /// которому не пришлось никуда идти. Подписка на объявление и есть та обратная связь,
    /// которой не хватало, — искать больше не требуется, а момент срабатывания не значит
    /// ничего.
    /// </summary>
    event Action<IWorkSite> Superseded;
}
