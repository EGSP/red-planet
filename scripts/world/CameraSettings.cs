using Godot;

/// <summary>
/// Настройка камеры: скорость панорамирования и пределы зума.
///
/// ПОЧЕМУ РЕСУРС. Те же основания, что у CloudSettings и FogSettings: подбор ведётся в одном
/// файле и подхватывается сценой партии, а не размазывается по полям узла в Session.tscn.
/// </summary>
[Tool]
[GlobalClass]
public partial class CameraSettings : Resource
{
    [ExportGroup("Панорамирование")]

    /// <summary>Скорость сдвига камеры по границам экрана, пикселей в секунду при зуме 1.</summary>
    [Export(PropertyHint.Range, "100,2000,10")] public float PanSpeed = 700f;

    /// <summary>
    /// Ширина полосы у края окна, в которой курсор двигает камеру, пиксели.
    ///
    /// Число подбирается: узкая полоса требует прицеливаться в самый край, широкая
    /// начинает сдвигать камеру там, где игрок ещё работает с интерфейсом. Поэтому оно
    /// и вынесено в ресурс, а не записано в коде.
    /// </summary>
    [Export(PropertyHint.Range, "4,120,1")] public float EdgePanMarginPx = 24f;

    [ExportGroup("Зум")]

    /// <summary>Множитель зума на один шаг колеса. Больше единица — крупнее шаг.</summary>
    [Export(PropertyHint.Range, "1.01,1.5,0.01")] public float ZoomStep = 1.12f;

    /// <summary>
    /// Зум при полном отдалении. Он же наименьшее из допустимых значений: чем меньше зум,
    /// тем больше видно, — поэтому упоры названы по тому, что игрок видит на экране,
    /// а не по величине числа.
    /// </summary>
    [Export(PropertyHint.Range, "0.05,2,0.01")] public float ZoomFar = 0.25f;

    /// <summary>Зум при полном приближении. Он же наибольшее из допустимых значений.</summary>
    [Export(PropertyHint.Range, "0.1,4,0.01")] public float ZoomNear = 2.5f;

    /// <summary>
    /// Ступени зума долями отдаления: ноль отвечает <see cref="ZoomNear"/> (камера у земли,
    /// видно меньше всего), единица — <see cref="ZoomFar"/> (камера отведена дальше всего,
    /// видно больше всего). Клавиши приближения и отдаления переводят камеру на соседнюю
    /// ступень.
    ///
    /// ДОЛЯ СЧИТАЕТСЯ ОТ ОТДАЛЕНИЯ, А НЕ ОТ ПРИБЛИЖЕНИЯ. Внутри камеры отсчёт обратный
    /// (единица означает наибольший зум), но здесь настройку читает и правит человек,
    /// а не расчёт: доля отдаления совпадает с высотой отметки на шкале зума в углу экрана
    /// и с обиходным «отдалить на сто процентов». Обращение делает <c>CameraRig.Rungs</c>,
    /// и оно же единственное место, где два отсчёта встречаются.
    ///
    /// ДОЛЯ, А НЕ САМО ЗНАЧЕНИЕ ЗУМА, потому что упоры подбираются под размер карты
    /// и меняются; ступени, заданные долями, переживают такую правку без пересчёта.
    /// Отрезок логарифмический — тот же, по которому считается <c>CameraRig.ZoomFactor</c>,
    /// поскольку зум умножается на шаг, а не сдвигается на постоянную величину.
    ///
    /// Порядок значений в массиве безразличен: соседняя ступень ищется перебором.
    ///
    /// УПОРЫ ЗАПИСЫВАЮТСЯ НАРАВНЕ С ПРОЧИМИ СТУПЕНЯМИ и сами собой в перечень
    /// не добавляются: пока ноль и единица не записаны, клавиши до соответствующего упора
    /// не доводят и он достаётся только колесу. Отсюда следует, что число записей здесь
    /// равно числу положений, между которыми ходят клавиши, и сосчитать их можно,
    /// не заглядывая в код.
    /// </summary>
    [Export] public float[] ZoomSteps = { 0f, 0.25f, 0.5f, 0.75f, 1f };

    /// <summary>
    /// Допуск примыкания к ступени долей промежутка между соседними ступенями. Зум,
    /// отстоящий от ступени не далее этой доли, считается стоящим на ней, и клавиша
    /// переводит камеру на следующую, а не притягивает к ближайшей.
    ///
    /// ЗАЧЕМ ОН НУЖЕН. Колесом игрок задаёт произвольное значение и обыкновенно
    /// останавливается неподалёку от ступени. Без допуска первое нажатие тратилось бы
    /// на притягивание к ней, изменение оказывалось бы едва заметным, и отдалить камеру
    /// удавалось бы только со второго нажатия.
    ///
    /// Доля промежутка, а не доля всего отрезка между упорами: ступени расставляются
    /// неравномерно, и допуск, отмеренный от отрезка, поглотил бы частые ступени целиком.
    /// Ноль означает, что примыкания нет вовсе и первое нажатие приводит камеру
    /// на ближайшую ступень.
    /// </summary>
    [Export(PropertyHint.Range, "0,0.5,0.01")] public float ZoomStepTolerance = 0.2f;

    /// <summary>
    /// Быстрота, с которой зум догоняет ступень, заданную клавишей, в долях расхождения
    /// за секунду. Ноль означает мгновенный переход без сглаживания.
    ///
    /// Зума колесом это не касается: колесо задаёт произвольное значение малыми шагами
    /// и применяет их сразу.
    ///
    /// Отдельного признака включения сглаживания нет: мгновенная смена есть предельный
    /// случай той же величины, и два поля вместо одного допускали бы несогласованные
    /// сочетания вроде выключенного сглаживания при заданной быстроте.
    /// </summary>
    [Export(PropertyHint.Range, "0,40,0.5")] public float ZoomLerpSpeed = 16f;
}
