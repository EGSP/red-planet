using Godot;

/// <summary>
/// Настройка облаков: форма, ход ветра и две цветовые шкалы — для тени на земле и для
/// самого облака.
///
/// ПОЧЕМУ ГРАДИЕНТЫ, А НЕ НАБОР ЧИСЕЛ. Порог появления облака, мягкость его края, плотность
/// и цвет — это одна кривая, и правится она целиком, на глаз. Ресурс <see cref="Gradient"/>
/// показывается в инспекторе полосой с перетаскиваемыми точками, причём альфа входит в цвет
/// точки, поэтому отдельных полей прозрачности и мягкости не нужно. Основания те же, по
/// которым градиентом задана <see cref="ShadowSettings.Tint"/>.
///
/// ПОЧЕМУ ШКАЛЫ ДВЕ. Тень и тело облака выводятся из одного поля плотности, но подчиняются
/// разным соображениям: тень должна читаться, не мешая различать постройки, а тело —
/// оставаться лёгким. Незаданная шкала означает, что слой не рисуется вовсе. Текущие
/// множители непрозрачности (ShadeAmount / BodyAmount) живут на CloudRenderer: их пишет
/// сигнал зума камеры. Ужатие и кривые ответа на зум — здесь, в общем ресурсе настроек.
///
/// ПОЧЕМУ ТЕНЬ НЕ ЧЁРНАЯ. Облачная тень в природе есть смена прямого освещения рассеянным,
/// то есть смещение цвета в холодную сторону при падении насыщенности, а не убавление
/// яркости. Умножение на чёрный поверх охристой поверхности даёт бурый цвет, которого нет
/// в палитре игры нигде, и местность выглядит запачканной. Отсюда холодный оттенок шкалы
/// по умолчанию.
///
/// ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО. Облака не влияют ни на видимость, ни на проходимость, ни на
/// дальность стрельбы: они целиком принадлежат виду. Иначе их положение пришлось бы
/// выводить из зерна партии и держать на стороне симуляции — цена, несоизмеримая с
/// украшением.
/// </summary>
[Tool]
[GlobalClass]
public partial class CloudSettings : Resource
{
    [ExportGroup("Отображение")]

    /// <summary>Показывать ли облака.</summary>
    [Export] public bool Enabled = true;

    [ExportGroup("Вид")]

    /// <summary>
    /// Цвет тени облака на земле. Левый край шкалы отвечает краю облака, правый — его ядру;
    /// альфа задаёт плотность. Незаданная шкала означает, что тень не рисуется.
    ///
    /// Плотность выше четверти начинает мешать различать постройки и юнитов, а для игры
    /// со стратегическим обзором это дефект, а не стиль.
    /// </summary>
    [Export] public Gradient Shade = DefaultShade();

    /// <summary>
    /// Цвет самого облака. Шкала устроена так же, как <see cref="Shade"/>: край облака
    /// слева, ядро справа. Незаданная шкала означает, что тела облаков не видно и остаётся
    /// одна тень.
    /// </summary>
    [Export] public Gradient Body = DefaultBody();

    /// <summary>
    /// Смещение тела облака относительно его тени, пикселей. Задаёт кажущуюся высоту
    /// облачного слоя и направление освещения разом.
    /// </summary>
    [Export] public Vector2 LiftPx = new(56f, 72f);

    [ExportGroup("Прозрачность от зума")]

    /// <summary>
    /// Ужатие краёв диапазона зума перед кривыми. Ноль — доля камеры идёт как есть. При 0.2
    /// значения зума ниже пятой части и выше четырёх пятых считаются крайними, а оставшаяся
    /// середина растягивается на полный отрезок: игрок редко доводит зум до упоров, и без
    /// ужатия облака почти не меняются в обычном диапазоне игры.
    /// </summary>
    [Export(PropertyHint.Range, "0,0.45,0.01")] public float ZoomSqueeze = 0.2f;

    /// <summary>
    /// Кривая тени: вход — доля зума после <see cref="ZoomSqueeze"/>, выход — множитель
    /// непрозрачности тени. Ею задаётся, на каком участке приближения тень появляется и
    /// гаснет. Не задана — выход равен входу.
    /// </summary>
    [Export] public Curve ShadeCurve;

    /// <summary>
    /// Кривая тела облака. Устройство то же, что у <see cref="ShadeCurve"/>: после ужатия
    /// зума по кривой выбирается множитель непрозрачности тела.
    /// </summary>
    [Export] public Curve BodyCurve;

    /// <summary>
    /// Скорость сближения текущих множителей непрозрачности с целевыми от зума:
    /// <c>Lerp(current, target, LerpFactor * delta)</c>. Ноль — мгновенная подстановка
    /// цели; большие значения — более резкий переход. Нужна затем, чтобы тень и тело
    /// проявлялись и гасли плавно при кручении колеса, а не скачком на каждый шаг зума.
    /// </summary>
    [Export(PropertyHint.Range, "0,20,0.1")] public float LerpFactor = 6f;

    [ExportGroup("Форма")]

    /// <summary>
    /// Насколько небо закрыто облаками. Величина задаёт порог, ниже которого поле плотности
    /// облаком не считается, поэтому она приблизительна: распределение шума не равномерно,
    /// и доля закрашенной площади выходит несколько меньше самого числа. Подбирается она
    /// на глаз, и точное соответствие здесь не требуется.
    ///
    /// Сплошная облачность неотличима от общего потемнения карты и лишь съедает контраст,
    /// поэтому осмысленные значения лежат в пределах от пятой части до половины.
    /// </summary>
    [Export(PropertyHint.Range, "0,1,0.01")] public float Coverage = 0.32f;

    /// <summary>
    /// Насколько мелкий слой шума выгрызает край крупного. Ноль оставляет гладкие пятна,
    /// большие значения дают рваный контур и разрывают облака на клочья.
    /// </summary>
    [Export(PropertyHint.Range, "0,1,0.01")] public float Erosion = 0.35f;

    /// <summary>
    /// Базовый размер пятна плотности в мировых пикселях. Больше значение — крупнее облака.
    /// Оси дополнительно масштабируются через <see cref="ScaleX"/> и <see cref="ScaleY"/>.
    /// </summary>
    [Export(PropertyHint.Range, "128,4096,16")] public float Zoom = 1400f;

    /// <summary>
    /// Масштаб вдоль ветра относительно <see cref="Zoom"/>. Единица даёт кучевые пятна,
    /// три и более — перистые волокна по ходу ветра.
    /// </summary>
    [Export(PropertyHint.Range, "0.1,8,0.1")] public float ScaleX = 3.2f;

    /// <summary>Масштаб поперёк ветра относительно <see cref="Zoom"/>.</summary>
    [Export(PropertyHint.Range, "0.1,8,0.1")] public float ScaleY = 1f;

    [ExportGroup("Ветер")]

    /// <summary>Направление ветра, градусов.</summary>
    [Export(PropertyHint.Range, "0,360,1")] public float WindDegrees = 24f;

    /// <summary>
    /// Скорость ветра, пикселей в секунду. Движение в поле зрения притягивает внимание,
    /// а оно принадлежит бою, поэтому ориентир — облако пересекает экран за время порядка
    /// минуты.
    /// </summary>
    [Export(PropertyHint.Range, "0,120,0.5")] public float WindSpeedPx = 14f;

    [ExportGroup("Источник плотности")]

    /// <summary>
    /// Нарисованная бесшовная карта плотности. Не задана — берётся процедурный шум по
    /// зерну <see cref="Seed"/>.
    ///
    /// Разделение оставлено затем, чтобы форму облаков можно было задать рисунком, а не
    /// шумом: у шума нет узнаваемых очертаний, и облака из него выходят безликими.
    /// Шейдеру источник безразличен, поэтому замена не требует правки кода.
    /// </summary>
    [Export] public Texture2D Texture;

    /// <summary>Зерно процедурного шума. Действует, только когда <see cref="Texture"/> не задана.</summary>
    [Export] public int Seed = 1;

    /// <summary>Направление ветра единичным вектором.</summary>
    public Vector2 WindDirection
    {
        get
        {
            var dir = Vector2.Right.Rotated(Mathf.DegToRad(WindDegrees));
            return dir.IsZeroApprox() ? Vector2.Right : dir.Normalized();
        }
    }

    /// <summary>
    /// Шкала тени по умолчанию: холодный полупрозрачный оттенок, сходящий на нет к краю
    /// облака. Нужна затем, чтобы ресурс, созданный в инспекторе с нуля, сразу что-то рисовал.
    /// </summary>
    private static Gradient DefaultShade()
    {
        var gradient = new Gradient();

        gradient.SetOffset(0, 0f);
        gradient.SetColor(0, new Color(0.17f, 0.21f, 0.31f, 0f));
        gradient.SetOffset(1, 1f);
        gradient.SetColor(1, new Color(0.17f, 0.21f, 0.31f, 0.2f));

        return gradient;
    }

    /// <summary>Шкала облака по умолчанию: светлая холодная дымка, прозрачная по краю.</summary>
    private static Gradient DefaultBody()
    {
        var gradient = new Gradient();

        gradient.SetOffset(0, 0f);
        gradient.SetColor(0, new Color(0.85f, 0.87f, 0.94f, 0f));
        gradient.SetOffset(1, 1f);
        gradient.SetColor(1, new Color(0.85f, 0.87f, 0.94f, 0.14f));

        return gradient;
    }
}
