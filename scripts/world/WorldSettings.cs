using Godot;

/// <summary>
/// Настройка мира: раскладка точек метала и выведенный из неё радиус появления противника.
///
/// ПОЧЕМУ ЭТО ПЕРЕЕХАЛО ИЗ <see cref="Const"/> В РЕСУРС. Разделение прежнее — по способу
/// настройки. Величины, которые подбираются глазом на карте, должны правиться там, где
/// карта видна, то есть в инспекторе рядом с предпросмотром. Числа же, от которых зависит
/// размер массивов растра навигации, остались константами: <see cref="NavGrid.Width"/>
/// объявлено как const, и менять размер мира ползунком нельзя без пересборки.
///
/// СИД ЗАДАЁТСЯ ЯВНО. Раньше раскладка бралась от случайного сида и повторить её было
/// нечем, из-за чего разбор неудачной карты сводился к пересказу. Ноль означает «взять
/// случайный», любое другое значение делает раскладку воспроизводимой — и та же раскладка
/// показывается предпросмотром в редакторе.
/// </summary>
[Tool]
[GlobalClass]
public partial class WorldSettings : Resource
{
    // ── Размер поля ───────────────────────────────────────────────────────────────

    [ExportGroup("Размер поля")]

    /// <summary>
    /// Клеток застройки от центра до края. Мир — квадрат со стороной в удвоенное значение
    /// плюс одна клетка, с центром в точке высадки.
    ///
    /// От этого числа выводится размер растра навигации, поэтому менять его по ходу партии
    /// нельзя: <see cref="NavGrid"/> пересоздаёт свои массивы при изменении, но пути,
    /// посчитанные до того, остались бы в старых координатах. Между партиями и в редакторе
    /// правится свободно.
    /// </summary>
    [Export(PropertyHint.Range, "8,64,1")] public int RadiusCells = 20;

    // ── Точки метала ──────────────────────────────────────────────────────────────
    //
    // Все точки одинаковы: богатство числом не задаётся, разницу создаёт только положение.
    // До дальней точки дольше идти и труднее её прикрыть — этого достаточно, чтобы вопрос
    // «куда расширяться» имел цену.

    [ExportGroup("Точки метала")]

    /// <summary>Сколько точек метала на карте.</summary>
    [Export] public int SpotCount = 14;

    /// <summary>Дальше этого радиуса точек нет: у самой границы мира их не разместить.</summary>
    [Export] public int FieldRadiusCells = 15;

    /// <summary>Ближе этого радиуса точек нет — иначе они встанут прямо в базу.</summary>
    [Export] public int BaseClearanceCells = 4;

    /// <summary>Наименьшее расстояние между точками, клеток: иначе они собираются в кучу.</summary>
    [Export] public int SpacingCells = 3;

    /// <summary>
    /// Сколько точек гарантированно лежит рядом со стартом. Без гарантии случайная раскладка
    /// иногда оставляет начало вовсе без метала, и партия проиграна ещё до первого решения.
    /// </summary>
    [Export] public int StartCount = 3;

    /// <summary>Радиус, внутри которого раскладываются гарантированные точки.</summary>
    [Export] public int StartRadiusCells = 8;

    /// <summary>Сколько раз пробуем поставить одну точку, прежде чем сдаться.</summary>
    [Export] public int Attempts = 60;

    /// <summary>Сид раскладки. Ноль — случайный на каждую партию.</summary>
    [Export] public ulong Seed;

    // ── Появление противника ──────────────────────────────────────────────────────

    [ExportGroup("Появление противника")]

    /// <summary>
    /// Во сколько раз окружность появления противника дальше поля точек метала.
    ///
    /// Больше единицы намеренно: враги приходят из-за поля, поэтому дальние точки лежат
    /// на линии их подхода, и экстрактор на краю кольца обороняется тяжелее, чем экстрактор
    /// у базы. Величина связывает две системы — сдвинув радиус поля, вы двигаете и линию
    /// подхода, и форму появления волн, которая от неё отсчитывается.
    /// </summary>
    [Export] public float RingFactor = 1.3f;

    /// <summary>Радиус окружности появления противника в пикселях.</summary>
    public float SpawnRadiusPx => FieldRadiusCells * RingFactor * Const.Unit;

    public float FieldRadiusPx => FieldRadiusCells * Const.Unit;

    public float BaseClearancePx => BaseClearanceCells * Const.Unit;

    public float StartRadiusPx => StartRadiusCells * Const.Unit;
}
