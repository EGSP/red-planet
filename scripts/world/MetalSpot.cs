using Godot;

/// <summary>
/// Точка метала — свойство местности, а не запас. Она вечна: не расходуется, не исчезает
/// и не восстанавливается, потому что восстанавливать в ней нечего. Всё, что она делает, —
/// разрешает поставить на своей клетке экстрактор.
///
/// РАНЬШЕ ЭТО БЫЛО МЕСТОРОЖДЕНИЕ (OreDeposit) — узел работы с конечным запасом, к которому
/// подключались копатели. Смена модели преследует две цели сразу. Первая: сделать метал
/// позиционным ресурсом. Пока руда восстанавливалась в кольце вокруг базы, добыча не
/// требовала никуда идти, и пространство не имело ценности. Вторая: убрать из экономики
/// обслуживание. Конечное месторождение с ручной перестановкой копателей расходует
/// внимание игрока, ничего не решая, а внимание в этой игре — главный дефицит.
///
/// Отсюда и то, чем точка НЕ является. Она не узел работы: подключаться к ней некому.
/// Она не участник экономики: метал производит экстрактор, а не земля под ним. Она не
/// препятствие: занятость означает «здесь кто-то стоит», а точка — это сама местность,
/// и на ней ещё предстоит построить. Запрет ставить на неё что попало живёт в правиле
/// постановки (<see cref="Placement.CanPlace"/>), а не в занятости.
/// </summary>
public partial class MetalSpot : Node2D
{
    public int Id { get; private set; }

    public void Init(int id, Vector2 position)
    {
        Id = id;
        Position = position;
    }

    /// <summary>
    /// Рисуется один раз: точка неизменна, и перерисовывать её каждый кадр незачем.
    /// Экстрактор встаёт слоем выше и закрывает её собой — так и задумано, отметка нужна
    /// ровно до тех пор, пока место свободно.
    /// </summary>
    public override void _Draw()
    {
        float half = Const.Unit * 0.5f;

        ShapeDraw.Rect(this, new Rect2(-half, -half, Const.Unit, Const.Unit),
            DrawTheme.Fill(VizKind.Metal, 0.25f));
        ShapeDraw.Circle(this, Vector2.Zero, half * 0.55f, DrawTheme.Fill(VizKind.Metal, 1f));
        ShapeDraw.Circle(this, Vector2.Zero, half * 0.8f,
            DrawTheme.Outline(VizKind.Metal, 2f, WidthMode.Screen, 0.7f), 24);
    }
}
