using Godot;

/// <summary>
/// Настройка тени препятствий: цветовая шкала и ширина полосы затенения.
///
/// ПОЧЕМУ ГРАДИЕНТ, А НЕ НАБОР ЧИСЕЛ. Цвет у края препятствия, цвет на внешней границе,
/// плотность и форма спада — это одна кривая, и правится она целиком, на глаз. Ресурс
/// <see cref="Gradient"/> показывается в инспекторе полосой с перетаскиваемыми точками,
/// причём альфа входит в цвет точки, поэтому отдельного поля прозрачности не нужно.
/// Шейдеру градиент передаётся запечённым в одномерную текстуру и участвует в отрисовке
/// одной выборкой.
///
/// ПОЧЕМУ РЕСУРС, А НЕ ПРИЗНАКИ ОТЛАДКИ. Тень есть часть вида игры, а не выкладка для
/// разбора поведения систем, — те же основания, по которым ресурсом стал
/// <see cref="FogSettings"/>.
/// </summary>
[Tool]
[GlobalClass]
public partial class ShadowSettings : Resource
{
    [ExportGroup("Отображение")]

    /// <summary>Показывать ли тень препятствий.</summary>
    [Export] public bool Enabled = true;

    [ExportGroup("Тень")]

    /// <summary>
    /// Цвет тени по мере удаления от препятствия. Левый край шкалы отвечает точке вплотную
    /// к краю препятствия, правый — внешней границе полосы; альфа задаёт плотность.
    /// Форма спада целиком определяется расстановкой точек, поэтому отдельной кривой нет.
    ///
    /// Плотность вдобавок гасится к границе полосы множителем <see cref="Falloff"/>,
    /// поэтому правый край шкалы можно оставлять непрозрачным: за полосой тени всё равно
    /// не будет.
    /// </summary>
    [Export] public Gradient Tint = Default();

    /// <summary>
    /// Ширина полосы затенения наружу от края препятствия, пикселей.
    ///
    /// Величина меряется тем же свободным местом, что и <see cref="NavGrid.FreeRadius"/>:
    /// на границе полосы вокруг точки помещается круг такого радиуса. Отсюда прямое чтение
    /// картинки — тень заканчивается там, где проходит юнит соответствующего размера.
    ///
    /// Сверху ограничена насыщением chamfer-расстояния (<see cref="MaxWidthPx"/>): дальше
    /// поле расстояний не различает, насколько место открыто, и растягивать по нему градиент
    /// нечего. Отрисовка это ограничение применяет сама, значение поля при этом не портится.
    /// </summary>
    [Export(PropertyHint.Range, "0,64,1")] public float WidthPx = 40f;

    /// <summary>
    /// Сила угасания тени к границе полосы, за которой начинается простор.
    ///
    /// Плотность умножается на <c>(1 − t)</c> в этой степени, где <c>t</c> — доля пройденной
    /// полосы. Ноль оставляет плотность целиком за шкалой <see cref="Tint"/>; единица гасит
    /// её равномерно; большие значения держат тень плотной почти до конца полосы и роняют
    /// её у самого края.
    ///
    /// Множитель нужен потому, что резкое отсечение за порогом даёт границу по ячейкам
    /// растра, а не по геометрии построек, и тень выглядит комковатой.
    /// </summary>
    [Export(PropertyHint.Range, "0,8,0.1")] public float Falloff = 1f;

    /// <summary>
    /// Ступенчатая тень вместо плавной: подача сменяется с <c>shadow.gdshader</c> на
    /// <c>shadow_pixel.gdshader</c>, а фильтрация растра — на «ближайший сосед».
    ///
    /// Ступеней столько, сколько ячеек растра укладывается в <see cref="WidthPx"/>.
    /// Прочие настройки — шкала, ширина, угасание — действуют одинаково в обеих подачах,
    /// поэтому переключатель сравнивает именно язык изображения, а не два разных вида.
    /// </summary>
    [Export] public bool Pixelated;

    /// <summary>
    /// Предельная ширина полосы при текущем <see cref="NavSettings.MaxClearance"/>, пикселей.
    /// При значении 12 и ячейке растра 16 px это 56 px, то есть без малого клетка застройки.
    /// </summary>
    public static float MaxWidthPx
    {
        get
        {
            int saturation = Mathf.Max(NavGrid.Settings?.MaxClearance ?? 12, NavGrid.Straight);
            return (saturation / (float)NavGrid.Straight - 0.5f) * NavGrid.Cell;
        }
    }

    /// <summary>
    /// Шкала по умолчанию: плотная тень у края препятствия, полная прозрачность на границе
    /// полосы. Нужна затем, чтобы ресурс, созданный в инспекторе с нуля, сразу что-то рисовал.
    /// </summary>
    private static Gradient Default()
    {
        var gradient = new Gradient();

        gradient.SetOffset(0, 0f);
        gradient.SetColor(0, new Color(0f, 0f, 0f, 0.35f));
        gradient.SetOffset(1, 1f);
        gradient.SetColor(1, new Color(0f, 0f, 0f, 0f));

        return gradient;
    }
}
