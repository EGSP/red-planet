/// <summary>
/// Тот, у кого есть очередь производства: сам завод (<see cref="Plant"/>) и каркас
/// будущего завода (<see cref="Blueprint"/>).
///
/// ЗАЧЕМ ПРИЗНАК, А НЕ ПРЯМАЯ ССЫЛКА НА ЗАВОД. Очередь производства набирается ещё
/// на этапе каркаса: постройка завода занимает время, и требовать от игрока вернуться
/// к нему после достройки значит терять это время впустую. Строительная панель поэтому
/// спрашивает не «завод ли это», а «есть ли у выделенного очередь производства», и обе
/// стадии постройки отвечают на такой вопрос одинаково.
///
/// Очередь производства — НЕ <see cref="OrderQueue"/>. Приказы (точка сбора, атака)
/// живут в обычной очереди и достаются выпущенным юнитам; состав производства — отдельный
/// список ключей справочника, который игрок набирает кнопками панели.
/// </summary>
public interface IProducer
{
    int Id { get; }

    UnitDefinition Definition { get; }

    /// <summary>
    /// Способна ли сущность производить юнитов вообще. У каркаса ответ зависит от того,
    /// что из него получится: панель производства не должна появляться у каркаса стены
    /// только потому, что у его определения есть строительный раздел.
    /// </summary>
    bool CanProduce { get; }

    /// <summary>Бесконечное производство: очередь не расходуется, а прокручивается.</summary>
    bool Infinite { get; set; }

    /// <summary>
    /// Сколько раз менялся состав очереди или режим. По нему панель обновляет счётчики
    /// на кнопках, не перебирая очередь каждый кадр.
    /// </summary>
    int Revision { get; }

    /// <summary>Сколько экземпляров данного типа заказано всего: и в основной очереди, и срочно.</summary>
    int CountOf(string unitId);

    /// <summary>Сколько экземпляров данного типа заказано срочно, вне основной очереди.</summary>
    int RushCountOf(string unitId);

    /// <summary>
    /// Заказать выпуск. При <paramref name="rush"/> заказ попадает не в основную очередь,
    /// а в отдельный список срочных: он расходуется до опустошения прежде основной очереди
    /// и никогда не прокручивается по кругу, даже когда включён режим повтора.
    /// </summary>
    void Enqueue(string unitId, int count = 1, bool rush = false);

    /// <summary>
    /// Снять заказ. <paramref name="rush"/> выбирает список, из которого снимать: срочный
    /// заказ правится отдельно от основной очереди, иначе снять его было бы нечем.
    /// </summary>
    void Dequeue(string unitId, int count = 1, bool rush = false);
}
